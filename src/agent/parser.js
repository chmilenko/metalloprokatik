const { askAI } = require('./llm')
const { loadMap } = require('./searchMapManager')

async function parseOrder(text) {
  const searchMap = loadMap()

  const prompt = `
Ты помощник менеджера по металлопрокату.
Извлеки список позиций из заявки и верни ТОЛЬКО JSON массив.
Никакого текста до или после JSON. Никаких markdown блоков.

Заявка:
${text}

Используй этот словарь для поискового запроса — если название есть в словаре, используй соответствующий запрос:
${JSON.stringify(searchMap.поисковые_запросы, null, 2)}

Формат каждой позиции:
{
  "название": "человекочитаемое название позиции",
  "поисковый_запрос": "запрос для поиска на mc.ru",
  "параметры": {
    "ду": число или null,
    "диаметр": число или null,
    "стенка": число или null,
    "толщина": число или null,
    "ширина": число или null,
    "длина_листа": число или null,
    "длина": число или null,
    "номер": число или null,
    "марка": "строка или null"
  },
  "количество": число,
  "единица": "т или м или шт или кг"
}

ПРАВИЛА ДЛЯ МАРКИ СТАЛИ ПО УМОЛЧАНИЮ — ВАЖНО:

Если марка стали НЕ указана явно в заявке:
- Горячекатаный металл (г/к, гк, горячекатаный) → марка = "Ст3" (она же Ст1-3пс/сп5)
- Холоднокатаный металл (х/к, хк, холоднокатаный) → марка = "Ст08пс" (она же 08пс, Ст08)
- Если марка указана явно → используй то что написано

ИСКЛЮЧЕНИЕ — Лист рифленый: НЕ проставляй марку по умолчанию (марка=null),
даже если это "рифленый г/к" или подобное. У рифлёного листа на сайте в
колонке "марка" указывается тип рисунка (ромб/чечевица), а не марка стали
— дефолт "Ст3" там никогда не совпадёт и лист не найдётся. Если менеджер
явно указал тип рисунка ("ромб"/"чечевица"/"чечевичный") — впиши его
как есть в марку (например марка="ромб"). Если не указал — марка=null.

Примеры:
- "Лист г/к 6х1500х3000" → марка="Ст3" (г/к без указания марки)
- "Лист х/к 1х1250х2500" → марка="Ст08пс" (х/к без указания марки)
- "Труба г/к 76х8 Ст20" → марка="Ст20" (марка указана явно)
- "Лист г/к 10х1500х6000 09Г2С" → марка="09Г2С" (марка указана явно)
- "Лист рифленый 2.5х1200х2500" → марка=null (рифлёный без указания рисунка)
- "Лист рифленый ромб 3х1200х2400" → марка="ромб" (рисунок указан явно)
- "Трубы электросварные ЭСВ квадратные 100х4" → марка=null (профильные трубы — марка не применяется)

ПРАВИЛА ДЛЯ ПОИСКОВОГО ЗАПРОСА:

1. Трубы круглые:
   - Труба ВГП, труба водогазопроводная → "ВГП"
   - Труба электросварная, э/с труба → "электросварная"
   - Труба бесшовная г/д, горячедеформированная → "трубы горячедеформированные [диаметр]x[стенка]"
   - Труба бесшовная х/д, холоднодеформированная → "трубы холоднодеформированные [диаметр]x[стенка]"
   - Труба нержавеющая круглая → "труба нержавеющая [диаметр]x[стенка]"
   - Труба чугунная → "труба чугунная"

2. Трубы профильные:
   - Если оба размера ОДИНАКОВЫЕ (квадратная) → "Трубы электросварные ЭСВ квадратные [сторона]х[стенка]"
     Пример: 40*40*3 → "Трубы электросварные ЭСВ квадратные 40х3"
     Пример: 100х100х4 → "Трубы электросварные ЭСВ квадратные 100х4"
   - Если размеры РАЗНЫЕ (прямоугольная) → "Трубы электросварные ЭСВ прямоугольные [А]х[Б]х[стенка]"
     Пример: 40*25*3 → "Трубы электросварные ЭСВ прямоугольные 40х25х3"
     Пример: 180*140*4 → "Трубы электросварные ЭСВ прямоугольные 180х140х4"
   - ВАЖНО: для профильных труб ВСЕГДА включай полное название с размерами
   - НИКОГДА не сокращай до просто размеров типа "150х100х4"

3. Сортовой прокат:
   - Уголок равнополочный 100х100х7 → "уголок 100х7"
   - Уголок неравнополочный 100х65х8 → "уголок 100х65х8"
   - Швеллер 16П → "швеллер 16 П" (ВАЖНО: пробел перед П или У!)
   - Швеллер 12П → "швеллер 12 П"
   - Швеллер низколегированный 16П → "швеллер низколегированный 16 П"
   - Балка, двутавр 20 → "балка 20"
   - Двутавр 18Б2 → "балка 18 Б2"
   - Круг 14 → "круг 14"
   - Полоса г/к 40х4 → "полоса 40х4"

НОМЕР ПРОФИЛЯ — параметры.номер (КРИТИЧНО для швеллера/балки/уголка/квадрата):
Для любого сортового проката, где в заявке указан номер профиля (размер),
ВСЕГДА заполняй параметры.номер этим числом — ОТДЕЛЬНО и НЕЗАВИСИМО от того,
что попало в поисковый_запрос или название. Это число не должно теряться
никогда, даже если для поискового запроса используется фраза из словаря.
- "Швеллер 16П" → параметры.номер=16
- "Балка 18 Б2" → параметры.номер=18
- "Двутавр 35Ш1" → параметры.номер=35
- "Уголок 100х100х7" → параметры.номер=100 (первое число — сторона уголка)
- "Квадрат 20" → параметры.номер=20

СЛОВАРЬ — ВАЖНОЕ ОГРАНИЧЕНИЕ: словарь (searchMap) можно использовать
ТОЛЬКО для формулировки поискового_запроса. НИКОГДА не используй словарь,
чтобы переписать "название" или обобщить/потерять номер размера — эти
поля должны точно отражать то, что менеджер написал в заявке, даже если
для того же товара в словаре сохранена другая (обобщённая) формулировка.
Пример: если в заявке "Балка 18 Б2 09Г2С", а в словаре есть запись
"Балка низколегированная Б2" → "..." — используй словарную формулировку
ТОЛЬКО для поискового_запроса, а название и параметры.номер всё равно
должны быть "Балка 18 Б2" и 18 соответственно, а не обобщённая фраза без номера.
   - Арматура д12, арматура А500 ф12 → "арматура 12"
   - Катанка 6 → "катанка 6"
   - ПВЛ 406 → "ПВЛ 406"

4. Листовой прокат — включай размеры в запрос:
   - Лист горячекатаный, лист г/к → "лист г/к [толщина]х[ширина]х[длина]"
     Пример: Лист г/к 2х1250х2500 → "лист г/к 2х1250х2500"
     Пример: Лист горячекатаный 5х1500х6000 → "лист г/к 5х1500х6000"

   - Лист холоднокатаный, лист х/к → "лист х/к [толщина]х[ширина]х[длина]"
     Пример: Лист х/к 1х1250х2500 → "лист х/к 1х1250х2500"
     Пример: Лист холоднокатаный 2х1000х2000 → "лист х/к 2х1000х2000"

   - Лист нержавеющий — включай толщину, ширину и тип поверхности:
     Пример: Лист нержавеющий х/к 0.4х1000 BA+PE зеркальный → "нержавеющий лист х/к 0.4х1000 BA+PE (зеркальный)"
     Пример: Лист нержавеющий х/к 0.4х1000 2B матовый → "нержавеющий лист х/к 0.4х1000 2B (матовый)"

   - Лист оцинкованный → "лист оцинкованный [толщина]х[ширина]х[длина]"
     Пример: Лист оцинкованный 0.9х1250х2500 → "лист оцинкованный 0.9х1250х2500"

   - Лист мостостроительный → "лист г/к [толщина]х[ширина]х[длина] мостостроительный"

5. Если позиция есть в словаре — используй запрос из словаря.

6. Если не знаешь — используй полное название позиции как написано в заявке.

ПРАВИЛА ДЛЯ ПАРАМЕТРОВ:

Листы:
- "лист 2.5x1250x2500" → толщина=2.5, ширина=1250, длина_листа=2500
- "лист 0.4х1000" → толщина=0.4, ширина=1000, длина_листа=null (рулон)

Трубы круглые:
- "ДУ15" или "ДУ 15" → ду=15
- "стенка 2" или "х2" или "x2" → стенка=2
- "диаметр 12" или "д12" → диаметр=12

Круг (сортовой прокат) — ОБЯЗАТЕЛЬНО заполняй параметры.диаметр, точно
так же как для труб/арматуры — это критично для поиска на сайте:
- "Круг 40", "Круг ф40", "Круг д40" → параметры.диаметр=40
- "Круг ф40 ст45" → параметры.диаметр=40, марка="ст45"

ПРАВИЛА ДЛЯ СТЕНКИ — ТОЧНОЕ СОВПАДЕНИЕ:
Если указана стенка 2 — ищем ТОЛЬКО 2. Не 2.5, не 2.2, не 2.1.
Если указана стенка 3 — ищем ТОЛЬКО 3.

Арматура — ВАЖНО, класс арматуры определяет тип проката:
- А3, А400, А500, А500С — периодического профиля (рифлёная)
- А1, А240, А240С — гладкого профиля
- Указывай марку ТОЧНО как написано в заявке (А3, А1, А500С, А240 и т.п.) —
  не подменяй одно обозначение другим, дальше это разруливается отдельно.
- диаметр арматуры (12, 14, 6, 10 и т.п.) → параметры.диаметр

ДЛИНА ПРУТКА/СТЕРЖНЯ — параметры.длина (в мм):
Если в заявке указана длина стержня/прутка (актуально для арматуры, балки,
круга, квадрата и т.п.) — заполняй параметры.длина в миллиметрах.
Это ОТДЕЛЬНО от количества/единицы измерения заказа.
- "по 6 метров", "6 м", "длина 6000" → длина=6000
- "по 11,7 м", "11.7м", "11700" → длина=11700
- Если длина не указана явно — длина=null (не проставляй значение по умолчанию,
  разные длины могут быть в наличии на складе)

Если указано "N шт по X метров" — считай количество=N*X, единица="м", а длину
стержня одновременно проставляй в параметры.длина=X (в мм). Если же дано
"Y тонн по X метров" — количество остаётся Y, единица="т", а параметры.длина
всё равно фиксирует длину стержня X (в мм), т.к. это просто уточнение какой
именно длины нужен товар, а не пересчёт количества.

ПРИМЕРЫ:

Вход: "Лист горячекатаный 2х1250х2500 - 1т"
Выход: поисковый_запрос="лист г/к 2х1250х2500", толщина=2, ширина=1250, длина_листа=2500, марка="Ст3", количество=1, единица="т"

Вход: "Лист холоднокатаный 1х1250х2500 - 1т"
Выход: поисковый_запрос="лист х/к 1х1250х2500", толщина=1, ширина=1250, длина_листа=2500, марка="Ст08пс", количество=1, единица="т"

Вход: "Лист г/к 10х1500х6000 09Г2С - 2т"
Выход: поисковый_запрос="лист г/к 10х1500х6000", толщина=10, ширина=1500, длина_листа=6000, марка="09Г2С", количество=2, единица="т"

Вход: "Лист оцинкованный 0.9х1250х2500 2 кл КР пром_пас - 1т"
Выход: поисковый_запрос="лист оцинкованный 0.9х1250х2500", толщина=0.9, ширина=1250, длина_листа=2500, количество=1, единица="т"

Вход: "Труба г/к 76х8 - 1т"
Выход: поисковый_запрос="трубы горячедеформированные 76x8", диаметр=76, стенка=8, марка="Ст3", количество=1, единица="т"

Вход: "40*25*3=60 м"
Выход: поисковый_запрос="Трубы электросварные ЭСВ прямоугольные 40х25х3", количество=60, единица="м"

Вход: "60*60*3=60 м"
Выход: поисковый_запрос="Трубы электросварные ЭСВ квадратные 60х3", количество=60, единица="м"

Вход: "Швеллер 16П 18м"
Выход: поисковый_запрос="швеллер 16 П", параметры.номер=16, количество=18, единица="м"

Вход: "Балка 18 Б2 09Г2С - 1 т"
Выход: название="Балка 18 Б2 09Г2С", поисковый_запрос="балка 18 Б2", параметры.номер=18, марка="09Г2С", количество=1, единица="т"

Вход: "Круг ф40 ст45 - 1 т"
Выход: поисковый_запрос="круг 40", параметры.диаметр=40, марка="ст45", количество=1, единица="т"

Вход: "Труба ВГП ДУ15 стенка 2 одна тонна"
Выход: поисковый_запрос="ВГП", параметры.ду=15, параметры.стенка=2, количество=1, единица="т"

Вход: "Двутавр 18Б2 — 5 шт по 12 метров"
Выход: поисковый_запрос="балка 18 Б2", параметры.длина=12000, количество=60, единица="м"

Вход: "Арматура А500С 12 — 10 шт по 6 метров"
Выход: поисковый_запрос="арматура 12", диаметр=12, марка="А500С", параметры.длина=6000, количество=60, единица="м"

Вход: "Арматура А3 ф14 - 2 т по 11,7 м"
Выход: поисковый_запрос="арматура 14", диаметр=14, марка="А3", параметры.длина=11700, количество=2, единица="т"

Вход: "Арматура А1 ф6 - 1 т"
Выход: поисковый_запрос="арматура 6", диаметр=6, марка="А1", параметры.длина=null, количество=1, единица="т"
`

  const response = await askAI(prompt)

  try {
    let clean = response.replace(/```json|```/g, '').trim()

    // Модель иногда добавляет пояснительный текст до/после JSON, несмотря
    // на явную инструкцию "только JSON, никакого текста до или после"
    // (например: "Это профильная труба... \n\n[{...}]"). Подстраховываемся:
    // вырезаем именно JSON-массив по первой '[' и последней ']', а не
    // полагаемся на то, что весь ответ целиком — чистый JSON.
    const start = clean.indexOf('[')
    const end = clean.lastIndexOf(']')
    if (start !== -1 && end !== -1 && end > start) {
      clean = clean.slice(start, end + 1)
    }

    const positions = JSON.parse(clean)
    console.log('=== ПАРСИНГ ===', JSON.stringify(positions, null, 2))
    return positions
  } catch (err) {
    throw new Error(`Не удалось распарсить ответ AI: ${response}`)
  }
}

module.exports = { parseOrder }