/**
 * handlers/brok.js
 *
 * /brok — состояние прайс-листов Брок Инвеста (склад «Октябрьский») и
 * принудительное обновление. Брок используется только для сравнения цен
 * (в корзину через бота не кладётся).
 */

const { isAllowed } = require("../../utils/auth");
const { инфоОПрайсе } = require("../../scraper-brok/index");
const { обновитьПрайс } = require("../../scraper-brok/download");
const logger = require("../../utils/logger");

function описание(инфо) {
  if (!инфо.есть) return "Прайсы Брок Инвеста пока не загружены.";
  return (
    `Прайсы Брок Инвеста (склад Октябрьский): дата в файлах ${инфо.датаПрайсаТекст}, бот скачал их ${инфо.скачанТекст || "—"}.` +
    `\nПозиций с ценой: ${инфо.позиций}, из них распознано для сравнения: ${инфо.разобрано}.` +
    (инфо.нетКатегорий.length ? `\nНе загружены категории: ${инфо.нетКатегорий.join(", ")}.` : "") +
    (инфо.устарел ? "\n⚠️ Бот давно не мог скачать прайсы." : "") +
    (!инфо.устарел && инфо.давноНеОбновлялся ? "\nℹ️ Дата в самих прайсах давняя — Брок новее не выкладывал." : "")
  );
}

async function handleBrokCommand(ctx) {
  if (!isAllowed(ctx.from.id)) {
    await ctx.reply("⛔ У вас нет доступа к этому боту.");
    return;
  }

  await ctx.reply(`${описание(инфоОПрайсе())}\n\n⏬ Скачиваю свежие прайсы с brokinvest.ru…`);
  try {
    const до = инфоОПрайсе();
    const р = await обновитьПрайс();
    const тотЖе = до.есть && до.датаПрайсаТекст === р.датаПрайсаТекст;
    await ctx.reply(
      (тотЖе
        ? `✅ Скачал прайсы с brokinvest.ru — внутри та же дата, ${р.датаПрайсаТекст}.\n`
        : `✅ Прайсы обновлены: теперь от ${р.датаПрайсаТекст}.\n`) +
        `Категорий обновлено: ${р.обновлено.length}, позиций с ценой: ${р.позиций}, распознано: ${р.разобрано}.` +
        (р.нетСсылок.length ? `\n⚠️ Не нашёл на сайте: ${р.нетСсылок.join(", ")}.` : "") +
        (р.проблемы.length ? `\n⚠️ Не разобрались: ${р.проблемы.join("; ")}.` : ""),
    );
  } catch (err) {
    logger.error("Брок: ручное обновление не удалось", { error: err.message });
    await ctx.reply(`❌ Не удалось обновить прайсы Брок Инвеста: ${err.message}`);
  }
}

module.exports = { handleBrokCommand };