/**
 * Строит inline-клавиатуру для одной позиции — по кнопке на каждую
 * непустую базу (текст: "база — цена₽") + кнопка "Пропустить". Кнопки
 * идут по одной в ряд — длинные названия баз (особенно "КТЗ: Дмитров")
 * плохо влезают по 2-3 в ряд на узком экране телефона.
 */
/**
 * Описание варианта так, как его называет каталог mc.ru: название (первая
 * строка) + марка + длина — например «горячекатаный круг из
 * конструкционной сортовой стали 30 Ст20». Нужно, чтобы менеджер видел,
 * ЧТО именно уйдёт в заказ, если выбрано не точное совпадение.
 */
function описаниеВарианта(вариант) {
  return [String(вариант.название || '').split('\n')[0].trim(), вариант.марка, вариант.длина]
    .filter(Boolean)
    .join(' ');
}

function построиКлавиатуру(индексПозиции, записьСтроки, базыСписок) {
  const кнопки = [];
  базыСписок.forEach((база, idx) => {
    const ячейка = записьСтроки.ячейки[база];
    if (!ячейка) return;
    const цена = ячейка.варианты[0].цена_от_1т;
    // 🟧 — не точное совпадение (другая марка/длина/ТУ), как оранжевые
    // ячейки в Excel
    const знак = ячейка.тип === 'альтернатива' ? '🟧 ' : '';
    кнопки.push([{ text: `${знак}${база} — ${цена}₽`, callback_data: `o|${индексПозиции}|${idx}` }]);
  });
  кнопки.push([{ text: '⏭ Пропустить эту позицию', callback_data: `o|${индексПозиции}|x` }]);
  return { inline_keyboard: кнопки };
}

/**
 * Отправляет следующую позицию (с кнопками) либо, если позиции
 * закончились, сводку с подтверждением. Пустые позиции (нет ни одной
 * базы с ценой) пропускает молча — нечего выбирать, незачем спрашивать.
 */
async function отправьСледующуюПозицию(ctx, userId) {
  const кэш = получиКэшСводки(userId);
  const session = getSession(userId);
  const состояние = session.ордерПоток;
  if (!состояние || !кэш) return;

  if (состояние.индексПозиции >= кэш.индексСводки.length) {
    await покажиИтогИПодтверждение(ctx, userId);
    return;
  }

  const записьСтроки = кэш.индексСводки[состояние.индексПозиции];
  const непустыеБазы = кэш.базыСписок.filter((база) => записьСтроки.ячейки[база]);

  if (непустыеБазы.length === 0) {
    состояние.индексПозиции += 1;
    setSession(userId, { ордерПоток: состояние });
    await отправьСледующуюПозицию(ctx, userId);
    return;
  }

  const клавиатура = построиКлавиатуру(состояние.индексПозиции, записьСтроки, кэш.базыСписок);
  const естьАльтернативы = непустыеБазы.some((база) => записьСтроки.ячейки[база].тип === 'альтернатива');
  await ctx.reply(
    `📍 Позиция ${состояние.индексПозиции + 1}/${кэш.индексСводки.length}: *${записьСтроки.названиеСтроки}*\n\nВыберите базу:` +
    (естьАльтернативы ? '\n🟧 — не точное совпадение (другая марка/длина/ТУ)' : ''),
    { parse_mode: 'Markdown', reply_markup: клавиатура }
  );
}

async function handleOrderCommand(ctx) {
  if (!isAllowed(ctx.from.id)) {
    await ctx.reply('⛔ У вас нет доступа к этому боту.');
    return;
  }

  const кэш = получиКэшСводки(ctx.from.id);
  if (!кэш || !кэш.индексСводки || кэш.индексСводки.length === 0) {
    await ctx.reply('❌ Нет сохранённой сводной таблицы — сначала пришлите заявку, чтобы бот её построил.');
    return;
  }

  setSession(ctx.from.id, { ордерПоток: { индексПозиции: 0, выборы: {} } });
  await отправьСледующуюПозицию(ctx, ctx.from.id);
}

/**
 * Обработчик нажатий на кнопки — регистрировать как
 * bot.action(/^o\|/, handleOrderCallback), чтобы не перехватывать
 * callback_query от других частей бота (если они есть).
 */
async function handleOrderCallback(ctx) {
  const userId = ctx.from.id;
  const session = getSession(userId);
  const состояние = session.ордерПоток;
  const data = ctx.callbackQuery.data;
  if (data.startsWith('o|lim|')) {
    const [, , решение, инд] = data.split('|');
    await ответНаЛимит(ctx, userId, решение === 'yes', parseInt(инд, 10));
    return;
  } // "o|<idx>|<baseIdx|x>" | "o|confirm" | "o|cancel"

  // ФИКС: проверяем актуальность сессии ДО обработки confirm/cancel —
  // иначе тап по кнопке "Оформить"/"Отменить" на сообщении, пережившем
  // рестарт бота (session.ордерПоток сброшен в null), падал с
  // "Cannot read properties of undefined (reading 'выборы')" внутри
  // выполниЗаказ(), т.к. проверка !состояние стояла НИЖЕ этих веток.
  if (!состояние) {
    await ctx.answerCbQuery('Сессия устарела — начните заново через /order');
    return;
  }

  if (data === 'o|confirm' || data.startsWith('o|confirm|')) {
    await ctx.answerCbQuery();
    const [, , режим, оптИдx] = data.split('|');
    состояние.режим = режим || 'one';
    if (режим === 'opt') состояние.оптБазаИдx = parseInt(оптИдx, 10);
    setSession(userId, { ордерПоток: состояние });
    await выполниЗаказ(ctx, userId);
    return;
  }

  if (data === 'o|cancel') {
    await ctx.answerCbQuery();
    setSession(userId, { ордерПоток: null }); // стираем ТОЛЬКО поток заказа, не всю сессию
    await ctx.editMessageText('❌ Отменено — корзины не трогали.');
    return;
  }

  const части = data.split('|');
  const индексПозиции = parseInt(части[1], 10);
  const выбор = части[2];

  if (выбор !== 'x') {
    состояние.выборы[индексПозиции] = parseInt(выбор, 10);
  }

  await ctx.answerCbQuery(выбор === 'x' ? 'Пропущено' : 'Выбрано ✓');
  состояние.индексПозиции = индексПозиции + 1;
  setSession(userId, { ордерПоток: состояние });

  await отправьСледующуюПозицию(ctx, userId);
}

async function покажиИтогИПодтверждение(ctx, userId) {
  const кэш = получиКэшСводки(userId);
  const session = getSession(userId);
  const выборы = session.ордерПоток.выборы;

  const строки = [];
  for (const [посIdxStr, baseIdx] of Object.entries(выборы)) {
    const посIdx = parseInt(посIdxStr, 10);
    const записьСтроки = кэш.индексСводки[посIdx];
    const база = кэш.базыСписок[baseIdx];
    const ячейкаВыбора = записьСтроки.ячейки[база];
    const альт = ячейкаВыбора && ячейкаВыбора.тип === 'альтернатива'
      ? `\n   🟧 не точное совпадение: ${описаниеВарианта(ячейкаВыбора.варианты[0])}`
      : '';
    строки.push(`• ${записьСтроки.названиеСтроки} → ${база}${альт}`);
  }

  if (строки.length === 0) {
    await ctx.reply('Ничего не выбрано — заказ не начат.');
    setSession(userId, { ордерПоток: null });
    return;
  }

  // Если позиции mc.ru выбраны на РАЗНЫХ базах — спрашиваем, как оформлять
  const выбранныеMc = [];
  for (const [посIdxStr, baseIdx] of Object.entries(выборы)) {
    const база = кэш.базыСписок[baseIdx];
    if (!база.startsWith(КТЗ_ПРЕФИКС)) выбранныеMc.push({ посIdx: parseInt(посIdxStr, 10), база });
  }
  const разныеБазы = Array.from(new Set(выбранныеMc.map((x) => x.база)));
  if (разныеБазы.length > 1) {
    // общие базы: есть у каждой выбранной позиции mc.ru — для «оптимизации»
    const общие = кэш.базыСписок.filter((б, i) =>
      !б.startsWith(КТЗ_ПРЕФИКС) && выбранныеMc.every((x) => кэш.индексСводки[x.посIdx].ячейки[б])
    );
    const кнопки = [
      [{ text: '📄 Один счёт, базы как выбрали', callback_data: 'o|confirm|one' }],
      [{ text: '📑 Раздельные счета по базам', callback_data: 'o|confirm|sep' }],
    ];
    for (const б of общие.slice(0, 4)) {
      кнопки.push([{ text: `🔀 Оптимизация: всё на «${б}»`, callback_data: `o|confirm|opt|${кэш.базыСписок.indexOf(б)}` }]);
    }
    кнопки.push([{ text: '❌ Отмена', callback_data: 'o|cancel' }]);
    await ctx.reply(
      `📋 Итого выбрано:\n${строки.join('\n')}\n\n` +
      `Позиции mc.ru на разных базах (${разныеБазы.join(', ')}). Как оформляем?\n` +
      `• Один счёт — базы как выбраны\n• Раздельные — по счёту на каждую базу\n` +
      (общие.length ? '• Оптимизация — все позиции на одну общую базу' : '(общей базы для всех позиций нет — оптимизация недоступна)'),
      { reply_markup: { inline_keyboard: кнопки } }
    );
    return;
  }

  await ctx.reply(`📋 Итого выбрано:\n${строки.join('\n')}\n\nОформляем?`, {
    reply_markup: {
      inline_keyboard: [[
        { text: '✅ Да, оформить', callback_data: 'o|confirm' },
        { text: '❌ Отмена', callback_data: 'o|cancel' },
      ]],
    },
  });
}

// ───────────────────────── «доска» прогресса заказа ─────────────────────────
// Вместо десятков отдельных сообщений ("✅ добавлено…", "🧹 очищаю…") бот ведёт
// ОДНО редактируемое сообщение-чеклист. Отдельными (новыми) остаются только то,
// что менеджер не должен пропустить: запрос кода КТЗ, предупреждение о разных
// базах, PDF-документы, скриншот ошибки и итог. Правка сообщения уведомления
// не даёт — поэтому итог всегда приходит новым сообщением.

const ЗНАЧОК = { ждёт: '▫️', идёт: '⏳', ок: '✅', внимание: '⚠️', ошибка: '❌' };

function создатьДоску(live, заголовок) {
  const строки = []; // { группа, текст, статус, заметка }
  const доска = {
    добавить(группа, текст, статус = 'ждёт', заметка = '') {
      const запись = { группа, текст: String(текст).slice(0, 90), статус, заметка };
      строки.push(запись);
      return запись;
    },
    обновить(запись, статус, заметка) {
      запись.статус = статус;
      if (заметка !== undefined) запись.заметка = String(заметка).slice(0, 300);
      доска.показать();
    },
    текст(шапка = заголовок) {
      const части = [шапка];
      let группа = null;
      for (const з of строки) {
        if (з.группа !== группа) {
          группа = з.группа;
          части.push('', группа);
        }
        части.push(`${ЗНАЧОК[з.статус]} ${з.текст}`);
        if (з.заметка) части.push(`      ↳ ${з.заметка}`);
      }
      return части.join('\n');
    },
    показать(шапка) {
      live.обновить(доска.текст(шапка));
    },
    строки,
  };
  return доска;
}

async function добавьЗаписьMcRu(запись, доска, userId) {
    if (доска) доска.обновить(запись._строка, 'идёт');
    try {
      const результат = await addToCart(запись.вариант, запись.quantity, запись.unit);
      const заметки = [];
      let статус = 'ок';
      if (результат && результат.adjusted && результат.adjustmentMessage) {
        // Сайт сам изменил количество (например, «Максимальный объём
        // заказа: 20 т. Количество уменьшено до 20 т») — показываем,
        // чтобы менеджер не думал, что добавлено ровно запрошенное.
        статус = 'внимание';
        заметки.push(`запрошено ${запись.quantity} ${запись.unit}. Сайт: ${результат.adjustmentMessage}`);
      }
      if (запись.альтернатива) {
        заметки.push(`🟧 не точное совпадение: ${запись.альтернатива}`);
        if (статус === 'ок') статус = 'внимание';
      }
      if (результат && результат.infoMessage) {
        // Информационное сообщение сайта — только показываем, на добавление
        // оно не влияет.
        заметки.push(`сообщение сайта: ${результат.infoMessage}`);
      }
      if (результат && результат.baseNotSelected) {
        статус = 'внимание';
        заметки.push(`не удалось выбрать базу «${запись.база}» на карточке — позиция могла попасть в корзину с другой базой, проверьте корзину`);
      }
      if (доска) доска.обновить(запись._строка, статус, заметки.join(' · '));
    } catch (err) {
      logger.error('Ошибка добавления в корзину mc.ru', {
        userId, позиция: запись.названиеСтроки, error: err.message,
      });
      // cart.js бросает "WARNING:<название>|<сообщение сайта>", когда сайт
      // не даёт добавить позицию (нет такого количества на складе и т.п.)
      const сообщениеСайта = err.message.startsWith('WARNING:')
        ? err.message.slice('WARNING:'.length).split('|').slice(1).join('|')
        : null;
      if (доска) доска.обновить(
        запись._строка,
        сообщениеСайта ? 'внимание' : 'ошибка',
        сообщениеСайта ? `НЕ добавлено. Сайт: ${сообщениеСайта}` : err.message
      );
    }
}

async function выполниЗаказ(ctx, userId) {
  const кэш = получиКэшСводки(userId);
  const session = getSession(userId);

  // Защитная проверка на всякий случай — handleOrderCallback уже не
  // должен пускать сюда без состояния, но дешёвая страховка от
  // будущих вызовов выполниЗаказ из другого места.
  if (!session.ордерПоток || !session.ордерПоток.выборы) {
    await ctx.reply('❌ Сессия заказа устарела — начните заново через /order.');
    return;
  }

  const выборы = session.ордерПоток.выборы;
  const режимЗаказа = session.ордерПоток.режим || 'one';

  const выборMcRu = [];
  const выборКтз = [];
  const ошибки = [];

  for (const [посIdxStr, baseIdx] of Object.entries(выборы)) {
    const посIdx = parseInt(посIdxStr, 10);
    const записьСтроки = кэш.индексСводки[посIdx];
    let база = кэш.базыСписок[baseIdx];
    // «Оптимизация»: все позиции mc.ru — на одну общую базу
    if (режимЗаказа === 'opt' && !база.startsWith(КТЗ_ПРЕФИКС)) {
      const общая = кэш.базыСписок[session.ордерПоток.оптБазаИдx];
      if (общая && записьСтроки.ячейки[общая]) база = общая;
    }
    const ячейка = записьСтроки.ячейки[база];
    const вариант = ячейка.варианты[0];
    const источник = база.startsWith(КТЗ_ПРЕФИКС) ? 'ktz' : 'mc.ru';

    const количество = подготовьКоличествоДляКорзины(записьСтроки.position, вариант, источник);
    if (!количество) {
      ошибки.push(`${записьСтроки.названиеСтроки} — не смог перевести количество в тонны (нет длины/веса у товара или вес на сайте сомнительный) — укажите эту позицию в тоннах`);
      continue;
    }

    // ФИКС: для mc.ru передаём выбранную менеджером базу как
    // recommendedBase — cart.js по ней выбирает строку нужной базы.
    // Раньше она нигде не передавалась (целеваяБаза: null в логах), и в
    // корзину попадала первая попавшаяся строка с тем же названием —
    // например с базой Очаково вместо выбранной Карачарово.
    const вариантДляКорзины = источник === 'ktz' ? вариант : { ...вариант, recommendedBase: база };
    // Для позиций в метрах считаем и тонны: у некоторых товаров mc.ru (катанка в
    // мотках) на карточке нет поля метров — cart.js тогда вводит эти тонны, а не метры.
    if (источник === 'mc.ru' && количество.unit === 'м') {
      try {
        const р = посчитайПоЗаявке({ ...записьСтроки.position, единица: 'м', количество: количество.quantity });
        if (р && р.total_weight > 0) вариантДляКорзины._тоннЭквивалент = Math.max(0.001, Math.round(р.total_weight) / 1000);
      } catch (e) {
        logger.warn('Не удалось пересчитать метры в тонны', { позиция: записьСтроки.названиеСтроки, error: e.message });
      }
    }

    const запись = {
      названиеСтроки: записьСтроки.названиеСтроки,
      база,
      вариант: вариантДляКорзины,
      quantity: количество.quantity,
      unit: количество.unit,
      альтернатива: ячейка.тип === 'альтернатива' ? описаниеВарианта(вариант) : null,
    };
    if (источник === 'ktz') выборКтз.push(запись);
    else выборMcRu.push(запись);
  }

  if (выборMcRu.length === 0 && выборКтз.length === 0) {
    if (ошибки.length > 0) await ctx.reply('⚠️ Проблемы с позициями:\n' + ошибки.join('\n'));
    await ctx.reply('❌ Ни одной позиции не удалось обработать — заказ не начат.');
    setSession(userId, { ордерПоток: null });
    return;
  }

  const live = await создатьЖивоеСообщение(ctx, '📦 Оформляю заказ…');
  const доска = создатьДоску(live, '📦 Оформляю заказ');

  // Позиции, у которых не удалось посчитать количество, сразу видны как ❌
  for (const текст of ошибки) доска.добавить('⚠️ Не обработаны', текст, 'ошибка');

  // Этапы доски заводим заранее — менеджер сразу видит весь план
  const этапКтзВход = выборКтз.length > 0 ? доска.добавить('🔑 Вход', 'Авторизация на КТЗ') : null;
  const этапОчистка = выборMcRu.length > 0 ? доска.добавить('🔑 Вход', 'Очистка корзины mc.ru от старых позиций') : null;
  for (const з of выборMcRu) з._строка = доска.добавить('🛒 mc.ru — в корзину', `${з.названиеСтроки} (${з.база}) — ${з.quantity} ${з.unit}`);
  for (const з of выборКтз) з._строка = доска.добавить('🛒 КТЗ — в корзину', `${з.названиеСтроки} (${з.база}) — ${з.quantity} ${з.unit}`);
  const этапКпКтз = выборКтз.length > 0 ? доска.добавить('📄 Документы', 'КП на КТЗ') : null;
  // mc.ru: по одному счёту на каждую выбранную базу (так база в счёте точно та, что выбрал менеджер)
  const группыMc = [];
  const разныеБазыЗаказа = new Set(выборMcRu.map((з) => з.база));
  if (режимЗаказа !== 'sep' && разныеБазыЗаказа.size > 1) {
    // по умолчанию: ОДИН заказ с разными базами у позиций
    группыMc.push({ база: 'разные базы', записи: выборMcRu.slice(), смешанные: true });
  } else {
    for (const з of выборMcRu) {
      let г = группыMc.find((x) => x.база === з.база);
      if (!г) { г = { база: з.база, записи: [] }; группыMc.push(г); }
      г.записи.push(з);
    }
    группыMc.sort((x, y) => y.записи.length - x.записи.length);
  }
  for (const г of группыMc) г.этап = доска.добавить('📄 Документы', г.смешанные ? 'Счёт на mc.ru — несколько баз' : `Счёт на mc.ru — база «${г.база}»`);
  доска.показать();

  const итоговыеПроблемы = []; // что вынести в итоговое сообщение (новое — с уведомлением)

  // ФИКС: авторизуемся на КТЗ ДО добавления в корзину и оформления КП —
  // раньше этого вызова не было вообще, из-за чего КП оформлялось от
  // имени гостя без доступа к "Коммерческое предложение" и падало с
  // "Не нашли кнопку «Коммерческое предложение» в корзине КТЗ" даже
  // после успешного добавления всех позиций в корзину. Делаем это
  // только если реально есть позиции на КТЗ — незачем логиниться зря
  // для чисто mc.ru заказа.
  if (выборКтз.length > 0) {
    доска.обновить(этапКтзВход, 'идёт');
    try {
      await authorizeKTZ({
        // КТЗ запросил код подтверждения — код приходит администратору в
        // Telegram, поэтому менеджеру говорим, что идёт ожидание, чтобы
        // он не нажимал повторно. Это — ОТДЕЛЬНОЕ сообщение (с уведомлением).
        приЗапросеКода: (попытка) => {
          доска.обновить(этапКтзВход, 'идёт', 'жду код подтверждения от администратора');
          return ctx.reply(
            попытка === 1
              ? '📲 КТЗ запросил код подтверждения входа. Жду код от администратора (до 5 минут)…'
              : '📲 КТЗ не принял код — жду новый от администратора (до 5 минут)…'
          );
        },
      });
      доска.обновить(этапКтзВход, 'ок', '');
    } catch (err) {
      logger.error('Ошибка авторизации на КТЗ', { userId, error: err.message });
      доска.обновить(этапКтзВход, 'ошибка', err.message);
      for (const з of выборКтз) доска.обновить(з._строка, 'ошибка', 'пропущено — нет входа на КТЗ');
      if (этапКпКтз) доска.обновить(этапКпКтз, 'ошибка', 'пропущено');
      итоговыеПроблемы.push(`❌ Не удалось авторизоваться на КТЗ: ${err.message}\nПозиции КТЗ (${выборКтз.length}) пропущены, mc.ru оформляю дальше.`);
      выборКтз.length = 0;
    }
  }

  for (const запись of выборКтз) {
    доска.обновить(запись._строка, 'идёт');
    try {
      await addToCartKTZ(запись.вариант, запись.quantity, запись.unit);
      доска.обновить(
        запись._строка,
        запись.альтернатива ? 'внимание' : 'ок',
        запись.альтернатива ? `🟧 не точное совпадение: ${запись.альтернатива}` : ''
      );
    } catch (err) {
      logger.error('Ошибка добавления в корзину КТЗ', {
        userId, позиция: запись.названиеСтроки, error: err.message,
      });
      доска.обновить(запись._строка, 'ошибка', err.message);
    }
  }

  // Оформление КП на КТЗ — подключено и протестировано.
  const документы = []; // [{ source, filename, caption? }] — отправим после итога
  if (выборКтз.length > 0) {
    доска.обновить(этапКпКтз, 'идёт');
    try {
      const { placeOrderKTZ } = require('../../scraper-ktz/order-ktz');
      const pdfPath = await placeOrderKTZ();
      документы.push({ source: pdfPath, filename: 'КП_КТЗ.pdf' });
      доска.обновить(этапКпКтз, 'ок', 'файл придёт ниже');
    } catch (err) {
      logger.error('Ошибка оформления КП на КТЗ', { userId, error: err.message });
      доска.обновить(этапКпКтз, 'ошибка', err.message);
    }
  }

  let скриншотОшибки = false;
  // mc.ru: для каждой базы — своя корзина и свой счёт. Если оформлять всё разом,
  // сайт сам переносит позиции на «оптимальные» базы (в одном заказе вышли
  // Коровино и Карачарово вместо выбранной Балашихи).
  const вопросыЛимит = [];
  for (let gi = 0; gi < группыMc.length; gi++) {
    const г = группыMc[gi];
    // 1. чистим корзину
    if (gi === 0 && этапОчистка) доска.обновить(этапОчистка, 'идёт');
    try {
      await authorize();
      await clearCart(await getPage());
      if (gi === 0 && этапОчистка) доска.обновить(этапОчистка, 'ок');
    } catch (err) {
      logger.error('Не удалось очистить корзину mc.ru', { userId, error: err.message });
      if (gi === 0 && этапОчистка) доска.обновить(этапОчистка, 'ошибка', err.message);
      for (const з of г.записи) доска.обновить(з._строка, 'ошибка', 'пропущено — корзина не очищена');
      доска.обновить(г.этап, 'ошибка', 'пропущено');
      итоговыеПроблемы.push(
        `❌ Не удалось очистить корзину mc.ru: ${err.message}\n` +
        `Позиции базы «${г.база}» (${г.записи.length}) не добавляю и счёт не оформляю, чтобы не выписать старые позиции. ` +
        `Очистите корзину на mc.ru вручную и повторите /order.`
      );
      continue;
    }

    // 2. добавляем позиции этой базы
    for (const запись of г.записи) await добавьЗаписьMcRu(запись, доска, userId);

    // 3. сверяем корзину: если позиция пропала — пробуем добавить ещё раз
    try {
      const { прочитатьКорзину, названиеСовпадает } = require('../../scraper/order');
      let строки = await прочитатьКорзину();
      if (г.смешанные) {
        // в корзине у каждой строки своя база — сверяем с выбранной менеджером
        const не = [];
        for (const з of г.записи) {
          const р = строки.find((p) => названиеСовпадает(з.вариант.название, p.название));
          if (р && р.база && !р.база.includes(з.база)) {
            не.push(`${з.названиеСтроки}: выбрана «${з.база}», в корзине «${р.база}»`);
            const прежняя = з._строка.заметка ? `${з._строка.заметка} · ` : '';
            доска.обновить(з._строка, 'внимание', `${прежняя}в корзине база «${р.база}», а не «${з.база}»`);
          }
        }
        if (не.length > 0) {
          итоговыеПроблемы.push(
            '⚠️ В корзине mc.ru у позиций оказались другие базы, чем выбраны:\n' + не.map((x) => `• ${x}`).join('\n') +
            '\n\nЕсли нужны именно выбранные базы — оформите этот заказ режимом «Раздельные счета по базам».'
          );
        }
      }
      const нет = г.записи.filter((з) => !строки.some((p) => названиеСовпадает(з.вариант.название, p.название)));
      if (нет.length > 0) {
        logger.warn('Позиций нет в корзине mc.ru — добавляю повторно', { позиции: нет.map((з) => з.названиеСтроки) });
        for (const з of нет) {
          try { await addToCart(з.вариант, з.quantity, з.unit); } catch (e) { logger.warn('Повторное добавление не удалось', { позиция: з.названиеСтроки, error: e.message }); }
        }
      }
    } catch (e) {
      logger.warn('Не удалось сверить корзину mc.ru после добавления', { error: e.message });
    }

    // 4. счёт на эту базу
    доска.обновить(г.этап, 'идёт');
    try {
      const { placeOrder } = require('../../scraper/order');
      const pdfPath = await placeOrder(г.смешанные ? [] : [г.база], {
        смешанныеБазы: !!г.смешанные,
        приПредупреждении: (текст) => { итоговыеПроблемы.push(String(текст)); },
        ожидаемые: г.записи.map((з) => ({ ключ: з.названиеСтроки, название: з.вариант.название })),
        приПроверкеКорзины: (проблемы) => {
          for (const п of проблемы) {
            const з = г.записи.find((x) => x.названиеСтроки === п.ключ);
            if (!з) continue;
            const прежняя = з._строка.заметка ? `${з._строка.заметка} · ` : '';
            доска.обновить(з._строка, 'внимание', `${прежняя}${п.причина}`);
          }
          итоговыеПроблемы.push(
            `⚠️ Корзина mc.ru (база «${г.база}») не совпала с заказом:\n` + проблемы.map((п) => `• ${п.ключ} — ${п.причина}`).join('\n') +
            '\n\nПроверьте счёт: этих позиций там может не быть.'
          );
        },
      });
      const файлы = Array.isArray(pdfPath) ? pdfPath : [pdfPath];
      файлы.forEach((путь, k) => {
        документы.push({
          source: путь,
          filename: г.смешанные ? `Счёт_mc.ru_${k + 1}.pdf` : `Счёт_mc.ru_${г.база}.pdf`,
          caption: г.смешанные
            ? `Счёт mc.ru (${k + 1} из ${файлы.length}), разные базы. Позиции заказа: ` + г.записи.map((з) => `${з.названиеСтроки} (${з.база})`).join('; ')
            : `Счёт mc.ru, база «${г.база}». Позиции: ` + г.записи.map((з) => з.названиеСтроки).join('; '),
        });
      });
      доска.обновить(г.этап, 'ок', 'файл придёт ниже');
    } catch (err) {
      logger.error('Ошибка оформления счёта на mc.ru', { userId, база: г.база, error: err.message });
      const отказСайта = err.message.startsWith('mc.ru отменил создание счёта');
      if (err.лимит) {
        доска.обновить(г.этап, 'ошибка', 'превышен лимит по неоплаченным счетам');
        итоговыеПроблемы.push(
          `⚠️ Счёт на mc.ru (база «${г.база}») не создан: превышен лимит по неоплаченным счетам` +
          (err.позицииЛимита && err.позицииЛимита.length
            ? ' по позициям:\n' + err.позицииЛимита.map((п) => `• ${п}`).join('\n')
            : '.') +
          '\n\nСайт изменил количество (обычно до 0). Оплатите или удалите старые неоплаченные счета на mc.ru.'
        );
        if (err.остальных !== 0 && г.записи.length > 1) {
          вопросыЛимит.push({ база: г.база, смешанные: !!г.смешанные, записи: г.записи, позиции: err.позицииЛимита || [] });
        }
      } else {
        доска.обновить(г.этап, 'ошибка', err.message);
        итоговыеПроблемы.push(
          `❌ Не удалось оформить счёт на mc.ru (база «${г.база}»): ${err.message}` +
          (отказСайта ? '\n\nПозиции остались в корзине mc.ru — проверьте её и оформите вручную.' : '')
        );
        скриншотОшибки = true;
      }
    }
  }

  // Итог: доска дорисовывается в финальном виде, а менеджеру приходит НОВОЕ
  // сообщение (с уведомлением) — правка старого уведомления не даёт.
  const всего = доска.строки.length;
  const плохих = доска.строки.filter((з) => з.статус === 'ошибка').length;
  const внимание = доска.строки.filter((з) => з.статус === 'внимание').length;
  await live.завершить(доска.текст(плохих + внимание === 0 ? '✅ Заказ оформлен' : '📦 Заказ обработан — есть замечания'));

  const итог = [];
  итог.push(
    плохих === 0 && внимание === 0
      ? `✅ Готово: все ${всего} пунктов выполнены.`
      : `📦 Заказ обработан: без замечаний ${всего - плохих - внимание} из ${всего}` +
        (внимание ? `, ⚠️ требуют внимания: ${внимание}` : '') +
        (плохих ? `, ❌ с ошибкой: ${плохих}` : '') +
        `. Подробности — в списке выше.`
  );
  for (const п of итоговыеПроблемы) итог.push(п);
  await ctx.reply(итог.join('\n\n'));

  for (const д of документы) {
    try {
      await ctx.replyWithDocument(
        { source: д.source, filename: д.filename },
        д.caption ? { caption: д.caption } : undefined
      );
    } catch (err) {
      logger.error('Не удалось отправить документ заказа', { userId, файл: д.filename, error: err.message });
      await ctx.reply(`❌ Не удалось отправить файл ${д.filename}: ${err.message}`);
    }
  }

  if (скриншотОшибки) {
    // Скриншот корзины — чтобы сразу видеть, что на самом деле лежало в
    // корзине mc.ru в момент неудачи (пуста, не те позиции и т.п.).
    try {
      const скриншот = await screenshotCart();
      await ctx.replyWithPhoto({ source: скриншот }, { caption: 'Корзина mc.ru на момент ошибки' });
    } catch (e) {
      logger.warn('Не удалось сделать скриншот корзины после ошибки оформления', { error: e.message });
    }
  }

  setSession(userId, { ордерПоток: null });

  if (вопросыЛимит.length > 0) {
    setSession(userId, { лимитОжидание: вопросыЛимит });
    for (let i = 0; i < вопросыЛимит.length; i++) {
      const q = вопросыЛимит[i];
      await ctx.reply(
        `Оформить счёт на mc.ru (база «${q.база}») БЕЗ ` +
          (q.позиции.length ? 'позиций с превышенным лимитом:\n' + q.позиции.map((п) => `• ${п}`).join('\n') : 'этих позиций') +
          '\n\nОстальные позиции этой базы оформлю заново.',
        { reply_markup: { inline_keyboard: [[
          { text: '✅ Да, оформить без них', callback_data: `o|lim|yes|${i}` },
          { text: '❌ Нет', callback_data: `o|lim|no|${i}` },
        ]] } }
      );
    }
  }
}

/** Ответ на вопрос «оформить счёт без позиций с превышенным лимитом?» */
async function ответНаЛимит(ctx, userId, да, индекс) {
  const список = getSession(userId).лимитОжидание;
  const q = Array.isArray(список) ? список[индекс] : null;
  if (!q) {
    await ctx.answerCbQuery('Вопрос устарел — начните заново через /order');
    return;
  }
  список[индекс] = null;
  setSession(userId, { лимитОжидание: список });
  await ctx.answerCbQuery();
  if (!да) {
    await ctx.editMessageText('Ок, этот счёт не оформляю.');
    return;
  }
  await ctx.editMessageText(`⏳ Оформляю счёт mc.ru (база «${q.база}») без позиций с превышенным лимитом…`);
  try {
    const { placeOrder } = require('../../scraper/order');
    await authorize();
    await clearCart(await getPage());
    for (const запись of q.записи) await добавьЗаписьMcRu(запись, null, userId);
    const pdfPath = await placeOrder(q.смешанные ? [] : [q.база], { повторПослеЛимита: true, смешанныеБазы: !!q.смешанные });
    const файлы = Array.isArray(pdfPath) ? pdfPath : [pdfPath];
    for (let k = 0; k < файлы.length; k++) {
      await ctx.replyWithDocument(
        { source: файлы[k], filename: q.смешанные ? `Счёт_mc.ru_${k + 1}.pdf` : `Счёт_mc.ru_${q.база}.pdf` },
        { caption: `Счёт mc.ru (${q.база}), без позиций с превышенным лимитом.` }
      );
    }
  } catch (err) {
    logger.error('Ошибка оформления счёта mc.ru после лимита', { userId, error: err.message });
    await ctx.reply(`❌ Не удалось оформить счёт на mc.ru: ${err.message}`);
    try {
      const скриншот = await screenshotCart();
      await ctx.replyWithPhoto({ source: скриншот }, { caption: 'Корзина mc.ru на момент ошибки' });
    } catch (e) {
      logger.warn('Не удалось сделать скриншот корзины', { error: e.message });
    }
  }
}

