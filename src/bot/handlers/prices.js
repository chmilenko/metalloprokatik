/**
 * handlers/prices.js
 *
 * /prices — сводка по свежести источников цен: прайсы Дипоса и Брок Инвеста
 * (скачиваются раз в сутки), mc.ru и КТЗ (смотрим вживую при каждой заявке).
 */

const { isAllowed } = require("../../utils/auth");
const { инфоОПрайсе: инфоДипос } = require("../../scraper-dipos/index");
const { инфоОПрайсе: инфоБрок } = require("../../scraper-brok/index");

function строкаПоставщика(название, инфо, подсказка) {
  if (!инфо.есть) return `⚪ <b>${название}</b> — прайс не загружен. ${подсказка}`;
  const значок = инфо.устарел ? "🔴" : инфо.давноНеОбновлялся ? "🟡" : "🟢";
  let строка =
    `${значок} <b>${название}</b> — прайс от ${инфо.датаПрайсаТекст}, бот скачал ${инфо.скачанТекст || "—"}\n` +
    `      позиций: ${инфо.позиций}, для сравнения распознано: ${инфо.разобрано}`;
  if (инфо.устарел) строка += `\n      ⚠️ бот давно не смог скачать прайс — ${подсказка}`;
  else if (инфо.давноНеОбновлялся) строка += `\n      ℹ️ поставщик давно не выкладывал новый прайс`;
  if (инфо.нетКатегорий && инфо.нетКатегорий.length) {
    строка += `\n      ⚠️ не загружены категории: ${инфо.нетКатегорий.join(", ")}`;
  }
  return строка;
}

async function handlePricesCommand(ctx) {
  if (!isAllowed(ctx.from.id)) {
    await ctx.reply("⛔ У вас нет доступа к этому боту.");
    return;
  }
  const текст =
    "💰 <b>Источники цен</b>\n\n" +
    "🟢 <b>mc.ru</b> и <b>КТЗ</b> — смотрю вживую при каждой заявке\n\n" +
    строкаПоставщика("Дипос", инфоДипос(), "обновить: /dipos") +
    "\n\n" +
    строкаПоставщика("Брок Инвест (склад Октябрьский)", инфоБрок(), "обновить: /brok") +
    "\n\n<i>Прайсы обновляются сами каждое утро (Дипос ≈9:20, Брок ≈9:30). 🟢 свежий · 🟡 поставщик давно не обновлял · 🔴 бот не смог скачать.</i>";
  await ctx.reply(текст, { parse_mode: "HTML" });
}

module.exports = { handlePricesCommand };