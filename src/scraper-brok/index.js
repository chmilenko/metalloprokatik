/**
 * scraper-brok/index.js
 *
 * Брок Инвест — поставщик, у которого мы берём ТОЛЬКО прайс-листы (склад
 * «СК Октябрьский») и показываем цену в сводной таблице рядом с mc.ru, КТЗ и
 * Дипосом — ИСКЛЮЧИТЕЛЬНО ДЛЯ СРАВНЕНИЯ. Через бота там не заказываем,
 * поэтому /order колонку «Брок» не предлагает.
 *
 * Прайс разбит на файлы по категориям (см. parse.js). Все файлы скачиваются
 * раз в сутки (download.js) и складываются в один JSON — data/brok-price.json.
 * Если одну категорию скачать/разобрать не удалось, остаётся её прежний
 * вариант, остальные обновляются.
 *
 * Правила сравнения позиции заявки с прайсом — те же, что у Дипоса
 * (scraper-dipos/index.js: разобратьПозицию + сравнить): размер/форма —
 * жёстко, длина/ТУ/сорт/сталь — мягко (альтернатива с пометкой).
 */

const fs = require("fs");
const path = require("path");
const logger = require("../utils/logger");
const { разобратьФайл, КАТЕГОРИИ } = require("./parse");
const { разобратьПозицию, сравнить } = require("../scraper-dipos/index");

const ПРЕФИКС_СКЛАДА = "Брок: ";
const БАЗА = `${ПРЕФИКС_СКЛАДА}Октябрьский`;

const ПАПКА_ДАННЫХ = path.join(__dirname, "../../data");
const ФАЙЛ_ДАННЫХ = path.join(ПАПКА_ДАННЫХ, "brok-price.json");
const ПАПКА_ФАЙЛОВ = path.join(__dirname, "../../downloads/brok");

const УСТАРЕЛ_ЧАСОВ = 36;
const ДАВНО_НЕ_ОБНОВЛЯЛ_ЧАСОВ = 48;
const МАКС_ЦЕН_В_ЯЧЕЙКЕ = 3;
const МАКС_АЛЬТЕРНАТИВ = 8;

// Категории, где «не распознано» — норма (рулоны, ленты, оцинкованные трубы):
// для них не применяем проверку «разобралось подозрительно мало».
const ЛЮБОЙ_ПРОЦЕНТ_НОРМА = new Set(["ocinkovannij", "esshp"]);

// ───────────────────────── хранилище ─────────────────────────

let кэш = { mtime: 0, данные: null };

function получитьПрайс() {
  if (!fs.existsSync(ФАЙЛ_ДАННЫХ)) return null;
  const mtime = fs.statSync(ФАЙЛ_ДАННЫХ).mtimeMs;
  if (кэш.данные && кэш.mtime === mtime) return кэш.данные;
  try {
    const данные = JSON.parse(fs.readFileSync(ФАЙЛ_ДАННЫХ, "utf-8"));
    кэш = { mtime, данные };
    return данные;
  } catch (err) {
    logger.error("Брок: не удалось прочитать сохранённый прайс", { error: err.message });
    return null;
  }
}

function форматВремени(мс) {
  return new Date(мс).toLocaleString("ru-RU", {
    day: "2-digit",
    month: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    timeZone: "Europe/Moscow",
  });
}

function инфоОПрайсе() {
  const прайс = получитьПрайс();
  if (!прайс) return { есть: false };
  const времяПрайса = прайс.датаПрайса ? new Date(прайс.датаПрайса).getTime() : null;
  // дата в файле — без времени (на начало суток), поэтому «давно» считаем с запасом в сутки
  const возрастЧасов = времяПрайса ? (Date.now() - времяПрайса) / 3600000 - 24 : null;
  const времяСкачивания = прайс.скачан ? Date.parse(прайс.скачан) : null;
  const возрастСкачиванияЧасов = времяСкачивания ? (Date.now() - времяСкачивания) / 3600000 : null;
  const категории = прайс.категории || {};
  return {
    есть: true,
    датаПрайсаТекст: прайс.датаПрайсаТекст,
    скачан: прайс.скачан,
    скачанТекст: времяСкачивания ? форматВремени(времяСкачивания) : null,
    возрастЧасов,
    возрастСкачиванияЧасов,
    устарел: возрастСкачиванияЧасов == null ? true : возрастСкачиванияЧасов > УСТАРЕЛ_ЧАСОВ,
    давноНеОбновлялся: возрастЧасов != null && возрастЧасов > ДАВНО_НЕ_ОБНОВЛЯЛ_ЧАСОВ,
    позиций: прайс.позиции.length,
    разобрано: прайс.позиции.filter((п) => п.разобрано).length,
    категории, // { slug: {скачан, датаПрайсаТекст, позиций, разобрано} }
    нетКатегорий: Object.keys(КАТЕГОРИИ).filter((к) => !категории[к] && к !== "listpp"),
  };
}

/**
 * Принимает скачанные файлы { slug: путьКФайлу }, разбирает и обновляет
 * хранилище. Категория, которая не разобралась, остаётся прежней.
 * Бросает ошибку, только если не обновилась НИ ОДНА категория.
 */
function обновитьИзФайлов(файлыПоКатегориям) {
  const прежний = получитьПрайс() || { позиции: [], категории: {} };
  const категории = { ...(прежний.категории || {}) };
  const позицииПоКатегориям = {};
  for (const п of прежний.позиции) (позицииПоКатегориям[п.категория] ||= []).push(п);

  const обновлено = [];
  const проблемы = [];
  let датаПрайса = null;
  let датаПрайсаТекст = null;

  for (const [slug, файл] of Object.entries(файлыПоКатегориям)) {
    try {
      const р = разобратьФайл(файл, slug);
      const с = р.статистика;
      const кСравнению = с.разобрано + с.неРазобрано;
      if (!ЛЮБОЙ_ПРОЦЕНТ_НОРМА.has(slug) && кСравнению >= 10 && с.разобрано / кСравнению < 0.7) {
        throw new Error(`разобралось подозрительно мало (${с.разобрано} из ${кСравнению}) — формат файла, вероятно, изменился`);
      }
      позицииПоКатегориям[slug] = р.позиции;
      категории[slug] = {
        скачан: new Date().toISOString(),
        датаПрайсаТекст: р.датаПрайсаТекст,
        позиций: р.позиции.length,
        разобрано: с.разобрано,
      };
      обновлено.push(slug);
      if (р.датаПрайса && (!датаПрайса || р.датаПрайса > датаПрайса)) {
        датаПрайса = р.датаПрайса;
        датаПрайсаТекст = р.датаПрайсаТекст;
      }
    } catch (err) {
      проблемы.push(`${slug}: ${err.message}`);
      logger.warn("Брок: категория не обновлена", { slug, error: err.message });
    }
  }

  if (обновлено.length === 0) {
    throw new Error(`не удалось разобрать ни один прайс Брок Инвеста (${проблемы.join("; ")}). Прежние данные оставлены.`);
  }

  const позиции = Object.values(позицииПоКатегориям).flat();
  const данные = {
    датаПрайса: датаПрайса || прежний.датаПрайса || null,
    датаПрайсаТекст: датаПрайсаТекст || прежний.датаПрайсаТекст || null,
    скачан: new Date().toISOString(),
    категории,
    позиции,
  };
  if (!fs.existsSync(ПАПКА_ДАННЫХ)) fs.mkdirSync(ПАПКА_ДАННЫХ, { recursive: true });
  const времянка = `${ФАЙЛ_ДАННЫХ}.tmp`;
  fs.writeFileSync(времянка, JSON.stringify(данные));
  fs.renameSync(времянка, ФАЙЛ_ДАННЫХ);
  кэш = { mtime: 0, данные: null };
  logger.info("Брок: прайс обновлён", { дата: данные.датаПрайсаТекст, обновлено: обновлено.length, проблем: проблемы.length });
  return {
    датаПрайсаТекст: данные.датаПрайсаТекст,
    обновлено,
    проблемы,
    позиций: позиции.length,
    разобрано: позиции.filter((п) => п.разобрано).length,
  };
}

// ───────────────────────── поиск ─────────────────────────

function вВариант(строка, метки) {
  const р = строка.разобрано;
  const д = р.длина ?? р.длинаЛиста;
  return {
    название: строка.название,
    смц: БАЗА,
    длина: typeof д === "number" ? String(д) : "н/д",
    марка: р.стальСырая || null,
    цена_от_1т: строка.цена,
    cardUrl: null,
    sourceUrl: null,
    // Флаг тот же, что у Дипоса: «справочная» база — только для сравнения цен,
    // в /order не участвует (exportToExcel опирается именно на него).
    _дипос: true,
    _брок: true,
    _строкаПрайса: `${строка.категория}: ${строка.строка}`,
    _альтернатива: метки.length > 0,
    _альтМетка: метки.join(", "),
  };
}

/**
 * Ищет позицию заявки в прайсе Брок Инвеста. Формат результата — как у
 * найдиВДипосе(): { variants, оценённые }. Никогда не бросает исключение.
 */
function найдиВБроке(position) {
  const пусто = { variants: [], оценённые: [] };
  try {
    const прайс = получитьПрайс();
    if (!прайс) return пусто;
    const п = разобратьПозицию(position);
    if (!п) return пусто;

    const точные = [];
    const альтернативы = [];
    for (const строка of прайс.позиции) {
      if (!строка.разобрано) continue;
      const итог = сравнить(п, строка.разобрано, строка);
      if (!итог) continue;
      const вариант = вВариант(строка, итог.метки);
      (итог.метки.length === 0 ? точные : альтернативы).push(вариант);
    }

    const определённые = точные.filter((v) => /^\d+$/.test(v.длина));
    const пул = определённые.length > 0 ? определённые : точные;
    const вЯчейку = [];
    const видели = new Set();
    for (const v of [...пул].sort((a, b) => a.цена_от_1т - b.цена_от_1т)) {
      if (видели.has(v.цена_от_1т)) continue;
      видели.add(v.цена_от_1т);
      вЯчейку.push(v);
      if (вЯчейку.length >= МАКС_ЦЕН_В_ЯЧЕЙКЕ) break;
    }

    const альтернативыКоротко = [...альтернативы].sort((a, b) => a.цена_от_1т - b.цена_от_1т).slice(0, МАКС_АЛЬТЕРНАТИВ);
    const оценённые = [
      ...точные.map((вариант) => ({ вариант, прошёл: true, причина: "" })),
      ...альтернативыКоротко.map((вариант) => ({ вариант, прошёл: false, причина: `Брок: ${вариант._альтМетка}` })),
    ];

    logger.info("Брок: позиция обработана", {
      название: position.название,
      тип: п.тип,
      точных: точные.length,
      альтернатив: альтернативы.length,
    });
    return { variants: вЯчейку, оценённые };
  } catch (err) {
    logger.warn("Брок: ошибка при поиске по прайсу", { название: position?.название, error: err.message });
    return пусто;
  }
}

