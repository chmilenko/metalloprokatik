/**
 * scraper-brok/parse.js
 *
 * Разбор прайс-листов Брок Инвеста (brokinvest.ru/price-lists).
 *
 * Прайс разбит на файлы по категориям (лист г/к, трубы ВГП, арматура и т.д.).
 * В каждом файле: строка «Прайс актуален на: ДД.ММ.ГГГГ», шапка таблицы
 * (Название, Склад, Цена, ...размеры...) и строки по складам. Колонки у разных
 * категорий разные, поэтому ищем их по ЗАГОЛОВКУ, а не по номеру.
 *
 * Нас интересует только склад «СК Октябрьский»; цена «По запросу» — не цена,
 * такие строки пропускаем. Результат разбора строки — такая же структура
 * «разобрано», как у прайса Дипоса (см. scraper-dipos/parse.js), поэтому
 * сравнение с позицией заявки использует ту же логику.
 */

const fs = require("fs");
const XLSX = require("xlsx");
const { семействоСтали, НИЗКОЛЕГИРОВАННЫЕ } = require("../scraper-dipos/parse");

const СКЛАД = "СК Октябрьский";

// slug — часть имени файла «price-list-<slug>.xlsx» на сайте
const КАТЕГОРИИ = {
  listgoryachekatannij: { вид: "лист", видЛиста: "гк" },
  holodnokatannij: { вид: "лист", видЛиста: "хк" },
  ocinkovannij: { вид: "лист", видЛиста: "оц" },
  listsrifleniem: { вид: "лист", видЛиста: "гк", рифленый: true },
  vgp: { вид: "вгп" },
  esshp: { вид: "труба_эс" },
  profilnie: { вид: "труба_проф" },
  besshovnye: { вид: "труба_бш" },
  armatura: { вид: "арматура" },
  balka: { вид: "балка" },
  shveller: { вид: "швеллер" },
  ugol: { вид: "уголок" },
  prokat_kruglyj: { вид: "круг" },
  kvadrat: { вид: "квадрат" },
  polosa: { вид: "полоса" },
};

function число(x) {
  if (x == null || x === "") return null;
  if (typeof x === "number") return Number.isFinite(x) ? x : null;
  const n = parseFloat(String(x).replace(/[\s ]/g, "").replace(",", "."));
  return Number.isFinite(n) ? n : null;
}

function чистая(x) {
  return String(x == null ? "" : x)
    .replace(/[  ]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/** Колонка «Длина, мм»: число (мм) | null (нет длины / н/д) */
function длинаМм(x) {
  const n = число(x);
  return n != null && n >= 100 ? n : null;
}

/** Сталь: из колонки «Марка…», иначе ищем в названии. Возвращает {сырая, семейство}. */
function определитьСталь(марка, название) {
  let сырая = чистая(марка) || null;
  if (сырая && /^(рифленый|гладкий)$/i.test(сырая)) сырая = null; // у арматуры в этой колонке тип профиля
  if (!сырая) {
    const м =
      название.match(/(?:^|\s)(09Г2С|25Г2С|Ст\s?\d{1,2}(?:сп|пс|кп)?(?:\/пс)?\d?|С\s?3[45]5|С\s?2[45]5)(?=\s|$|,)/i);
    сырая = м ? м[1] : null;
  }
  if (!сырая) return { сырая: null, семейство: null };
  let семейство = семействоСтали(сырая);
  // С255/С245 — современное обозначение той же Ст3 (так считает и mc.ru)
  if (/^[сc]2[45]5/i.test(сырая.replace(/\s/g, ""))) семейство = "3";
  if (/^[сc]3[45]5/i.test(сырая.replace(/\s/g, ""))) {
    семейство = /^[сc]345/i.test(сырая.replace(/\s/g, "")) ? "с345" : "с355";
  }
  return { сырая, семейство };
}

function общее(название) {
  return {
    сорт2: /(^|\s)2\s*сорт/i.test(название) || /уценен/i.test(название),
    естьГост: /гост/i.test(название),
    естьТу: /(^|[\s,;])ту(?=[\s,;]|$)/i.test(название),
  };
}

/**
 * Разбор одной строки. колонки — { имяКолонки(нижний регистр): значение }
 * Возвращает «разобрано» либо null (строка в сравнении не участвует).
 */
function разобратьСтроку(slug, название, к) {
  const кат = КАТЕГОРИИ[slug];
  if (!кат) return null;
  const { сырая, семейство } = определитьСталь(к["марка стали"] ?? к["марка материала"], название);
  const базовая = { ...общее(название), стальСырая: сырая, сталь: семейство };
  const длина = длинаМм(к["длина, мм"]);
  const толщина = число(к["толщина, мм"]);

  if (кат.вид === "лист") {
    // рулоны, ленты и т.п. — не листы
    if (!/^лист\s/i.test(название)) return null;
    const ширина = число(к["ширина, мм"]);
    if (толщина == null || ширина == null) return null;
    return {
      ...базовая,
      тип: "лист",
      вид: кат.видЛиста,
      рифленый: !!кат.рифленый || /рифл/i.test(название),
      толщина,
      ширина,
      длинаЛиста: длина,
      низколегированный: НИЗКОЛЕГИРОВАННЫЕ.has(семейство),
    };
  }

  if (кат.вид === "вгп") {
    const ду = число(к["ду"]);
    if (ду == null || толщина == null) return null;
    return { ...базовая, тип: "труба_вгп", оцинк: /оцинк|(^|\s)оц(\s|$)/i.test(название), ду, стенка: толщина, длина };
  }

  if (кат.вид === "труба_эс") {
    // оцинкованные («ЭсвПШ ОЦ …») — другой, заметно более дорогой товар; в сравнение не берём
    if (/(^|\s)оц(\s|$)|оцинк/i.test(название)) return null;
    const диаметр = число(к["диаметр, мм"]);
    if (диаметр == null || толщина == null) return null;
    return { ...базовая, тип: "труба_эс", подТип: null, нержавеющая: /нерж/i.test(название), диаметр, стенка: толщина, длина };
  }

  if (кат.вид === "труба_бш") {
    const диаметр = число(к["диаметр, мм"]);
    if (диаметр == null || толщина == null) return null;
    const подТип = /г\/д/i.test(название) ? "г/д" : /х\/д/i.test(название) ? "х/д" : null;
    // длина в прайсе не указана («н/д») — как и у Дипоса, это только альтернатива
    return { ...базовая, тип: "труба_бш", подТип, нержавеющая: /нерж/i.test(название), диаметр, стенка: толщина, длина: null };
  }

  if (кат.вид === "труба_проф") {
    if (/оцинк|(^|\s)оц(\s|$)/i.test(название)) return null;
    const размер = чистая(к["размер профиля, мм"]).toLowerCase().replace(/х/g, "x");
    const м = размер.match(/^(\d+(?:[.,]\d+)?)\s*x\s*(\d+(?:[.,]\d+)?)$/);
    if (!м || толщина == null) return null;
    return { ...базовая, тип: "труба_проф", подТип: null, стороны: [число(м[1]), число(м[2])], стенка: толщина, длина };
  }

  if (кат.вид === "арматура") {
    const диаметр = число(к["размер, мм"]);
    if (диаметр == null) return null;
    const бухта = /бухт/i.test(название);
    // класс: А500С → А500С, А240С → А240, 25Г2С (ГОСТ 5781) → А400
    let класс = null;
    if (/А\s?500/i.test(название)) класс = "А500С";
    else if (/А\s?240/i.test(название)) класс = "А240";
    else if (/А\s?400|25Г2С/i.test(название)) класс = "А400";
    if (!класс) return null;
    return { ...базовая, тип: "арматура", класс, диаметр, бухта, длина: бухта ? null : длина, сталь: null };
  }

  if (кат.вид === "балка") {
    const м = название.match(/^балка\s+(\d+(?:[.,]\d+)?)\s*([А-ЯA-Z]{1,2}\d?)?\s*х/i);
    if (!м) return null;
    return {
      ...базовая,
      тип: "балка",
      низколегированная: НИЗКОЛЕГИРОВАННЫЕ.has(семейство),
      номер: число(м[1]),
      буква: м[2] ? м[2].toUpperCase() : null,
      длина,
    };
  }

  if (кат.вид === "швеллер") {
    // гнутый: «Швеллер Х/Г 100х50х3х12000 …» — размер в колонке «Размер»
    const гнутый = название.match(/^швеллер\s+х\/г\s+(\d+(?:[.,]\d+)?)\s*[хx]\s*(\d+(?:[.,]\d+)?)\s*[хx]\s*(\d+(?:[.,]\d+)?)\s*[хx]/i);
    if (гнутый) {
      return {
        ...базовая,
        тип: "швеллер_гнутый",
        низколегированный: НИЗКОЛЕГИРОВАННЫЕ.has(семейство),
        высота: число(гнутый[1]),
        полка: число(гнутый[2]),
        стенка: число(гнутый[3]),
        длина,
      };
    }
    const м = название.match(/^швеллер\s+(\d+(?:[.,]\d+)?)\s*([ПУЭЛ])?\s*х/i);
    if (!м) return null;
    return { ...базовая, тип: "швеллер", номер: число(м[1]), буква: м[2] ? м[2].toUpperCase() : null, длина };
  }

  if (кат.вид === "уголок") {
    const размер = чистая(к["размер полки, мм"]).toLowerCase().replace(/х/g, "x");
    const м = размер.match(/^(\d+(?:[.,]\d+)?)\s*x\s*(\d+(?:[.,]\d+)?)$/);
    if (!м || толщина == null) return null;
    return { ...базовая, тип: "уголок", a: число(м[1]), b: число(м[2]), стенка: толщина, длина };
  }

  if (кат.вид === "круг") {
    const диаметр = число(к["размер, мм"]);
    if (диаметр == null) return null;
    return { ...базовая, тип: "круг", калиброванный: /калибр/i.test(название), диаметр, длина };
  }

  if (кат.вид === "квадрат") {
    const м = чистая(к["размер, мм"]).toLowerCase().replace(/х/g, "x").match(/^(\d+(?:[.,]\d+)?)/);
    if (!м) return null;
    return { ...базовая, тип: "квадрат", калиброванный: /калибр/i.test(название), размер: число(м[1]), длина };
  }

  if (кат.вид === "полоса") {
    const ширина = число(к["ширина, мм"]);
    if (ширина == null || толщина == null) return null;
    return { ...базовая, тип: "полоса", вид: "гк", ширина, толщина, длина };
  }

  return null;
}

/**
 * Читает один xlsx-файл категории.
 * @returns {{датаПрайсаТекст, датаПрайса, позиции[], статистика, неРазобранные[]}}
 */
function разобратьФайл(путь, slug) {
  if (!КАТЕГОРИИ[slug]) throw new Error(`Неизвестная категория прайса Брок Инвеста: ${slug}`);
  if (!fs.existsSync(путь)) throw new Error(`Файл не найден: ${путь}`);
  const wb = XLSX.readFile(путь);
  const лист = wb.Sheets[wb.SheetNames[0]];
  if (!лист) throw new Error("В файле нет листов");
  const строки = XLSX.utils.sheet_to_json(лист, { header: 1, defval: "", raw: true });

  let датаПрайсаТекст = null;
  let датаПрайса = null;
  for (const r of строки.slice(0, 5)) {
    const м = String(r[0]).match(/(\d{2})\.(\d{2})\.(\d{4})/);
    if (м) {
      датаПрайсаТекст = `${м[1]}.${м[2]}.${м[3]}`;
      датаПрайса = `${м[3]}-${м[2]}-${м[1]}T00:00:00`;
      break;
    }
  }

  const пустой = строки.some((r) => /не найдено товаров/i.test(String(r[0])));
  const индексШапки = строки.findIndex(
    (r) => чистая(r[0]).toLowerCase() === "название" && чистая(r[1]).toLowerCase() === "склад",
  );
  if (индексШапки === -1) {
    if (пустой) return { датаПрайсаТекст, датаПрайса, позиции: [], статистика: { строкСклада: 0, сЦеной: 0, разобрано: 0, неРазобрано: 0 }, неРазобранные: [] };
    throw new Error("Формат прайса Брок Инвеста изменился: не найдена шапка «Название … Склад»");
  }
  const шапка = строки[индексШапки].map((h) => чистая(h).toLowerCase());
  const колЦена = шапка.indexOf("цена");
  if (колЦена === -1) throw new Error("В прайсе Брок Инвеста нет колонки «Цена»");

  const позиции = [];
  const статистика = { строкСклада: 0, сЦеной: 0, разобрано: 0, неРазобрано: 0 };
  const неРазобранные = [];

  for (let i = индексШапки + 1; i < строки.length; i++) {
    const r = строки[i];
    if (чистая(r[1]) !== СКЛАД) continue;
    статистика.строкСклада += 1;
    const цена = typeof r[колЦена] === "number" ? r[колЦена] : null; // «По запросу» — не цена
    if (цена == null || цена <= 0) continue;
    статистика.сЦеной += 1;

    const название = чистая(r[0]).replace(/(\d),(\d)/g, "$1.$2");
    const колонки = {};
    шапка.forEach((h, idx) => {
      if (h) колонки[h] = r[idx];
    });
    const разобрано = разобратьСтроку(slug, название, колонки);
    if (разобрано) статистика.разобрано += 1;
    else {
      статистика.неРазобрано += 1;
      неРазобранные.push(название);
    }
    позиции.push({ категория: slug, строка: i + 1, название, характеристика: "", цена, разобрано });
  }

  return { датаПрайсаТекст, датаПрайса, позиции, статистика, неРазобранные };
}

module.exports = { разобратьФайл, разобратьСтроку, КАТЕГОРИИ, СКЛАД };