/**
 * scraper-dipos/download.js
 *
 * Ежедневное скачивание прайс-листа Дипоса и его обновление в базе бота.
 *
 * Как достаём файл: открываем главную страницу dipos.ru и берём ссылку с
 * кнопки «Прайс-лист» (<a class="price-link" href="/price/price.xls?a=...">).
 * Параметр ?a= меняется (это метка времени), поэтому ссылку НЕ хардкодим, а
 * каждый раз читаем со страницы. Скачиваем отдельным экземпляром браузера —
 * общий браузер бота (mc.ru/КТЗ) не трогаем, чтобы не мешать заказам.
 *
 * Расписание: прайс выкладывают около 9:00 — обновляем в 9:20 (по времени
 * процесса; на сервере стоит Europe/Moscow), при неудаче повторяем через
 * 30 минут, после четвёртой неудачи пишем администратору. При старте бота,
 * если прайса нет или он старше последнего ожидаемого обновления, качаем сразу.
 */

const fs = require("fs");
const path = require("path");
const logger = require("../utils/logger");
const { обновитьИзФайла, инфоОПрайсе, ФАЙЛ_ПРАЙСА_ЭКСЕЛЬ } = require("./index");

const АДРЕС_САЙТА = process.env.DIPOS_URL || "https://dipos.ru/";
const ЧАС_ОБНОВЛЕНИЯ = 9;
const МИНУТА_ОБНОВЛЕНИЯ = 20;
const ПОВТОР_ЧЕРЕЗ_МС = 30 * 60 * 1000;
const МАКС_ПОПЫТОК_ПОДРЯД = 4;
const МИН_РАЗМЕР_ФАЙЛА = 20 * 1024; // настоящий прайс — сотни КБ; меньше — это страница с ошибкой

let идётОбновление = false;

function этоФайлЭксель(буфер) {
  if (!буфер || буфер.length < 8) return false;
  const oleСтарыйФормат = буфер[0] === 0xd0 && буфер[1] === 0xcf && буфер[2] === 0x11 && буфер[3] === 0xe0;
  const zipНовыйФормат = буфер[0] === 0x50 && буфер[1] === 0x4b;
  return oleСтарыйФормат || zipНовыйФормат;
}

/**
 * Скачивает файл прайса в downloads/dipos-price.xls. Возвращает путь.
 * @param {{видимыйБраузер?: boolean}} опции
 */
async function скачатьФайл({ видимыйБраузер = false } = {}) {
  const { chromium } = require("playwright");
  const браузер = await chromium.launch({ headless: !видимыйБраузер });
  try {
    const контекст = await браузер.newContext({ acceptDownloads: true });
    const страница = await контекст.newPage();
    await страница.goto(АДРЕС_САЙТА, { waitUntil: "domcontentloaded", timeout: 60000 });

    const ссылка = страница.locator('a[href*="price.xls"], a.price-link').first();
    await ссылка.waitFor({ state: "attached", timeout: 30000 });
    const href = await ссылка.getAttribute("href");
    if (!href) throw new Error("У кнопки «Прайс-лист» нет ссылки (href)");
    const адресФайла = new URL(href, страница.url()).toString();

    let буфер = null;
    try {
      const ответ = await контекст.request.get(адресФайла, { timeout: 120000 });
      if (ответ.ok()) буфер = await ответ.body();
      else logger.warn("Дипос: прямое скачивание вернуло ошибку, пробую через клик", { статус: ответ.status() });
    } catch (err) {
      logger.warn("Дипос: прямое скачивание не удалось, пробую через клик", { error: err.message });
    }

    if (!этоФайлЭксель(буфер)) {
      // запасной путь — как это сделал бы человек: нажать кнопку и принять загрузку
      try {
        const [загрузка] = await Promise.all([
          страница.waitForEvent("download", { timeout: 30000 }),
          ссылка.click({ timeout: 30000 }),
        ]);
        буфер = fs.readFileSync(await загрузка.path());
      } catch (err) {
        throw new Error(`сайт не отдал файл прайса (по ссылке пришла не таблица Excel): ${err.message.split("\n")[0]}`);
      }
    }

    if (!этоФайлЭксель(буфер) || буфер.length < МИН_РАЗМЕР_ФАЙЛА) {
      throw new Error(`Скачан не прайс (размер ${буфер ? буфер.length : 0} байт, это не Excel-файл)`);
    }

    const папка = path.dirname(ФАЙЛ_ПРАЙСА_ЭКСЕЛЬ);
    if (!fs.existsSync(папка)) fs.mkdirSync(папка, { recursive: true });
    const времянка = `${ФАЙЛ_ПРАЙСА_ЭКСЕЛЬ}.tmp`;
    fs.writeFileSync(времянка, буфер);
    fs.renameSync(времянка, ФАЙЛ_ПРАЙСА_ЭКСЕЛЬ);
    return ФАЙЛ_ПРАЙСА_ЭКСЕЛЬ;
  } finally {
    await браузер.close().catch(() => {});
  }
}

/**
 * Скачать + разобрать + сохранить. Сначала без окна браузера, при неудаче —
 * ещё раз с видимым окном (на случай, если сайт не любит headless).
 * Бросает ошибку, если не вышло; прежний прайс при этом остаётся.
 */
async function обновитьПрайс() {
  if (идётОбновление) throw new Error("Обновление прайса Дипоса уже идёт");
  идётОбновление = true;
  try {
    let файл;
    try {
      файл = await скачатьФайл({ видимыйБраузер: process.env.DIPOS_HEADED === "1" });
    } catch (err) {
      logger.warn("Дипос: скачивание без окна не удалось, пробую с окном", { error: err.message });
      try {
        файл = await скачатьФайл({ видимыйБраузер: true });
      } catch (err2) {
        // главная причина — в первой попытке, вторая часто падает по своим причинам (нет экрана)
        throw new Error(`${err.message.split("\n")[0]} (повтор с окном тоже не удался: ${err2.message.split("\n")[0]})`);
      }
    }
    return обновитьИзФайла(файл);
  } finally {
    идётОбновление = false;
  }
}

// ───────────────────────── расписание ─────────────────────────

function следующийЗапуск(сейчас = new Date()) {
  const t = new Date(сейчас);
  t.setHours(ЧАС_ОБНОВЛЕНИЯ, МИНУТА_ОБНОВЛЕНИЯ, 0, 0);
  if (t.getTime() <= сейчас.getTime()) t.setDate(t.getDate() + 1);
  return t;
}

// Последний момент, к которому свежий прайс уже должен был появиться
function последнийОжидаемыйМомент(сейчас = new Date()) {
  const t = new Date(сейчас);
  t.setHours(ЧАС_ОБНОВЛЕНИЯ, 0, 0, 0); // прайс выкладывают в 9:00
  if (t.getTime() > сейчас.getTime()) t.setDate(t.getDate() - 1);
  return t;
}

function нужноСкачатьПриСтарте() {
  const инфо = инфоОПрайсе();
  if (!инфо.есть) return true;
  // Смотрим на момент последнего УДАЧНОГО скачивания, а не на дату внутри файла:
  // Дипос выкладывает прайс не каждый день, и иначе бот перекачивал бы один и
  // тот же файл при каждом запуске.
  const скачан = инфо.скачан ? Date.parse(инфо.скачан) : 0;
  return скачан < последнийОжидаемыйМомент().getTime();
}

/**
 * Запускает ежедневное обновление. Вызывать один раз при старте бота.
 * @param {{уведомить?: (текст:string)=>Promise<any>}} опции
 */
function запуститьЕжедневноеОбновление({ уведомить = null } = {}) {
  const сказать = async (текст) => {
    if (!уведомить) return;
    try {
      await уведомить(текст);
    } catch (err) {
      logger.error("Дипос: не удалось отправить уведомление", { error: err.message });
    }
  };

  async function попытка(номер) {
    try {
      const р = await обновитьПрайс();
      logger.info("Дипос: плановое обновление прайса прошло", { дата: р.датаПрайсаТекст });
      if (номер > 1) await сказать(`✅ Прайс Дипоса обновлён (от ${р.датаПрайсаТекст}) — со ${номер}-й попытки.`);
      return true;
    } catch (err) {
      logger.error("Дипос: не удалось обновить прайс", { попытка: номер, error: err.message });
      if (номер >= МАКС_ПОПЫТОК_ПОДРЯД) {
        const инфо = инфоОПрайсе();
        await сказать(
          `⚠️ Не удалось обновить прайс Дипоса (${номер} попытки подряд): ${err.message}\n` +
            (инфо.есть ? `Использую прежний — от ${инфо.датаПрайсаТекст}.` : "Прайса нет — колонки «Дипос» в таблице не будет."),
        );
        return true; // больше не долбим до следующего дня
      }
      setTimeout(() => попытка(номер + 1), ПОВТОР_ЧЕРЕЗ_МС).unref?.();
      return false;
    }
  }

  function назначить() {
    const когда = следующийЗапуск();
    const мс = когда.getTime() - Date.now();
    logger.info("Дипос: следующее обновление прайса", { когда: когда.toISOString() });
    setTimeout(async () => {
      await попытка(1);
      назначить();
    }, мс).unref?.();
  }

  назначить();

  if (нужноСкачатьПриСтарте()) {
    // чуть позже старта, чтобы не мешать запуску бота
    setTimeout(() => попытка(1), 15000).unref?.();
  }
}

module.exports = {
  обновитьПрайс,
  скачатьФайл,
  запуститьЕжедневноеОбновление,
  следующийЗапуск,
  последнийОжидаемыйМомент,
  нужноСкачатьПриСтарте,
  этоФайлЭксель,
};