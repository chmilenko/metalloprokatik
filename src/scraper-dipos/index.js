const path = require("path");
const logger = require("../utils/logger");
const { разобратьПрайс, семействоСтали, НИЗКОЛЕГИРОВАННЫЕ, число } = require("./parse");

const ПРЕФИКС_СКЛАДА = "Дипос: ";
const БАЗА = `${ПРЕФИКС_СКЛАДА}Москва`;

const ПАПКА_ДАННЫХ = path.join(__dirname, "../../data");
const ФАЙЛ_ПРАЙСА_ДАННЫЕ = path.join(ПАПКА_ДАННЫХ, "dipos-price.json");
const ПАПКА_ЗАГРУЗОК = path.join(__dirname, "../../downloads");
const ФАЙЛ_ПРАЙСА_ЭКСЕЛЬ = path.join(ПАПКА_ЗАГРУЗОК, "dipos-price.xls");

// Прайс публикуется утром (~09:00) — старше этого срока считаем устаревшим
// и предупреждаем в подписи к Excel, а не молча сравниваем со вчерашним.
const УСТАРЕЛ_ЧАСОВ = 36;
const МАКС_ЦЕН_В_ЯЧЕЙКЕ = 3;
const МАКС_АЛЬТЕРНАТИВ = 8;

// ───────────────────────── хранилище ─────────────────────────

let кэш = { mtime: 0, данные: null };

function получитьПрайс() {
  if (!fs.existsSync(ФАЙЛ_ПРАЙСА_ДАННЫЕ)) return null;
  const mtime = fs.statSync(ФАЙЛ_ПРАЙСА_ДАННЫЕ).mtimeMs;
  if (кэш.данные && кэш.mtime === mtime) return кэш.данные;
  try {
    const данные = JSON.parse(fs.readFileSync(ФАЙЛ_ПРАЙСА_ДАННЫЕ, "utf-8"));
    кэш = { mtime, данные };
    return данные;
  } catch (err) {
    logger.error("Дипос: не удалось прочитать сохранённый прайс", { error: err.message });
    return null;
  }
}

function инфоОПрайсе() {
  const прайс = получитьПрайс();
  if (!прайс) return { есть: false };
  const времяПрайса = прайс.датаПрайса ? new Date(прайс.датаПрайса).getTime() : null;
  const возрастЧасов = времяПрайса ? (Date.now() - времяПрайса) / 3600000 : null;
  return {
    есть: true,
    датаПрайсаТекст: прайс.датаПрайсаТекст,
    скачан: прайс.скачан,
    возрастЧасов,
    устарел: возрастЧасов == null ? true : возрастЧасов > УСТАРЕЛ_ЧАСОВ,
    позиций: прайс.позиции.length,
    разобрано: прайс.позиции.filter((п) => п.разобрано).length,
  };
}

/**
 * Разбирает скачанный xls и сохраняет JSON. Если разобралось подозрительно
 * мало (формат прайса изменился) — бросает ошибку и НЕ затирает прошлый
 * рабочий прайс.
 */
function обновитьИзФайла(путьФайла = ФАЙЛ_ПРАЙСА_ЭКСЕЛЬ) {
  const результат = разобратьПрайс(путьФайла);
  const { статистика } = результат;
  const кСравнению = статистика.разобрано + статистика.неРазобрано;
  if (кСравнению < 100 || статистика.разобрано / кСравнению < 0.7) {
    throw new Error(
      `Прайс Дипоса разобрался подозрительно плохо (разобрано ${статистика.разобрано} из ${кСравнению}) — ` +
        `формат файла, вероятно, изменился. Прежний прайс оставлен без изменений.`,
    );
  }
  if (!fs.existsSync(ПАПКА_ДАННЫХ)) fs.mkdirSync(ПАПКА_ДАННЫХ, { recursive: true });
  const данные = {
    датаПрайса: результат.датаПрайса,
    датаПрайсаТекст: результат.датаПрайсаТекст,
    скачан: new Date().toISOString(),
    статистика,
    позиции: результат.позиции,
  };
  const времянка = `${ФАЙЛ_ПРАЙСА_ДАННЫЕ}.tmp`;
  fs.writeFileSync(времянка, JSON.stringify(данные));
  fs.renameSync(времянка, ФАЙЛ_ПРАЙСА_ДАННЫЕ); // атомарно, как и остальные файлы состояния
  кэш = { mtime: 0, данные: null };
  logger.info("Дипос: прайс обновлён", { дата: результат.датаПрайсаТекст, ...статистика });
  return { датаПрайсаТекст: результат.датаПрайсаТекст, статистика, неРазобранные: результат.неРазобранные };
}

// ───────────────────────── разбор позиции заявки ─────────────────────────

function естьСлово(текст, слово) {
  const экр = слово.replace(/[.*+?^${}()|[\]\\\/]/g, "\\$&");
  return new RegExp(`(?<![а-яa-z0-9])${экр}(?![а-яa-z])`, "i").test(текст);
}

function классАрматуры(сырой) {
  if (!сырой) return null;
  const т = String(сырой).toLowerCase().replace(/ё/g, "е").replace(/\s/g, "");
  if (т.includes("240") || т === "а1") return "А240";
  if (т.includes("400") || т === "а3") return "А400";
  if (т.includes("500")) return "А500С";
  return null;
}

function разобратьПозицию(position) {
  const п = position.параметры || {};
  const текст = `${position.поисковый_запрос || ""} ${position.название || ""}`
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/(\d),(\d)/g, "$1.$2");

  const спец = п.спецификация || {};
  const общее = {
    текст,
    маркаСырая: п.марка || null,
    сталь: п.марка ? семействоСтали(п.марка) : null,
    низколегированныйЗапрос: текст.includes("низколег"),
    длина: п.длина != null ? Number(п.длина) : null,
    хотятТу: спец.приоритет === "ТУ" || нужныОбаЕсть(спец),
  };

  const вид = () => {
    if (текст.includes("оцинк")) return "оц";
    if (/х\/к|холоднокат/.test(текст)) return "хк";
    if (/г\/к|горячекат|мостостр/.test(текст)) return "гк";
    return null;
  };

  if (естьСлово(текст, "вгп") || текст.includes("водогазопровод")) {
    if (п.ду == null || п.стенка == null) return null;
    return { ...общее, тип: "труба_вгп", ду: Number(п.ду), стенка: Number(п.стенка), оцинк: текст.includes("оцинк") };
  }

  if (естьСлово(текст, "труба") || естьСлово(текст, "трубы")) {
    if (текст.includes("овальн")) return null;
    if (п.диаметр == null && п.ширина != null && п.стенка != null) {
      const вторая = п.длина_листа != null ? Number(п.длина_листа) : Number(п.ширина);
      return { ...общее, тип: "труба_проф", стороны: [Number(п.ширина), вторая], стенка: Number(п.стенка) };
    }
    if (п.диаметр != null && п.стенка != null) {
      let подТип = null;
      if (/г\/д|горячедеформ|бесшов/.test(текст)) подТип = "бш_гд";
      else if (/х\/д|холоднодеформ/.test(текст)) подТип = "бш_хд";
      return {
        ...общее,
        тип: "труба_круглая",
        подТип, // null — электросварная по умолчанию
        нержавеющая: текст.includes("нержав"),
        диаметр: Number(п.диаметр),
        стенка: Number(п.стенка),
      };
    }
    return null;
  }

  if (естьСлово(текст, "арматура")) {
    if (п.диаметр == null) return null;
    const класс = классАрматуры(п.марка) || классАрматуры((текст.match(/а\s?(?:240|400|500)|(?<![а-я0-9])а[13](?![0-9])/) || [])[0]);
    return { ...общее, тип: "арматура", диаметр: Number(п.диаметр), класс, хотятБухту: текст.includes("бухт") };
  }

  if (естьСлово(текст, "круг")) {
    if (п.диаметр == null) return null;
    return { ...общее, тип: "круг", диаметр: Number(п.диаметр) };
  }

  if (естьСлово(текст, "квадрат")) {
    const размер = п.номер ?? п.диаметр ?? п.ширина;
    if (размер == null) return null;
    return { ...общее, тип: "квадрат", размер: Number(размер) };
  }

  if (естьСлово(текст, "шестигранник")) {
    const размер = п.номер ?? п.диаметр ?? п.ширина;
    if (размер == null) return null;
    return { ...общее, тип: "шестигранник", размер: Number(размер) };
  }

  if (естьСлово(текст, "уголок")) {
    if (п.номер == null || п.стенка == null) return null;
    return { ...общее, тип: "уголок", a: Number(п.номер), b: Number(п.ширина ?? п.номер), стенка: Number(п.стенка) };
  }

  if (естьСлово(текст, "швеллер")) {
    if (текст.includes("гнут")) {
      if (п.номер == null || п.ширина == null || п.стенка == null) return null;
      return { ...общее, тип: "швеллер_гнутый", высота: Number(п.номер), полка: Number(п.ширина), стенка: Number(п.стенка) };
    }
    if (п.номер == null) return null;
    const б = текст.match(/швеллер\s*(?:низколегированный\s*)?\d+(?:\.\d+)?\s*([пуэл])(?![а-яa-z])/);
    return { ...общее, тип: "швеллер", номер: Number(п.номер), буква: б ? б[1].toUpperCase() : null };
  }

  if (естьСлово(текст, "балка") || естьСлово(текст, "двутавр")) {
    if (п.номер == null) return null;
    const б = текст.match(/(?:балка|двутавр)\s*(?:низколегированная\s*)?\d+(?:\.\d+)?\s*([бкш]\d?)(?![а-яa-z])/);
    return { ...общее, тип: "балка", номер: Number(п.номер), буква: б ? б[1].toUpperCase() : null };
  }

  if (естьСлово(текст, "полоса")) {
    if (п.ширина == null || п.толщина == null) return null;
    return { ...общее, тип: "полоса", вид: вид() || "гк", ширина: Number(п.ширина), толщина: Number(п.толщина) };
  }

  if (текст.includes("пвл") || текст.includes("просечно") || текст.includes("вытяжн")) {
    if (п.номер == null) return null;
    return {
      ...общее,
      тип: "лист_пв",
      номер: Number(п.номер),
      ширина: п.ширина != null ? Number(п.ширина) : null,
      длинаЛиста: п.длина_листа != null ? Number(п.длина_листа) : null,
    };
  }

  if (естьСлово(текст, "лист")) {
    if (текст.includes("нержав") || п.толщина == null || п.ширина == null) return null;
    return {
      ...общее,
      тип: "лист",
      вид: вид(),
      рифленый: текст.includes("рифл"),
      толщина: Number(п.толщина),
      ширина: Number(п.ширина),
      длинаЛиста: п.длина_листа != null ? Number(п.длина_листа) : null,
    };
  }

  return null; // форма не поддерживается Дипосом/не распознана — не сравниваем
}

function нужныОбаЕсть(спец) {
  return !!спец.нужны_оба;
}

// ───────────────────────── сравнение ─────────────────────────

const равно = (a, b) => a != null && b != null && Math.abs(a - b) < 0.001;

function м(мм) {
  return `${Math.round((мм / 1000) * 10) / 10}м`;
}

/**
 * Длина: возвращает null (подходит) или метку (мягкое отличие).
 * @param {number|null} нужная — длина из заявки, мм
 * @param {number|{от,до}|null} у — длина в прайсе (null = «н/д»)
 */
function сравнитьДлину(нужная, у, { листы = false } = {}) {
  // «н/д» в прайсе Дипоса — это, как правило, немерные остатки/лоты (средняя
  // цена таких строк заметно ниже мерных), поэтому они НИКОГДА не считаются
  // точным совпадением — только оранжевой альтернативой с пометкой.
  if (у == null) return "длина н/д";
  if (нужная == null) return null;
  if (typeof у === "object") {
    if (нужная >= у.от && нужная <= у.до) return null;
    return `${м(у.от)}–${м(у.до)}`;
  }
  if (равно(нужная, у)) return null;
  return листы ? `${у}мм` : м(у);
}

/**
 * Сталь: "ok" | "мягко:<метка>" | "жёстко"
 */
function сравнитьСталь(п, р, { разрешитьБелыйСписокКруга = false, пропуститьПроверку = false } = {}) {
  if (пропуститьПроверку) return "ok";

  const низколегПозиции = п.низколегированныйЗапрос;
  const низколегПрайса = НИЗКОЛЕГИРОВАННЫЕ.has(р.сталь) || !!р.низколегированная || !!р.низколегированный;

  if (п.сталь == null) {
    // марка в заявке не задана
    if (низколегПозиции) {
      if (!р.сталь) return "мягко:сталь не указана";
      return низколегПрайса ? "ok" : "жёстко";
    }
    return "ok";
  }

  if (р.сталь == null) return "мягко:сталь не указана";
  if (р.сталь === п.сталь) return "ok";

  // Круг: Ст3 по умолчанию, но если её нет — Ст10/Ст20 допустимая замена
  // (то же правило, что в поиске по mc.ru)
  if (разрешитьБелыйСписокКруга && п.сталь === "3" && (р.сталь === "10" || р.сталь === "20")) {
    return `мягко:Ст${р.сталь}`;
  }
  return "жёстко";
}

/**
 * Сравнивает позицию заявки с разобранной строкой прайса.
 * Возвращает null (не подходит) либо { метки: [...] } — пустые метки =
 * точное совпадение.
 */
function сравнить(п, р, строка) {
  if (!р) return null;
  const метки = [];
  const мягко = (метка) => {
    if (метка && !метки.includes(метка)) метки.push(метка);
  };

  let тип = п.тип;
  if (тип === "труба_круглая") {
    if (р.тип === "труба_эс") {
      if (п.подТип) return null; // просили бесшовную — электросварную не предлагаем
      if (!!р.нержавеющая !== !!п.нержавеющая) return null;
    } else if (р.тип === "труба_бш") {
      if (п.подТип === "бш_гд" && р.подТип !== "г/д") return null;
      if (п.подТип === "бш_хд" && р.подТип !== "х/д") return null;
      if (!п.подТип) return null;
    } else return null;
    if (!равно(п.диаметр, р.диаметр) || !равно(п.стенка, р.стенка)) return null;
    const ст = сравнитьСталь(п, р, { пропуститьПроверку: !п.маркаСырая }); // у круглых труб «марка» заявки — это стенка/пусто
    if (ст === "жёстко") return null;
    if (ст.startsWith("мягко:")) мягко(ст.slice(6));
    мягко(сравнитьДлину(п.длина, р.длина));
  } else {
    if (р.тип !== тип) return null;

    if (тип === "труба_проф") {
      const [а1, б1] = [...п.стороны].sort((x, y) => x - y);
      const [а2, б2] = [...р.стороны].sort((x, y) => x - y);
      if (!равно(а1, а2) || !равно(б1, б2) || !равно(п.стенка, р.стенка)) return null;
      const ст = сравнитьСталь(п, р, { пропуститьПроверку: !п.маркаСырая });
      if (ст === "жёстко") return null;
      if (ст.startsWith("мягко:")) мягко(ст.slice(6));
      мягко(сравнитьДлину(п.длина, р.длина));
    } else if (тип === "труба_вгп") {
      if (!равно(п.ду, р.ду) || !равно(п.стенка, р.стенка) || !!п.оцинк !== !!р.оцинк) return null;
      мягко(сравнитьДлину(п.длина, р.длина));
    } else if (тип === "арматура") {
      if (!равно(п.диаметр, р.диаметр)) return null;
      if (п.класс && р.класс !== п.класс) {
        const периодические = ["А400", "А500С"];
        if (периодическиеОба(периодические, п.класс, р.класс)) мягко(р.класс);
        else return null;
      }
      if (р.бухта && !п.хотятБухту) мягко("бухта");
      else мягко(сравнитьДлину(п.длина, р.длина));
    } else if (тип === "круг") {
      if (!равно(п.диаметр, р.диаметр)) return null;
      const ст = сравнитьСталь(п, р, { разрешитьБелыйСписокКруга: true });
      if (ст === "жёстко") return null;
      if (ст.startsWith("мягко:")) мягко(ст.slice(6));
      мягко(сравнитьДлину(п.длина, р.длина));
    } else if (тип === "квадрат" || тип === "шестигранник") {
      if (!равно(п.размер, р.размер)) return null;
      const ст = сравнитьСталь(п, р);
      if (ст === "жёстко") return null;
      if (ст.startsWith("мягко:")) мягко(ст.slice(6));
      мягко(сравнитьДлину(п.длина, р.длина));
    } else if (тип === "полоса") {
      if (!равно(п.ширина, р.ширина) || !равно(п.толщина, р.толщина)) return null;
      if (п.вид !== р.вид) return null;
      const ст = сравнитьСталь(п, р);
      if (ст === "жёстко") return null;
      if (ст.startsWith("мягко:")) мягко(ст.slice(6));
      мягко(сравнитьДлину(п.длина, р.длина));
    } else if (тип === "уголок") {
      if (!равно(п.a, р.a) || !равно(п.b, р.b) || !равно(п.стенка, р.стенка)) return null;
      const ст = сравнитьСталь(п, р);
      if (ст === "жёстко") return null;
      if (ст.startsWith("мягко:")) мягко(ст.slice(6));
      мягко(сравнитьДлину(п.длина, р.длина));
    } else if (тип === "швеллер") {
      if (!равно(п.номер, р.номер)) return null;
      if (п.буква) {
        if (!р.буква) мягко("без индекса");
        else if (р.буква !== п.буква) return null;
      }
      const ст = сравнитьСталь(п, р);
      if (ст === "жёстко") return null;
      if (ст.startsWith("мягко:")) мягко(ст.slice(6));
      мягко(сравнитьДлину(п.длина, р.длина));
    } else if (тип === "швеллер_гнутый") {
      if (!равно(п.высота, р.высота) || !равно(п.полка, р.полка) || !равно(п.стенка, р.стенка)) return null;
      // марка у гнутого швеллера в заявке не ставится (null), низколегированность — по слову
      const ст = сравнитьСталь(п, р);
      if (ст === "жёстко") return null;
      if (ст.startsWith("мягко:")) мягко(ст.slice(6));
      мягко(сравнитьДлину(п.длина, р.длина));
    } else if (тип === "балка") {
      if (!равно(п.номер, р.номер)) return null;
      if (п.буква && р.буква !== п.буква) return null;
      const ст = сравнитьСталь(п, р);
      if (ст === "жёстко") return null;
      if (ст.startsWith("мягко:")) мягко(ст.slice(6));
      мягко(сравнитьДлину(п.длина, р.длина));
    } else if (тип === "лист") {
      if (!равно(п.толщина, р.толщина) || !равно(п.ширина, р.ширина)) return null;
      if (п.вид && п.вид !== р.вид) return null;
      if (!!п.рифленый !== !!р.рифленый) return null;
      // оцинкованный лист стали в названии не имеет — сталь не проверяем
      const ст = сравнитьСталь(п, р, { пропуститьПроверку: р.вид === "оц" });
      if (ст === "жёстко") return null;
      if (ст.startsWith("мягко:")) мягко(ст.slice(6));
      мягко(сравнитьДлину(п.длинаЛиста, р.длинаЛиста, { листы: true }));
    } else if (тип === "лист_пв") {
      if (!равно(п.номер, р.номер)) return null;
      if (п.ширина != null && !равно(п.ширина, р.ширина)) return null;
      мягко(сравнитьДлину(п.длинаЛиста, р.длинаЛиста, { листы: true }));
    } else return null;
  }

  if (р.сорт2) мягко("2 сорт");
  if (р.естьТу && !р.естьГост && !п.хотятТу) мягко("ТУ");

  return { метки };
}

function периодическиеОба(список, а, б) {
  return список.includes(а) && список.includes(б);
}

function вВариант(строка, метки) {
  const р = строка.разобрано;
  const длинаПоле =
    typeof (р.длина ?? р.длинаЛиста) === "number"
      ? String(р.длина ?? р.длинаЛиста)
      : р.длина && typeof р.длина === "object"
        ? `${р.длина.от}-${р.длина.до}`
        : р.длинаЛиста && typeof р.длинаЛиста === "object"
          ? `${р.длинаЛиста.от}-${р.длинаЛиста.до}`
          : "н/д";
  return {
    название: строка.характеристика ? `${строка.название}, ${строка.характеристика}` : строка.название,
    смц: БАЗА,
    длина: длинаПоле,
    марка: р.стальСырая || null,
    цена_от_1т: строка.цена,
    cardUrl: null,
    sourceUrl: null,
    _дипос: true,
    _строкаПрайса: строка.строка,
    _альтернатива: метки.length > 0,
    _альтМетка: метки.join(", "),
  };
}

/**
 * Главная функция: ищет позицию заявки в прайсе Дипоса.
 * Никогда не бросает исключение наружу — при проблеме логирует и возвращает
 * пустой результат (поиск на mc.ru/КТЗ от этого не должен страдать).
 */
function найдиВДипосе(position) {
  const пусто = { variants: [], оценённые: [] };
  try {
    const прайс = получитьПрайс();
    if (!прайс) return пусто;
    const п = разобратьПозицию(position);
    if (!п) return пусто;

    const точные = [];
    const альтернативы = [];
    for (const строка of прайс.позиции) {
      if (!строка.разобрано) continue;
      const итог = сравнить(п, строка.разобрано, строка);
      if (!итог) continue;
      const вариант = вВариант(строка, итог.метки);
      (итог.метки.length === 0 ? точные : альтернативы).push(вариант);
    }

    // Как и в сводной для mc.ru: если есть точные с определённой длиной —
    // «н/д» не показываем; берём не больше трёх самых дешёвых цен.
    const определённые = точные.filter((v) => /^\d+$/.test(v.длина));
    const пул = определённые.length > 0 ? определённые : точные;
    const вЯчейку = [];
    const видели = new Set();
    for (const v of [...пул].sort((a, b) => a.цена_от_1т - b.цена_от_1т)) {
      if (видели.has(v.цена_от_1т)) continue;
      видели.add(v.цена_от_1т);
      вЯчейку.push(v);
      if (вЯчейку.length >= МАКС_ЦЕН_В_ЯЧЕЙКЕ) break;
    }

    const альтернативыКоротко = [...альтернативы]
      .sort((a, b) => a.цена_от_1т - b.цена_от_1т)
      .slice(0, МАКС_АЛЬТЕРНАТИВ);

    const оценённые = [
      ...точные.map((вариант) => ({ вариант, прошёл: true, причина: "" })),
      ...альтернативыКоротко.map((вариант) => ({ вариант, прошёл: false, причина: `Дипос: ${вариант._альтМетка}` })),
    ];

    logger.info("Дипос: позиция обработана", {
      название: position.название,
      тип: п.тип,
      точных: точные.length,
      альтернатив: альтернативы.length,
    });
    return { variants: вЯчейку, оценённые };
  } catch (err) {
    logger.warn("Дипос: ошибка при поиске по прайсу", { название: position?.название, error: err.message });
    return пусто;
  }
}

