/**
 * scraper-dipos/index.js
 *
 * Дипос — поставщик, у которого НЕТ корзины: берём только его прайс-лист
 * (скачивается раз в сутки, см. download.js) и показываем цену в сводной
 * таблице рядом с mc.ru и КТЗ — ИСКЛЮЧИТЕЛЬНО ДЛЯ СРАВНЕНИЯ. Заказать через
 * Дипос бот не может, поэтому /order эту колонку не предлагает.
 *
 * Формат результата — тот же, что у найдиНаКТЗ(): { variants, оценённые }.
 *   variants   — точные совпадения (не больше 3 самых дешёвых цен)
 *   оценённые  — все рассмотренные кандидаты: прошёл=true — точное,
 *                прошёл=false с вариант._альтМетка — «близкая альтернатива»
 *                (другая длина/ТУ/2 сорт/сталь не указана и т.п.). Кандидаты,
 *                не подошедшие по размеру/форме, в результат не попадают.
 *
 * Принципы те же, что у остальных поисков: размер/форма/толщина — жёстко
 * (иначе это другой товар), длина/ТУ/сорт — мягко (альтернатива с пометкой).
 */

