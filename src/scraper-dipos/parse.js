/**
 * scraper-dipos/parse.js
 *
 * Разбор прайс-листа Дипоса (price.xls) в структурированные позиции.
 *
 * Формат файла: 5 колонок — Номенклатура, Характеристика, Единица
 * измерения, Цена, Валюта. Категории идут отдельными строками-заголовками
 * (без цены), позиции — строками с ценой. Все параметры товара зашиты в
 * строку названия («Труба проф. г/к 100х60х5.0х12000, ст3сп/пс-5, ГОСТ ...»),
 * поэтому разбираем её регулярками — LLM здесь не нужен.
 *
 * Принцип: если строку не удалось разобрать уверенно — тип = null, и такая
 * позиция в сравнении не участвует (лучше промолчать, чем сравнить с чужим
 * товаром). Сколько строк разобрано/не разобрано — см. статистику в
 * разобратьПрайс().
 */

const fs = require("fs");
const XLSX = require("xlsx");

const ЧИСЛО = "(\\d+(?:[.,]\\d+)?)";

function число(строка) {
  if (строка == null) return null;
  const n = parseFloat(String(строка).replace(",", "."));
  return Number.isFinite(n) ? n : null;
}

function чистая(строка) {
  return String(какЕсть(строка))
    .replace(/[   ]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}
function какЕсть(x) {
  return x == null ? "" : x;
}

/**
 * Длина из прайса: число (мм) | { от, до } для диапазона | null для «н/д».
 * Бухты — отдельный признак (бухта: true), не длина.
 */
function разобратьДлину(текст) {
  if (текст == null) return null;
  const т = String(текст).trim().toLowerCase();
  if (!т || т.includes("н/д")) return null;
  const диапазон = т.match(/^(\d{3,5})\s*-\s*(\d{3,5})$/);
  if (диапазон) return { от: +диапазон[1], до: +диапазон[2] };
  const одно = т.match(/^(\d{3,5})$/);
  if (одно) return +одно[1];
  return null;
}

/**
 * Семейство стали — чтобы «ст3сп/пс-5», «ст3пс», «ст1-3сп/пс» и «Ст3»
 * считались одной маркой, а «ст3» и «ст20» — разными.
 * Возвращает строку-ключ или null, если марка не указана.
 */
function семействоСтали(сырая) {
  if (сырая == null) return null;
  let с = String(сырая).toLowerCase().replace(/ё/g, "е").replace(/\s+/g, "").replace(/,+$/g, "");
  if (!с) return null;
  с = с.replace(/^ст(?=[0-9a-zа-я])/, ""); // «ст3сп» → «3сп», «стС355» → «с355»
  if (/^aisi/.test(с)) return с.replace(/^aisi/, "");
  if (/^1-3/.test(с)) return "3"; // Ст1-3 на сайтах = Ст3 (так же считает mc.ru)
  if (/^1-2/.test(с)) return "1-2";
  if (/^3(сп|пс|кп|-|\/|$)/.test(с)) return "3";
  if (/^08/.test(с)) return "08";
  if (/^09г2с/.test(с)) return "09г2с";
  if (/^(с|c)?345/.test(с)) return "с345";
  if (/^(с|c)355/.test(с) || /^s355/.test(с)) return "с355";
  const м = с.match(/^(\d{2}[а-я0-9]*?)(?=сп|пс|кп|-|\/|$)/);
  if (м) return м[1];
  return с;
}

const НИЗКОЛЕГИРОВАННЫЕ = new Set(["09г2с", "с345", "с355"]);

/**
 * Общие признаки строки: 2 сорт, ГОСТ/ТУ, сталь после слова «ст...».
 */
function общиеПризнаки(название, характеристика) {
  const всё = `${название} ${характеристика}`;
  const сорт2 = /(^|\s)2\s*сорт/i.test(название);
  const естьГост = /гост/i.test(всё);
  const естьТу = /(^|[\s,])ту\s*\d/i.test(всё);
  return { сорт2, естьГост, естьТу };
}

function найтиСталь(текст) {
  // «ст3сп/пс-5», «ст09Г2С-12», «стС355», «стAISI 304», «травл. стS355MC».
  // После «ст» обязательно цифра/заглавная буква — иначе слово «сталь»
  // («нерж. сталь») давало бы «марку» «аль».
  const м = текст.match(/(?:^|[\s,])[сС][тТ]\s?(AISI\s?\d+|[0-9A-ZА-ЯЁ][^\s,]*)/);
  return м ? м[1] : null;
}

const ПРЕФИКС_ТИПОВ = [
  // порядок важен: более специфичные раньше
  { тип: "лента", re: /^(лента|рулон)\s/i },
  { тип: "труба_бу", re: /^труба\s+бу\s/i },
  { тип: "труба_овал", re: /^труба\s+(?:2 сорт\s+)?проф\s*\.?\s*овал/i },
  { тип: "труба_проф", re: /^труба\s+(?:2 сорт\s+)?проф/i },
  { тип: "труба_вгп", re: /^труба\s+(?:2 сорт\s+)?вгп/i },
  { тип: "труба_эс", re: /^труба\s+(?:2 сорт\s+)?э\/с/i },
  { тип: "труба_бш", re: /^труба\s+(?:2 сорт\s+)?б\/ш/i },
  { тип: "арматура", re: /^арматура\s+а\s?\d/i },
  { тип: "балка", re: /^балка\s/i },
  { тип: "квадрат", re: /^квадрат\s/i },
  { тип: "круг", re: /^круг\s/i },
  { тип: "лист_пв", re: /^лист\s+пв\s/i },
  { тип: "лист", re: /^лист\s+(?:гк|хк|оц)(?![а-яa-z])/i },
  { тип: "полоса", re: /^полоса\s/i },
  { тип: "уголок", re: /^уголок\s+\d/i },
  { тип: "швеллер_гнутый", re: /^швеллер\s+гнутый/i },
  { тип: "швеллер", re: /^швеллер\s+гк/i },
  { тип: "шестигранник", re: /^шестигранник\s/i },
];

function определитьТипСтроки(название) {
  for (const { тип, re } of ПРЕФИКС_ТИПОВ) if (re.test(название)) return тип;
  return null;
}

/**
 * Разбор одной строки прайса. Возвращает объект позиции либо null, если
 * строка не разобрана (тип неизвестен, либо не сошёлся шаблон размеров).
 */
function разобратьСтроку(названиеСырое, характеристикаСырая) {
  const название = чистая(названиеСырое).replace(/(\d),(\d)/g, "$1.$2");
  const характеристика = чистая(характеристикаСырая);
  const тип = определитьТипСтроки(название);
  if (!тип) return null;

  const общее = общиеПризнаки(название, характеристика);
  const сталь = найтиСталь(название);
  const базовая = { тип, ...общее, стальСырая: сталь, сталь: семействоСтали(сталь) };

  let м;

  if (тип === "труба_проф" || тип === "труба_вгп" || тип === "труба_эс" || тип === "труба_бш") {
    // всё до первой запятой: «100х60х5.0х12000» / «50х3.0х н/д»
    const после = название.replace(/^труба\s+(?:2 сорт\s+)?(?:проф\s*\.?\s*(?:г\/к|х\/к)?|вгп(?:\s+оцинк\s*\.?)?|э\/с\s+(?:г\/к|х\/к|нерж\.?\s*сталь)(?:\s*травл\s*\.?)?|б\/ш\s+(?:г\/д|х\/д))\s*/i, "");
    const размерная = после.split(/\s*,\s*/)[0];
    const части = размерная.split(/\s*[хx]\s*/i).map((с) => с.trim());
    const длинаТекст = части[части.length - 1];
    const размеры = части.slice(0, -1).map(число);
    if (размеры.some((x) => x == null)) return null;
    const подТип = /г\/к/i.test(название) ? "г/к" : /х\/к/i.test(название) ? "х/к" : /г\/д/i.test(название) ? "г/д" : /х\/д/i.test(название) ? "х/д" : null;
    const длина = разобратьДлину(длинаТекст);
    if (тип === "труба_проф") {
      if (размеры.length !== 3) return null;
      return { ...базовая, подТип, стороны: [размеры[0], размеры[1]], стенка: размеры[2], длина };
    }
    if (размеры.length !== 2) return null;
    if (тип === "труба_вгп") {
      return { ...базовая, оцинк: /оцинк/i.test(название), ду: размеры[0], стенка: размеры[1], длина };
    }
    return {
      ...базовая,
      подТип,
      нержавеющая: /нерж/i.test(название),
      диаметр: размеры[0],
      стенка: размеры[1],
      длина,
    };
  }

  if (тип === "арматура") {
    м = название.match(/^арматура\s+(а\s?\d{1,3}с?)/i);
    const диам = название.match(new RegExp("ф\\s*" + ЧИСЛО, "i"));
    if (!м || !диам) return null;
    const бухта = /бухт/i.test(название);
    const длинаТекст = (название.match(/(?:^|\s)(\d{4,5})(?=\s|$)/g) || []).map((с) => с.trim()).pop();
    return {
      ...базовая,
      класс: м[1].replace(/\s/g, "").toUpperCase(),
      диаметр: число(диам[1]),
      бухта,
      длина: бухта ? null : разобратьДлину(длинаТекст),
      сталь: семействоСтали(сталь) || (название.match(/\s(\d{2}г\d?с)\s/i) || [])[1]?.toLowerCase() || null,
    };
  }

  if (тип === "балка") {
    м = название.match(new RegExp("^балка(\\s+низколегированная)?\\s+" + ЧИСЛО + "\\s*([А-ЯA-Z]{1,2}\\d?)?\\s+ст\\S+\\s+(\\d{4,5}|н/д)", "i"));
    if (!м) return null;
    return {
      ...базовая,
      низколегированная: !!м[1] || НИЗКОЛЕГИРОВАННЫЕ.has(базовая.сталь),
      номер: число(м[2]),
      буква: м[3] ? м[3].toUpperCase() : null,
      длина: разобратьДлину(м[4]),
    };
  }

  if (тип === "квадрат" || тип === "шестигранник") {
    м = название.match(new RegExp("^(?:квадрат|шестигранник)\\s+(?:гк\\s+|калиброванный\\s+)?" + ЧИСЛО + "(?:\\s*х\\s*" + ЧИСЛО + ")?\\s+ст\\S+\\s*,\\s*(\\d{3,5}(?:-\\d{3,5})?|н/д)", "i"));
    if (!м) return null;
    return { ...базовая, калиброванный: /калибр/i.test(название), размер: число(м[1]), длина: разобратьДлину(м[3]) };
  }

  if (тип === "круг") {
    м = название.match(new RegExp("^круг\\s+(?:конструкционный\\s+)?(?:калиброванный\\s+)?ст\\S+\\s+ф\\s*" + ЧИСЛО + "\\s*,\\s*(\\d{3,5}(?:-\\d{3,5})?|н/д)", "i"));
    if (!м) return null;
    return { ...базовая, диаметр: число(м[1]), длина: разобратьДлину(м[2]) };
  }

  if (тип === "лист" || тип === "лист_пв") {
    const размеры = название.match(new RegExp(ЧИСЛО + "\\s*х\\s*" + ЧИСЛО + "(?:\\s*х\\s*(\\d+|н/д))?(?=\\s|$)", "i"));
    if (!размеры) return null;
    const вид = (название.match(/^лист\s+(гк|хк|оц|пв)/i) || [])[1]?.toLowerCase();
    const a = число(размеры[1]);
    const b = число(размеры[2]);
    const длина = размеры[3] ? разобратьДлину(размеры[3]) : null;
    if (тип === "лист_пв") {
      return { ...базовая, номер: a, ширина: b, длинаЛиста: длина };
    }
    return {
      ...базовая,
      вид, // гк | хк | оц
      рифленый: /рифл/i.test(название),
      толщина: a,
      ширина: b,
      длинаЛиста: длина,
      низколегированный: /(^|\s)н\/л(\s|$)/i.test(название) || НИЗКОЛЕГИРОВАННЫЕ.has(базовая.сталь),
    };
  }

  if (тип === "полоса") {
    м = название.match(new RegExp("^полоса\\s+(г\\/к|х\\/к|оцинк\\.?)\\s*" + ЧИСЛО + "\\s*х\\s*" + ЧИСЛО + "\\s+ст\\S+\\s*,\\s*(\\d{3,5}(?:-\\d{3,5})?|н/д)", "i"));
    if (!м) return null;
    const вид = /^г/i.test(м[1]) ? "гк" : /^х/i.test(м[1]) ? "хк" : "оц";
    return { ...базовая, вид, ширина: число(м[2]), толщина: число(м[3]), длина: разобратьДлину(м[4]) };
  }

  if (тип === "уголок") {
    м = название.match(new RegExp("^уголок\\s+" + ЧИСЛО + "\\s*х\\s*" + ЧИСЛО + "\\s*х\\s*" + ЧИСЛО + "\\s+ст\\S+\\s+(\\d{4,5}|н/д)", "i"));
    if (!м) return null;
    return { ...базовая, a: число(м[1]), b: число(м[2]), стенка: число(м[3]), длина: разобратьДлину(м[4]) };
  }

  if (тип === "швеллер") {
    м = название.match(new RegExp("^швеллер\\s+гк\\s+" + ЧИСЛО + "\\s*([ПУЭЛ])?\\s+ст\\S+\\s+(\\d{4,5}|н/д)", "i"));
    if (!м) return null;
    return { ...базовая, номер: число(м[1]), буква: м[2] ? м[2].toUpperCase() : null, длина: разобратьДлину(м[3]) };
  }

  if (тип === "швеллер_гнутый") {
    м = название.match(new RegExp("^швеллер\\s+гнутый\\s+(?:2 сорт\\s+)?" + ЧИСЛО + "\\s*х\\s*" + ЧИСЛО + "\\s*х\\s*" + ЧИСЛО + "\\s+(?:ст\\S+\\s+)?(\\d{4,5}|н/д)", "i"));
    if (!м) return null;
    return {
      ...базовая,
      низколегированный: /низколег/i.test(название) || НИЗКОЛЕГИРОВАННЫЕ.has(базовая.сталь),
      высота: число(м[1]),
      полка: число(м[2]),
      стенка: число(м[3]),
      длина: разобратьДлину(м[4]),
    };
  }

  return null;
}

/**
 * Читает price.xls → { датаПрайса, датаПрайсаТекст, позиции, статистика }.
 * В позиции попадают ВСЕ строки с ценой; те, что не разобраны, имеют
 * разобрано=null (и не участвуют в сравнении).
 */
function разобратьПрайс(путь) {
  if (!fs.existsSync(путь)) throw new Error(`Файл прайса не найден: ${путь}`);
  const wb = XLSX.readFile(путь);
  const лист = wb.Sheets[wb.SheetNames[0]];
  if (!лист) throw new Error("В файле прайса нет листов");
  const строки = XLSX.utils.sheet_to_json(лист, { header: 1, defval: "" });

  // Заголовок таблицы должен быть на месте — иначе формат прайса изменился
  const индексШапки = строки.findIndex((r) => String(r[0]).trim() === "Номенклатура" && /цена/i.test(String(r[3])));
  if (индексШапки === -1) {
    throw new Error("Формат прайса Дипоса изменился: не найдена шапка «Номенклатура … Цена»");
  }

  let датаПрайсаТекст = null;
  let датаПрайса = null;
  for (const r of строки) {
    const м = String(r[0]).match(/Дата:\s*(\d{2})\.(\d{2})\.(\d{4})\s+(\d{2}):(\d{2})/);
    if (м) {
      датаПрайсаТекст = `${м[1]}.${м[2]}.${м[3]} ${м[4]}:${м[5]}`;
      датаПрайса = `${м[3]}-${м[2]}-${м[1]}T${м[4]}:${м[5]}:00`;
    }
  }

  const позиции = [];
  const статистика = { строкСЦеной: 0, неВТоннах: 0, разобрано: 0, неРазобрано: 0 };
  const неРазобранные = [];

  for (let i = индексШапки + 1; i < строки.length; i++) {
    const r = строки[i];
    const цена = typeof r[3] === "number" ? r[3] : число(r[3]);
    if (цена == null || цена <= 0) continue; // заголовок категории / пустая строка / подвал
    статистика.строкСЦеной += 1;

    const единица = String(r[2]).trim().toLowerCase();
    const название = чистая(r[0]);
    const характеристика = чистая(r[1]);

    if (единица !== "т") {
      статистика.неВТоннах += 1;
      continue; // профнастил/сетка и т.п. в п.м./м² — с ценой за тонну не сравниваются
    }

    const разобрано = разобратьСтроку(название, характеристика);
    if (разобрано) статистика.разобрано += 1;
    else {
      статистика.неРазобрано += 1;
      неРазобранные.push(название);
    }
    позиции.push({ строка: i + 1, название, характеристика, цена, разобрано });
  }

  return { датаПрайса, датаПрайсаТекст, позиции, статистика, неРазобранные };
}

