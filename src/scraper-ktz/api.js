/**
 * api.js — получение каталога КТЗ через их JSON API.
 *
 * ВАЖНО: в отличие от mc.ru, тут не нужен браузер/Playwright — это
 * готовый JSON-эндпоинт, обычный fetch. Сайт блокирует автоматический
 * доступ через robots.txt для некоторых инструментов (например, для
 * web_fetch внутри Claude), но это ограничение конкретно ТОГО
 * инструмента — обычный HTTP-запрос с сервера бота (как в Postman)
 * работает без проблем, авторизация не нужна.
 */

const BASE_URL = "https://ktzholding.com/api/products";

// Кэш всего каталога по категории — эндпоинт отдаёт ВЕСЬ каталог разом
// (тысячи строк), нет смысла запрашивать его заново на каждую позицию
// внутри одной заявки. Живёт в памяти процесса, сбрасывается по таймауту,
// чтобы не работать с устаревшими ценами весь день напролёт.
const КЭШ_ВРЕМЯ_МС = 15 * 60 * 1000; // 15 минут — цены не меняются ежеминутно, но и не хотим кэшировать сутками
const кэш = new Map(); // категория → { время, данные }

async function получиСырыеТовары(категория) {
  const закэшированное = кэш.get(категория);
  if (закэшированное && Date.now() - закэшированное.время < КЭШ_ВРЕМЯ_МС) {
    return закэшированное.данные;
  }

  const url = `${BASE_URL}/${категория}`;

  // Одна повторная попытка при сетевой ошибке (не при ошибке статуса —
  // тот бросаем сразу, тут смысла в повторе нет). Реальный случай:
  // позиция "Труба 20х1" упала с "fetch failed" разово, а следующая же
  // позиция через 13 секунд отработала нормально — похоже на разовый
  // сетевой сбой, не постоянную проблему.
  let response;
  try {
    response = await fetch(url);
  } catch (err) {
    response = await fetch(url); // одна повторная попытка без задержки — если и она упадёт, ошибка уйдёт наверх как обычно
  }

  if (!response.ok) {
    throw new Error(`КТЗ API вернул ${response.status} для категории "${категория}" (${url})`);
  }

  const json = await response.json();
  const товары = json.products || [];

  кэш.set(категория, { время: Date.now(), данные: товары });
  return товары;
}

// Труба и лист — единственные категории, которые мы пока разбираем
async function получиТрубы() {
  return получиСырыеТовары("truba");
}

async function получиЛисты() {
  return получиСырыеТовары("list");
}

// На случай, если понадобится сбросить кэш вручную (например, при
// подозрении на устаревшие цены посреди работы)
function сбросьКэш() {
  кэш.clear();
}

module.exports = { получиТрубы, получиЛисты, получиСырыеТовары, сбросьКэш };