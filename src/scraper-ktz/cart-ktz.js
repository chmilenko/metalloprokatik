/**
 * cart-ktz.js
 *
 * Добавление в корзину на КТЗ. В отличие от mc.ru (серверный рендеринг,
 * стабильная вёрстка) — это React/MUI-приложение, автогенерируемые id
 * вида "_r_t_" пересоздаются при каждой сборке фронтенда и НЕНАДЁЖНЫ
 * для долгосрочной автоматизации. Ищем элементы по видимому тексту
 * (метки "Тонны"/"Метры", название склада) — это переживёт пересборку
 * фронтенда куда увереннее, чем конкретные CSS-классы/id.
 *
 * Схема (см. обсуждение с Артёмом):
 *   1. Прямая ссылка на товар по id: /category/{category_slug}/{id}
 *   2. Смотрим, какой склад "основной" (показан вверху формы)
 *      - Если это нужный нам склад → верхняя форма (поле количества +
 *        явная кнопка "В корзину")
 *      - Если нет → ищем строку с нужным складом в нижней таблице
 *        "Наличие" (там кнопки нет — ввод количества + клик мимо поля
 *        добавляет сам по себе). ВАЖНО: это безопасно делать только
 *        для складов Московской области — ввод количества в строке
 *        другого региона глобально переключает регион во всём
 *        приложении (подтверждено Артёмом). Мы работаем только с
 *        Дмитровом/Ивантеевкой — оба Московская область, так что тут
 *        мы в безопасной зоне, но проверка на регион всё равно есть.
 *
 * ФИКС (25.09.2026): модалка cookie-согласия (всплывает один раз за
 * сессию браузера, при первом заходе на сайт) перекрывала клики по
 * нижней таблице "Наличие" — ввод количества и клик "мимо поля" на
 * самом деле попадали в модалку, а не в таблицу. Закрываем её сразу
 * после первого захода на страницу товара, до любых других действий.
 *
 * ФИКС (02.10.2026): модалка "Уведомление" (наценка/разбивка по
 * складам) всплывает непредсказуемо по времени — иногда сразу при
 * заходе на карточку, иногда с задержкой 60+ секунд — и перехватывает
 * клики по полю количества (MuiDialog-container ... intercepts pointer
 * events). Проверяем её закрытие в трёх точках: сразу после
 * cookie-модалки, и прямо перед каждым кликом по полю количества в
 * обеих формах. ВАЖНО: эта функция никогда не трогает чекбокс "Больше
 * не показывать" — это постоянная настройка аккаунта, а не разовое
 * действие для одной заявки (см. notificationModal.js).
 */

const logger = require("../utils/logger");
const { getPage } = require("../scraper/browser");
const { закройCookieModalЕслиЕсть } = require("./cookieModal");
const { закройУведомлениеЕслиЕсть } = require("./notificationModal");

const delay = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

const МОСКОВСКАЯ_ОБЛАСТЬ = "Московская область";

/**
 * Добавляет один вариант КТЗ в корзину.
 * @param {object} variant - вариант из ktz/index.js (товарВВарианты) —
 *        обязательно должен нести _ктзТовар (с id/category_slug) и
 *        _ктзЦена (с wh — нужный склад)
 * @param {number} quantity
 * @param {string} unit - 'т' или 'м'
 */
async function addToCartKTZ(variant, quantity, unit = "т") {
  const товар = variant._ктзТовар;
  const цена = variant._ктзЦена;

  if (!товар || !товар.id) {
    throw new Error(
      `Нет данных КТЗ (id) для добавления в корзину: ${variant.название}`,
    );
  }
  if (!цена || !цена.wh) {
    throw new Error(
      `Нет данных о складе КТЗ для добавления в корзину: ${variant.название}`,
    );
  }

  const categorySlug = товар.category_slug || товар.slug_cat;
  if (!categorySlug) {
    throw new Error(
      `Нет category_slug для построения ссылки КТЗ: ${variant.название}`,
    );
  }

  const url = `https://ktzholding.com/category/${categorySlug}/${товар.id}`;
  const нужныйСклад = цена.wh;

  logger.info("КТЗ: открываем карточку товара", {
    название: variant.название,
    url,
    нужныйСклад,
    количество: quantity,
    единица: unit,
  });

  const page = await getPage();
  await page.goto(url);
  await page.waitForLoadState("domcontentloaded");
  await delay(1500);

  // ФИКС: закрываем модалку cookie-согласия ДО любых попыток
  // взаимодействия с формой/таблицей — иначе она перекрывает клики.
  await закройCookieModalЕслиЕсть(page);
  // ФИКС: модалка "Уведомление" (наценка/разбивка по складам) всплывает
  // непредсказуемо по времени — иногда сразу при заходе на карточку,
  // иногда с задержкой. Проверяем здесь же, сразу после cookie-модалки,
  // чтобы не наткнуться на неё позже посреди клика по полю.
  await закройУведомлениеЕслиЕсть(page);

  // ============================================================
  // 1. ЧИТАЕМ "ОСНОВНОЙ" СКЛАД (показан вверху формы, в блоке
  //    "Характеристики" рядом с меткой "Склад")
  // ============================================================

  const основнойСклад = await page.evaluate(() => {
    // Ищем строку характеристик с меткой "Склад" — по тексту, не по
    // классам (см. объяснение в шапке файла)
    const все = Array.from(document.querySelectorAll("div, p, span"));
    const метка = все.find((el) => el.textContent.trim() === "Склад");
    if (!метка) return null;
    // Значение — соседний элемент того же уровня (следующий sibling)
    const значение = метка.nextElementSibling;
    return значение ? значение.textContent.trim() : null;
  });

  logger.info("КТЗ: основной склад на карточке", {
    название: variant.название,
    основнойСклад,
    нужныйСклад,
  });

  // ============================================================
  // 2а. ОСНОВНОЙ СКЛАД СОВПАДАЕТ — используем верхнюю форму
  // ============================================================

  if (основнойСклад === нужныйСклад) {
    await заполнитьВерхнююФормуИДобавить(page, variant, quantity, unit);
    return;
  }

  // ============================================================
  // 2б. НУЖЕН ДРУГОЙ СКЛАД — ищем строку в нижней таблице "Наличие"
  // ============================================================

  logger.info("КТЗ: основной склад не совпадает, ищем в таблице «Наличие»", {
    название: variant.название,
    нужныйСклад,
  });

  await заполнитьСтрокуНаличия(page, variant, нужныйСклад, quantity, unit);
}

// ============================================================
// ВЕРХНЯЯ ФОРМА — есть явная кнопка "В корзину"
// ============================================================

async function заполнитьВерхнююФормуИДобавить(page, variant, quantity, unit) {
  const меткаПоля = unit === "м" ? "Метры" : "Тонны";

  const inputHandle = await page.evaluateHandle((меткаПоля) => {
    // ВАЖНО: слово "Наличие" на странице встречается ДВАЖДЫ — и как
    // заголовок таблицы снизу, и как метка "остатка" в блоке
    // характеристик наверху (рядом со "Склад"). Искать по заголовку
    // "Наличие" ненадёжно — можно случайно зацепить не тот. Вместо
    // этого используем структурный признак: поля верхней формы НЕ
    // находятся внутри <table>, а строки нижней таблицы "Наличие" —
    // находятся. Это надёжнее любого текстового ориентира.
    const все = Array.from(document.querySelectorAll("div"));
    const метка = все.find(
      (el) => el.textContent.trim() === меткаПоля && !el.closest("table"),
    );
    return метка?.parentElement?.querySelector("input") || null;
  }, меткаПоля);

  const inputElement = inputHandle.asElement();
  if (!inputElement) {
    throw new Error(
      `Не нашли поле "${меткаПоля}" в верхней форме: ${variant.название}`,
    );
  }

  await inputElement.scrollIntoViewIfNeeded();
  await delay(300);
  // ФИКС: модалка "Уведомление" могла появиться между открытием страницы
  // и этим моментом — перехватывает клик по полю, если не закрыть её
  // прямо здесь.
  await закройУведомлениеЕслиЕсть(page);
  await inputElement.click({ clickCount: 3 }); // выделить весь текст
  await delay(150);
  await page.keyboard.type(String(quantity), { delay: 60 });
  await delay(300);

  // Клик мимо поля, чтобы значение зафиксировалось (как в описанном
  // потоке — "убираем курсор с поля ввода")
  await page.keyboard.press("Tab");
  await delay(500);

  // ============================================================
  // Кнопка "В корзину"
  // ============================================================

  const кнопкаНажата = await page.evaluate(() => {
    const кнопки = Array.from(document.querySelectorAll("button"));
    const btn = кнопки.find((b) => b.textContent.trim().includes("В корзину"));
    if (!btn) return false;
    btn.click();
    return true;
  });

  if (!кнопкаНажата) {
    throw new Error(`Не нашли кнопку "В корзину": ${variant.название}`);
  }

  await delay(1000);

  await закройУведомлениеЕслиЕсть(page);

  logger.info("КТЗ: добавлено в корзину (верхняя форма)", {
    название: variant.название,
  });
}

// ============================================================
// НИЖНЯЯ ТАБЛИЦА "НАЛИЧИЕ" — без отдельной кнопки, добавление по
// вводу + клику мимо поля
// ============================================================

async function заполнитьСтрокуНаличия(
  page,
  variant,
  нужныйСклад,
  quantity,
  unit,
) {
  // Находим строку таблицы "Наличие", где ячейка "Склад" === нужныйСклад,
  // И параллельно проверяем регион — должен быть Московская область
  // (безопасность: ввод в строке другого региона переключает регион
  // глобально во всём приложении, см. шапку файла)
  const найденоИБезопасно = await page.evaluate(
    ({ нужныйСклад, московскаяОбласть }) => {
      const строки = Array.from(
        document.querySelectorAll("table tbody tr, div[role='row']"),
      );
      for (const row of строки) {
        const ячейки = Array.from(row.querySelectorAll("td, div"));
        const текстСтроки = row.textContent;
        if (!текстСтроки.includes(нужныйСклад)) continue;
        if (!текстСтроки.includes(московскаяОбласть)) continue; // защита от смены региона
        return true;
      }
      return false;
    },
    { нужныйСклад, московскаяОбласть: МОСКОВСКАЯ_ОБЛАСТЬ },
  );

  if (!найденоИБезопасно) {
    throw new Error(
      `Склад "${нужныйСклад}" не найден в таблице "Наличие" как база Московской области: ${variant.название}`,
    );
  }

  const меткаПоля = unit === "м" ? "Метры" : "Тонны";
  // Индекс колонки "Тонны"/"Метры" в таблице "Наличие" (см. присланную
  // разметку: Регион | Склад | Остатки | Цена FCA | Тонны | Метры)
  const индексКолонки = меткаПоля === "Тонны" ? 4 : 5;

  const inputHandle = await page.evaluateHandle(
    ({ нужныйСклад, индексКолонки }) => {
      const строки = Array.from(document.querySelectorAll("table tbody tr"));
      for (const row of строки) {
        if (!row.textContent.includes(нужныйСклад)) continue;
        const ячейки = row.querySelectorAll("td");
        const целеваяЯчейка = ячейки[индексКолонки];
        if (!целеваяЯчейка) continue;
        const input = целеваяЯчейка.querySelector("input");
        if (input) return input;
      }
      return null;
    },
    { нужныйСклад, индексКолонки },
  );

  const inputElement = inputHandle.asElement();
  if (!inputElement) {
    throw new Error(
      `Не нашли поле ввода "${меткаПоля}" в строке "${нужныйСклад}" таблицы «Наличие»: ${variant.название}`,
    );
  }

  await inputElement.scrollIntoViewIfNeeded();
  await delay(300);
  // ФИКС: модалка могла появиться между открытием страницы и этим
  // моментом (видели в логах задержку до 60+ секунд) — перехватывает
  // клик по полю (MuiDialog ... intercepts pointer events), если не
  // закрыть её прямо здесь.
  await закройУведомлениеЕслиЕсть(page);
  await inputElement.click({ clickCount: 3 });
  await delay(150);
  await page.keyboard.type(String(quantity), { delay: 60 });
  await delay(300);

  // Клик мимо поля — по описанию это и есть весь механизм добавления
  // для строк таблицы "Наличие" (нет отдельной кнопки)
  await page.keyboard.press("Tab");
  await delay(800);

  await закройУведомлениеЕслиЕсть(page);

  logger.info("КТЗ: добавлено в корзину (строка «Наличие»)", {
    название: variant.название,
    склад: нужныйСклад,
  });
}

module.exports = { addToCartKTZ };