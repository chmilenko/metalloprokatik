/**
 * index.js — главная точка входа для поиска на КТЗ.
 *
 * Задача: по позиции заявки (тот же формат, что и для mc.ru — см.
 * parser.js) найти подходящие товары на КТЗ и отдать их в формате,
 * совместимом с тем, что уже использует exportToExcel.js для сводной
 * таблицы mc.ru — то есть массив "вариантов" с полями смц/цена_от_1т/
 * длина/cardUrl, которые умеет читать разберБазы()/добавьСтроку().
 *
 * Склады КТЗ подписываются с префиксом "КТЗ: " — чтобы в общей сводной
 * таблице сразу было видно, откуда конкретная колонка (по просьбе:
 * "с префиксом норм").
 */

const { получиТрубы, получиЛисты } = require("./api");
const { нормализуй } = require("./normalize");
const { оцениВсеТрубы } = require("./match");
const { оцениВсеЛисты } = require("./match-list");
const logger = require("../utils/logger");

const ПРЕФИКС_СКЛАДА = "КТЗ: ";

// Наценка КТЗ за заказ МЕНЕЕ 1 тонны — сайт сам предупреждает об этом
// модальным окном при добавлении в корзину ("стоимость товара за одну
// тонну увеличивается на 1000 рублей"). Цена в каталоге через API этой
// наценки НЕ учитывает — добавляем её сами, иначе сводная таблица
// занижала бы реальную цену для позиций меньше тонны.
// ВРЕМЕННО ОТКЛЮЧЕНО (23.09.2026, по просьбе Артёма): "непонятно, на
// каких позициях работает +1000₽/т" — похоже, наценка не всегда
// срабатывает при заказе <1т, закономерность не установлена. Держим
// механику на месте (просто ставим false), чтобы быстро включить
// обратно, как только найдём точное правило (может, зависит от
// категории товара, конкретного склада, или ещё какого-то условия,
// которое мы пока не учли).
const НАЦЕНКА_ВКЛЮЧЕНА = false;
const ПОРОГ_БЕЗ_НАЦЕНКИ_Т = 1;
const НАЦЕНКА_ЗА_МАЛЫЙ_ЗАКАЗ = 1000; // руб/т

// Переводит количество позиции (т/м/шт — как указано в заявке) в тонны,
// используя вес товара (весТонн — тонн на метр для трубы, тонн на лист
// для листа, см. normalize.js). Возвращает null, если посчитать не
// удалось (например нет данных о длине для перевода штук в тонны) —
// в этом случае наценку НЕ применяем, лучше промолчать, чем ошибиться.
function переведиВТонны(position, товар) {
  const количество = position?.количество;
  const единица = position?.единица;
  if (количество == null || !единица) return null;

  if (единица === "т") return количество;

  const весНаМетр = товар.category_type === "Труба" ? товар.весТонн : null;

  if (единица === "м" && весНаМетр != null) {
    return количество * весНаМетр;
  }

  if (единица === "шт") {
    if (товар.category_type === "Лист" && товар.весТонн != null) {
      return количество * товар.весТонн; // весТонн для листа — вес ОДНОГО листа
    }
    if (товар.category_type === "Труба" && весНаМетр != null && товар.length_numeric) {
      // весТонн для трубы — тонн НА МЕТР, домножаем на длину одной штуки
      return количество * весНаМетр * (товар.length_numeric / 1000);
    }
  }

  return null;
}

// Белый список складов КТЗ — по просьбе нужны только эти два, остальные
// (Ижевск, Волгоград, Воронеж, Новосибирск, Челябинск, Екатеринбург и
// т.д. — видели в реальных данных) отсекаем. Та же логика, что
// ИЗВЕСТНЫЕ_БАЗЫ для mc.ru в utils/basePriorityStore.js — фильтруем
// максимально близко к источнику, а не только на этапе отображения,
// чтобы отсечённые склады не попадали и в поиск альтернатив.
const ИЗВЕСТНЫЕ_СКЛАДЫ_КТЗ = ["Дмитров", "Ивантеевка"];

// Определяет, труба это или лист — по тем же полям, что и логика
// mc.ru использует для маршрутизации (диаметр/ширина = труба,
// толщина+обе стороны без диаметра = лист). Не пытаемся угадывать
// по слову в тексте — структурные параметры надёжнее.
// Проверяет вхождение "слова" в текст как ЦЕЛОГО слова (не подстрокой
// внутри другого слова) — та же защита, что есть в search.js для mc.ru
// (\b не работает с кириллицей в JS regex, приходится проверять вручную)
function естьЦелоеСлово(текст, слово) {
  const idx = текст.indexOf(слово);
  if (idx === -1) return false;
  const before = текст[idx - 1];
  const after = текст[idx + слово.length];
  const этоБуква = (ch) => !!ch && /[a-zа-яё]/i.test(ch);
  return !этоБуква(before) && !этоБуква(after);
}

// ВАЖНО: парсер mc.ru переиспользует ОДНИ И ТЕ ЖЕ поля параметров для
// РАЗНЫХ форм проката — диаметр используется и кругом, и трубой;
// ширина+стенка — и уголком/швеллером, и профильной трубой; толщина+
// ширина — и полосой, и листом. Раньше определиТипТовара смотрела
// ТОЛЬКО на то, какие поля заполнены — из-за этого круг/уголок/
// швеллер/арматура/катанка ошибочно уходили в поиск как "труба", а
// полоса — как "лист" (и там реально находила чужие листы 1500мм
// вместо полосы 60мм, потому что match-list.js не проверяет ширину,
// если длина_листа не задана — а у полосы она никогда не задаётся).
// Теперь требуем ЯВНОГО подтверждения по тексту заявки — только
// круглые/профильные трубы и настоящие листы, никаких совпадений "по
// случайно заполненным полям".
function определиТипТовара(position) {
  const текст = `${position.поисковый_запрос || ""} ${position.название || ""}`.toLowerCase();

  const этоТруба = естьЦелоеСлово(текст, "труба") || естьЦелоеСлово(текст, "трубы") || естьЦелоеСлово(текст, "вгп");
  const этоЛист = естьЦелоеСлово(текст, "лист");

  // Явно НЕ поддерживаемые формы — даже если текст случайно содержит
  // "труба"/"лист" где-то рядом, эти слова должны перевесить (на
  // практике текст для круга/уголка и т.п. никогда не содержит "труба"/
  // "лист", так что этот блок скорее подстраховка на будущее)
  const другаяФорма = ["круг", "уголок", "швеллер", "балка", "двутавр", "арматура", "катанка", "полоса", "квадрат"].some(
    (ф) => естьЦелоеСлово(текст, ф),
  );
  if (другаяФорма && !этоТруба && !этоЛист) return null;

  if (этоТруба) return "труба";
  if (этоЛист) return "лист";
  return null; // неизвестная/неподдерживаемая форма — не лезем в КТЗ вообще
}

// Конвертирует ОДИН прошедший фильтр товар КТЗ в массив "вариантов" —
// по одному на каждый склад из prices[]. Формат совместим с тем, что
// уже понимает разберБазы()/добавьСтроку() в exportToExcel.js: смц,
// цена_от_1т, длина, cardUrl (там, где обычно ссылка на карточку — у
// КТЗ прямой ссылки на конкретный товар у нас пока нет, оставляем null).
function товарВВарианты(товар, position = null) {
  const длинаМм =
    товар.length_numeric != null
      ? String(товар.length_numeric)
      : (товар.length && товар.length !== "Немерная" ? товар.length : null);

  const тоннаж = position ? переведиВТонны(position, товар) : null;
  const применяетсяНаценка = НАЦЕНКА_ВКЛЮЧЕНА && тоннаж != null && тоннаж < ПОРОГ_БЕЗ_НАЦЕНКИ_Т;

  return (товар.prices || [])
    .filter((цена) => ИЗВЕСТНЫЕ_СКЛАДЫ_КТЗ.includes(цена.wh))
    .map((цена) => ({
    название: товар.real_name || товар.name,
    смц: `${ПРЕФИКС_СКЛАДА}${цена.wh}`,
    регион: цена.region,
    длина: длинаМм,
    марка: товар.mark_of_steel || null,
    цена_от_1т: применяетсяНаценка ? цена.price + НАЦЕНКА_ЗА_МАЛЫЙ_ЗАКАЗ : цена.price,
    _базоваяЦенаБезНаценки: цена.price,
    _наценкаЗаМалыйЗаказПрименена: применяетсяНаценка,
    весТонн: товар.весТонн,
    cardUrl: null,
    sourceUrl: null,
    // Держим ссылку на исходные объекты — вдруг понадобится больше
    // деталей (например при переходе к реальному добавлению в корзину)
    _ктзТовар: товар,
    _ктзЦена: цена,
  }));
}

/**
 * Ищет позицию на КТЗ. Возвращает { variants, оценённые } — тот же
 * формат, что findPosition() отдаёт для mc.ru (variants — прошедшие
 * фильтр, оценённые — ВСЕ с вердиктом, для таблицы решения/альтернатив).
 * Если тип товара не распознан (не труба и не лист) — возвращает
 * пустой результат, ничего не падает.
 */
async function найдиНаКТЗ(position) {
  const тип = определиТипТовара(position);
  if (!тип) return { variants: [], оценённые: [] };

  let сырыеТовары;
  let оценённыеТовары;

  if (тип === "труба") {
    сырыеТовары = await получиТрубы();
    const товары = нормализуй(сырыеТовары);
    оценённыеТовары = оцениВсеТрубы(товары, position);
  } else {
    сырыеТовары = await получиЛисты();
    const товары = нормализуй(сырыеТовары);
    оценённыеТовары = оцениВсеЛисты(товары, position);
  }

  const прошедшиеТовары = оценённыеТовары.filter((r) => r.прошёл);

  logger.info("КТЗ: позиция обработана", {
    название: position.название,
    тип,
    всегоТоваровВКаталоге: сырыеТовары.length,
    прошлоФильтр: прошедшиеТовары.length,
    товары: прошедшиеТовары.map((r) => ({
      название: r.товар.real_name,
      count: r.товар.count,
      склады: (r.товар.prices || []).map((p) => `${p.wh}:${p.price}${p.stock_status ? ` (${p.stock_status})` : ""}`),
    })),
  });

  // Разворачиваем каждый прошедший товар в варианты по складам
  const variants = прошедшиеТовары.flatMap((r) => товарВВарианты(r.товар, position));

  // Логируем отдельно, если где-то сработала наценка за малый заказ —
  // это меняет цену относительно того, что видно в каталоге, стоит
  // видеть явно в логе, а не только в итоговой цене
  const сНаценкой = variants.filter((v) => v._наценкаЗаМалыйЗаказПрименена);
  if (сНаценкой.length > 0) {
    logger.info("КТЗ: применена наценка за заказ менее 1 тонны", {
      название: position.название,
      количествоПозиций: сНаценкой.length,
      наценка: НАЦЕНКА_ЗА_МАЛЫЙ_ЗАКАЗ,
    });
  }

  // Для "оценённые" в формате, совместимом с оцениВсеВарианты() из
  // mc.ru (вариант/прошёл/причина) — тоже разворачиваем по складам,
  // чтобы построчная логика альтернатив (см. exportToExcel.js) могла
  // работать с КТЗ так же, как с mc.ru
  const оценённые = оценённыеТовары.flatMap(({ товар, прошёл, причина }) =>
    товарВВарианты(товар, position).map((вариант) => ({ вариант, прошёл, причина })),
  );

  return { variants, оценённые };
}

module.exports = { найдиНаКТЗ, определиТипТовара, товарВВарианты };