/**
 * match-list.js — сопоставляет разобранную позицию заявки с листами КТЗ.
 *
 * В отличие от труб, у листа только ОДНА ось категории (category_name:
 * "Лист г/к" | "Лист х/к" | "Лист оц." | "Лист ПВ" | ...) — нет отдельного
 * деления на "покрытие × конструкция", как у труб (ВГП/профильная +
 * оцинкованная независимо). Оцинковка тут — просто отдельное значение
 * той же самой категории, не отдельная ось.
 *
 * Размер листа — side_a_numeric/side_b_numeric (ширина×длина листа),
 * порядок в данных не гарантирован совпадать с тем, как менеджер написал
 * заявку — сравниваем в ОБОИХ направлениях, как и профильную трубу.
 *
 * Вес — ВАЖНО: для листов используется weight_t (тонн на ОДИН лист
 * целиком), НЕ weight_per_meter_t (то поле для листов всегда null —
 * см. normalize.js, там уже учтено через category_type==='Лист').
 */

const ДОПУСК = 0.001;

function числаРавны(a, b) {
  if (a == null || b == null) return false;
  return Math.abs(Number(a) - Number(b)) < ДОПУСК;
}

// Категория листа — по тексту заявки. Дефолт: если явно не сказано
// х/к/оцинкованный/ПВЛ — считаем г/к (та же логика дефолта, что была
// на mc.ru: "не указано ничего — берём самый распространённый вариант").
function определиКатегориюЛиста(позиция) {
  const текст = `${позиция.поисковый_запрос || ""} ${позиция.название || ""}`.toLowerCase();

  if (/оцинков|цинк/.test(текст)) return "Лист оц.";
  // ВАЖНО: НЕ \bпвл\b — \b не работает с кириллицей в JS regex (опирается
  // на \w, куда кириллица не входит). Та же ловушка уже дважды сегодня
  // ловилась в match.js (там же с "ту") — держим в уме на будущее.
  if (/(^|\s)пвл(\s|$)/.test(текст) || /просечно/.test(текст)) return "Лист ПВ";
  if (/х\/к|холоднокатан/.test(текст)) return "Лист х/к";
  // г/к — и явный запрос, и дефолт по умолчанию
  return "Лист г/к";
}

function оцениЛист(товар, позиция, контекст) {
  const { категория } = контекст;

  // Некондиция — брак/неликвид ("Лист ХК 0.5 цинк (теория, некондиция)" —
  // реальный пример с КТЗ). Исключаем БЕЗУСЛОВНО, даже если размер/марка
  // совпадают идеально — это не то же самое, что обычный товар, заказывать
  // такое можно только осознанно вручную, не через автоподбор. Та же
  // защита, что уже стояла на mc.ru (там были "некондиция"/"пересортица").
  const текстНазвания = (товар.real_name || товар.name || "").toLowerCase();
  if (текстНазвания.includes("некондици")) {
    return { ok: false, причина: "некондиция — брак/неликвид, не подбирается автоматически" };
  }

  if (товар.category_name !== категория) {
    return { ok: false, причина: `не та категория листа (нужна "${категория}", тут "${товар.category_name}")` };
  }

  // Толщина
  if (позиция.параметры?.толщина != null) {
    if (!числаРавны(товар.thickness_numeric, позиция.параметры.толщина)) {
      return { ok: false, причина: `толщина не совпадает (нужна ${позиция.параметры.толщина}, тут ${товар.thickness_numeric})` };
    }
  }

  // Размер листа (ширина × длина) — сравниваем в обоих направлениях,
  // порядок в исходной заявке может не совпадать с порядком на сайте
  const нужнаяШирина = позиция.параметры?.ширина;
  const нужнаяДлина = позиция.параметры?.длина_листа;
  if (нужнаяШирина != null && нужнаяДлина != null) {
    const совпадаетПрямо =
      числаРавны(товар.side_a_numeric, нужнаяШирина) && числаРавны(товар.side_b_numeric, нужнаяДлина);
    const совпадаетНаоборот =
      числаРавны(товар.side_b_numeric, нужнаяШирина) && числаРавны(товар.side_a_numeric, нужнаяДлина);
    if (!совпадаетПрямо && !совпадаетНаоборот) {
      return {
        ok: false,
        причина: `размер листа не совпадает (нужен ${нужнаяШирина}x${нужнаяДлина}, тут ${товар.side_a_numeric}x${товар.side_b_numeric})`,
      };
    }
  }

  // Марка стали, если указана явно
  if (позиция.параметры?.марка) {
    const нужнаяМарка = позиция.параметры.марка.toLowerCase().replace(/\s/g, "");
    const маркаТовара = (товар.mark_of_steel || "").toLowerCase().replace(/\s/g, "");
    if (маркаТовара && маркаТовара !== нужнаяМарка) {
      return { ok: false, причина: `марка не совпадает (запрошено "${позиция.параметры.марка}", тут "${товар.mark_of_steel}")` };
    }
  }

  // ГОСТ vs ТУ — тот же принцип, что и у труб/mc.ru
  const спецификация = позиция.параметры?.спецификация || {};
  const нуженТУ =
    спецификация.нужны_оба === true ||
    спецификация.приоритет === "ТУ" ||
    /(^|\s)ту(\s|$)/i.test(`${позиция.поисковый_запрос || ""} ${позиция.название || ""}`);
  const этоТУ = /^ту(\s|$)/i.test((товар.gost || "").trim());
  if (этоТУ && !нуженТУ) {
    return { ok: false, причина: "ТУ-спецификация вместо ГОСТ (риск нулевого остатка)" };
  }

  return { ok: true };
}

function подготовьКонтекстЛиста(позиция) {
  return { категория: определиКатегориюЛиста(позиция) };
}

function оцениВсеЛисты(товары, позиция) {
  const контекст = подготовьКонтекстЛиста(позиция);
  return товары.map((товар) => {
    const { ok, причина } = оцениЛист(товар, позиция, контекст);
    return { товар, прошёл: ok, причина: причина || null };
  });
}

module.exports = { оцениВсеЛисты, определиКатегориюЛиста, числаРавны };