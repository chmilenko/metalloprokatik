/**
 * match.js — сопоставляет разобранную позицию заявки (тот же формат
 * параметров, что и в parser.js для mc.ru: диаметр/ширина/длина_листа/
 * стенка/длина/марка) с товарами КТЗ.
 *
 * Главное отличие от mc.ru: тут почти все размеры уже лежат числами в
 * отдельных полях (side_a_numeric, thickness_numeric, length_numeric) —
 * не нужно вытаскивать их регексами из текста названия. Сравниваем
 * напрямую, с небольшим допуском на плавающую точку.
 */

const ДОПУСК = 0.001; // защита от 0.1+0.2!==0.3 при сравнении дробных мм

function числаРавны(a, b) {
  if (a == null || b == null) return false;
  return Math.abs(Number(a) - Number(b)) < ДОПУСК;
}

// Определяет, круглая это труба или профильная — по наличию side_b_numeric.
// У КТЗ это видно напрямую из данных (side_b_numeric===null у круглой),
// не нужно гадать по количеству чисел в тексте запроса, как на mc.ru —
// но сам запрос менеджера ВСЁ РАВНО разбираем той же логикой (см.
// договорённость с Александром: считаем по количеству чисел в размере).
function этоПрофильная(позиция) {
  // ВАЖНО: наличия параметры.ширина уже достаточно — это поле вообще
  // используется ТОЛЬКО для профильных труб (у круглой трубы размер
  // хранится в параметры.диаметр, не в ширине). Раньше тут требовалась
  // ЕЩЁ И параметры.длина_листа — но для квадратной трубы парсер
  // (та же логика, что и для mc.ru) её НЕ заполняет вовсе, когда обе
  // стороны равны ("Труба 20х20х3" → ширина=20, длина_листа=null,
  // подразумевая квадрат) — из-за этого квадратная труба без явно
  // повторённой второй стороны ошибочно считалась круглой и уходила
  // в поиск по диаметру, вместо профильного 20×20 (реальный баг,
  // найденный на примере "труба 20х20х3" — нашлись круглые трубы
  // 48/57/76/89/108/219мм со стенкой 3 вместо квадрата 20×20).
  return позиция.параметры?.ширина != null;
}

// ВАЖНО: у КТЗ покрытие (оцинкованная/обычная) и конструктивный вид
// (ВГП/профильная/электросварная) — ДВЕ НЕЗАВИСИМЫЕ оси, не альтернативы
// одного и того же поля. Подтверждено реальным примером: "Труба ВГП
// 15x2.8 цинк" имеет category_name="Труба оцинкованная" (покрытие) И
// ОДНОВРЕМЕННО subcategory_name="Труба ВГП" (конструкция) — то есть
// категория на сайте — это, по сути, "покрытие", а вид конструкции
// живёт в отдельном поле subcategory_name (или characteristics
// "Вид продукции", тот же смысл). Раньше здесь была одна функция,
// которая возвращала ОДНО значение на всё — из-за этого "труба ВГП
// оцинкованная" не находила бы товар (искала видТрубы="Труба ВГП",
// а у товара category_name="Труба оцинкованная", несовпадение).
function определиПокрытие(позиция) {
  const текст = `${позиция.поисковый_запрос || ""} ${позиция.название || ""}`.toLowerCase();
  return /оцинков|цинк/.test(текст) ? "оцинкованная" : "обычная";
}

function определиКонструкцию(позиция) {
  const текст = `${позиция.поисковый_запрос || ""} ${позиция.название || ""}`.toLowerCase();

  if (позиция.параметры?.ду != null || /вгп|водогазопроводн/.test(текст)) return "Труба ВГП";
  // ВАЖНО: на КТЗ категория называется "плоскоовальная" (с лишней "о"!),
  // а не "плосковальная" — реальный пример с сайта: "Труба плоскоовальная
  // 40x1.5". Менеджеры пишут по-разному (и "плосковальная", и
  // "плоскоовальная") — распознаём оба варианта написания в заявке, но
  // возвращаем именно то название, которое реально стоит у КТЗ в
  // category_name/subcategory_name, иначе строковое сравнение в
  // оцениТрубу никогда не совпадёт, даже если регулярка выше сработает.
  if (/плоск.{0,2}о?вальн/.test(текст)) return "Труба плоскоовальная";
  // Профильная определяется по количеству чисел в размере (та же логика,
  // что и на mc.ru) — а не по слову, слово может противоречить цифрам.
  if (этоПрофильная(позиция)) return "Труба профильная";
  return "Труба электросварная";
}

// Оценивает ОДИН товар против позиции — {ok:true} или {ok:false, причина}.
// Та же архитектура, что и оцениВариант в mc.ru search.js — переиспользуем
// и для обычной фильтрации, и для таблицы решения (видно все отклонения).
function оцениТрубу(товар, позиция, контекст) {
  const { покрытие, конструкция } = контекст;

  // Некондиция — брак/неликвид, исключаем безусловно (см. подробное
  // объяснение в match-list.js — та же защита, найдена на примере листа,
  // но проверяем и здесь на всякий случай — если КТЗ помечает так же
  // и некоторые трубы).
  const текстНазвания = (товар.real_name || товар.name || "").toLowerCase();
  if (текстНазвания.includes("некондици")) {
    return { ok: false, причина: "некондиция — брак/неликвид, не подбирается автоматически" };
  }

  // Покрытие — по товару смотрим на category_name/поле coating.
  // "Обычная" (не оцинкованная) — category_name НЕ должен быть "Труба
  // оцинкованная". "Оцинкованная" — наоборот, должен.
  const товарОцинкован = товар.category_name === "Труба оцинкованная";
  if (покрытие === "оцинкованная" && !товарОцинкован) {
    return { ok: false, причина: "не оцинкованная, а нужна оцинкованная" };
  }
  if (покрытие === "обычная" && товарОцинкован) {
    return { ok: false, причина: "оцинкованная — дороже обычной, явно не запрошена" };
  }

  // Конструкция — subcategory_name (или, если пусто, category_name —
  // у необычной оцинкованной там дублируется покрытие, а не конструкция,
  // так что подстраховка через category_name работает только для НЕ
  // оцинкованных товаров, где subcategory_name бывает пустым)
  const товарнаяКонструкция = товар.subcategory_name || товар.category_name;
  if (товарнаяКонструкция !== конструкция) {
    return { ok: false, причина: `не тот вид трубы (нужна "${конструкция}", тут "${товарнаяКонструкция}")` };
  }

  // ВГП: размер задаётся условным проходом (ДУ), а НЕ диаметром — параметры.диаметр у
  // такой позиции пустой, и раньше размер не проверялся вовсе: «ВГП 25х3,2» принимала
  // «ВГП 32х3,2» (в заказ ушёл не тот размер). Сверяем ДУ с первым числом размера товара.
  if (конструкция === "Труба ВГП" && позиция.параметры?.ду != null) {
    const ду = позиция.параметры.ду;
    const имя = (товар.real_name || товар.name || "").toLowerCase().replace(/\s+/g, " ");
    const поИмени = new RegExp(`вгп ${String(ду).replace(/[.,]/g, "[.,]")}\\s*[xх*]`, "i").test(имя);
    if (!числаРавны(товар.side_a_numeric, ду) && !поИмени) {
      return { ok: false, причина: `ДУ не совпадает (нужен ${ду}, тут ${товар.side_a_numeric})` };
    }
  }

  // Диаметр (круглая) — side_a_numeric, side_b_numeric должен быть null
  if (позиция.параметры?.диаметр != null) {
    if (товар.side_b_numeric != null) {
      return { ok: false, причина: "это профильная труба, а нужна круглая" };
    }
    if (!числаРавны(товар.side_a_numeric, позиция.параметры.диаметр)) {
      return { ok: false, причина: `диаметр не совпадает (нужен ${позиция.параметры.диаметр}, тут ${товар.side_a_numeric})` };
    }
  }

  // Плоскоовальная — ОСОБЫЙ случай: у неё тоже есть side_a/side_b в
  // данных (например 30×15), но менеджер и сам сайт КТЗ в разговорном
  // названии указывают ТОЛЬКО большую ось + толщину ("Труба плоскоовальная
  // 30x1.2") — малая ось (15) это СТАНДАРТНОЕ производное значение для
  // этого размера, не то, что выбирается независимо. Поэтому сравниваем
  // ТОЛЬКО большую ось (side_a_numeric), как у круглой трубы с диаметром,
  // а НЕ как у профильной с двумя независимо выбираемыми сторонами.
  if (конструкция === "Труба плоскоовальная") {
    if (позиция.параметры?.ширина != null) {
      if (!числаРавны(товар.side_a_numeric, позиция.параметры.ширина)) {
        return {
          ok: false,
          причина: `размер плоскоовальной не совпадает (нужна большая ось ${позиция.параметры.ширина}, тут ${товар.side_a_numeric})`,
        };
      }
    }
  } else if (позиция.параметры?.ширина != null && товар.side_b_numeric != null) {
    // Профильная — сторона А (ширина) и сторона Б (длина_листа)
    const стороныСовпадают =
      (числаРавны(товар.side_a_numeric, позиция.параметры.ширина) &&
        числаРавны(товар.side_b_numeric, позиция.параметры.длина_листа ?? позиция.параметры.ширина)) ||
      (числаРавны(товар.side_b_numeric, позиция.параметры.ширина) &&
        числаРавны(товар.side_a_numeric, позиция.параметры.длина_листа ?? позиция.параметры.ширина));
    if (!стороныСовпадают) {
      return { ok: false, причина: `размер не совпадает (нужно ${позиция.параметры.ширина}x${позиция.параметры.длина_листа ?? позиция.параметры.ширина})` };
    }
  }

  // Стенка (толщина)
  if (позиция.параметры?.стенка != null) {
    if (!числаРавны(товар.thickness_numeric, позиция.параметры.стенка)) {
      return { ok: false, причина: `стенка не совпадает (нужна ${позиция.параметры.стенка}, тут ${товар.thickness_numeric})` };
    }
  }

  // Длина
  if (позиция.параметры?.длина != null) {
    if (!числаРавны(товар.length_numeric, позиция.параметры.длина)) {
      return { ok: false, причина: `длина не совпадает (нужна ${позиция.параметры.длина}, тут ${товар.length_numeric})` };
    }
  }

  // Марка стали, если указана явно — сравниваем без учёта регистра/пробелов
  if (позиция.параметры?.марка) {
    const нужнаяМарка = позиция.параметры.марка.toLowerCase().replace(/\s/g, "");
    const маркаТовара = (товар.mark_of_steel || "").toLowerCase().replace(/\s/g, "");
    if (маркаТовара && маркаТовара !== нужнаяМарка) {
      return { ok: false, причина: `марка не совпадает (запрошено "${позиция.параметры.марка}", тут "${товар.mark_of_steel}")` };
    }
  }

  // ГОСТ vs ТУ — та же история, что и на mc.ru: на одном размере у КТЗ
  // тоже встречается и ГОСТ, и отдельно ТУ (подтверждено реальными
  // данными — 15x15x1.5 есть и в ГОСТ 8639, и в ТУ 1373). По умолчанию
  // предпочитаем ГОСТ, ТУ показываем только если явно запрошена (та же
  // спецификация.нужны_оба/приоритет из parser.js, что и на mc.ru).
  const спецификация = позиция.параметры?.спецификация || {};
  const нуженТУ =
    спецификация.нужны_оба === true ||
    спецификация.приоритет === "ТУ" ||
    // ВАЖНО: НЕ \bту\b — \b не работает с кириллицей в JS regex (\b
    // опирается на \w, а туда кириллица не входит). Та же ловушка,
    // что уже была на mc.ru, забыл про неё тут в новом коде.
    /(^|\s)ту(\s|$)/i.test(`${позиция.поисковый_запрос || ""} ${позиция.название || ""}`);
  const этоТУ = /^ту(\s|$)/i.test((товар.gost || "").trim());
  if (этоТУ && !нуженТУ) {
    return { ok: false, причина: "ТУ-спецификация вместо ГОСТ (риск нулевого остатка)" };
  }

  return { ok: true };
}

function подготовьКонтекстТрубы(позиция) {
  return {
    покрытие: определиПокрытие(позиция),
    конструкция: определиКонструкцию(позиция),
  };
}

function оцениВсеТрубы(товары, позиция) {
  const контекст = подготовьКонтекстТрубы(позиция);
  return товары.map((товар) => {
    const { ok, причина } = оцениТрубу(товар, позиция, контекст);
    return { товар, прошёл: ok, причина: причина || null };
  });
}

module.exports = { оцениВсеТрубы, определиПокрытие, определиКонструкцию, этоПрофильная, числаРавны };