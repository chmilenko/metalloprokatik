/**
 * normalize.js — приводит сырой ответ API КТЗ в удобную для фильтрации форму.
 *
 * ВАЖНО про структуру исходных данных: КТЗ отдаёт НЕ "один товар — массив
 * складов", а "одна запись — товар НА ОДНОМ складе" — если один и тот же
 * товар (одинаковый id) есть на нескольких складах, он приходит НЕСКОЛЬКИМИ
 * отдельными объектами в массиве products, у каждого свой единственный
 * элемент в prices[]. Это подтверждено на реальных примерах (труба
 * профильная 10x10x0.8, id=62f26b8d... — два объекта, Дмитров и Волгоград).
 * Поэтому первым делом объединяем такие записи по id в один товар с полным
 * списком складов внутри prices[].
 */

// Мержит сырые записи по id — на выходе один объект на уникальный товар,
// с объединённым массивом prices (все склады сразу)
function объединиПоСкладам(сырыеТовары) {
  const поId = new Map();

  for (const товар of сырыеТовары) {
    const существующий = поId.get(товар.id);
    if (!существующий) {
      // Копируем товар, но prices берём как массив (может быть несколько
      // элементов уже в этой конкретной записи — на всякий случай не
      // теряем, если сайт вдруг когда-то начнёт отдавать сразу пачкой)
      поId.set(товар.id, { ...товар, prices: [...(товар.prices || [])] });
    } else {
      // Тот же товар — добавляем склады из этой записи к уже накопленным
      существующий.prices.push(...(товар.prices || []));
    }
  }

  return [...поId.values()];
}

// Достаёт вес — тонны, ЕСЛИ ПОЛЯ ВООБЩЕ ЗАПОЛНЕНЫ ТАК, КАК ОЖИДАЕТСЯ.
// ВАЖНО: несмотря на название полей ("weight_kg_per_meter" и т.п.), по
// факту в них хранятся ТОННЫ, а не килограммы — проверено расчётом
// вручную на реальных примерах (лист 0.7мм: weight_t=0.0171 совпадает с
// 1.25×2.5×0.0007×7850=17.17кг=0.0171т, а не с 0.0171кг). Труба хранит
// вес в weight_per_meter_t (тонн на метр), лист — в weight_t (тонн на
// лист целиком); используется только ОДНО из двух полей в зависимости
// от category_type, второе всегда null.
function достаньВесТонн(товар) {
  if (товар.category_type === "Труба") {
    return товар.weight_per_meter_t ?? null;
  }
  if (товар.category_type === "Лист") {
    return товар.weight_t ?? null;
  }
  return товар.weight_per_meter_t ?? товар.weight_t ?? null;
}

// Нормализует один товар — раскладывает по понятным полям, не трогая
// исходные (на случай если что-то ещё понадобится из сырых данных)
function нормализуйТовар(товар) {
  return {
    ...товар,
    весТонн: достаньВесТонн(товар),
    // "физика" — реально взвешенный товар (обычно не своё производство,
    // own:false), "теория" — расчётный вес по номиналу ГОСТ (обычно own:true,
    // собственное производство КТЗ). Та же дихотомия, что мы разбирали на
    // mc.ru (своя прокатка vs перепродажа стороннего товара).
    этоФизика: товар.physical === true,
    этоТеория: товар.theory === true,
  };
}

