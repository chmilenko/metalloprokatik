/**
 * order-ktz.js
 *
 * Оформление Коммерческого предложения на КТЗ и скачивание PDF.
 *
 * Поток (уточнён на реальной разметке 25.09.2026):
 *   1. /cart → клик "Коммерческое предложение" → сайт переходит
 *      (в той же вкладке) на список КП: /history-orders/commerce-offer
 *      (путь через дефис "history-orders", а не "history/orders" —
 *      была ошибка в предыдущей версии файла).
 *   2. Список отсортирован по дате, самая свежая КП — первая строка.
 *   3. У каждой строки — кнопка "⋮" (aria-label="more"). У самой
 *      верхней строки это первая такая кнопка на странице (верстка
 *      сайта дублирует id="long-button" у каждой строки — невалидно,
 *      но querySelectorAll/[0] по aria-label всё равно возвращает
 *      первую в DOM-порядке).
 *   4. Клик по ней открывает выпадающее меню с пунктом-ссылкой
 *      "Скачать КП" — обычный <a href="...pdf" target="_blank">,
 *      прямая ссылка на PDF, кликать не нужно — забираем href.
 *
 * ФИКС (25.09.2026, второй раунд): скачивалось СТАРОЕ КП вместо
 * только что созданного. Причина — клик по кнопке "Коммерческое
 * предложение" делался через page.evaluate(() => btn.click()), что в
 * этом проекте уже не раз не пробивало реальный React-обработчик (см.
 * похожую историю с кнопкой "Личный кабинет" в auth-ktz.js). Когда
 * клик молча не срабатывал, код НЕ падал с ошибкой, а просто сам
 * переходил на список КП через page.goto(KP_LIST_URL) — список
 * показывался как есть, с последним (СТАРЫМ) КП наверху, и мы его
 * благополучно скачивали, не заметив подмены.
 *
 * Теперь: (а) клик — через настоящий Playwright page.locator().click()
 * вместо evaluate; (б) вместо тихого fallback-перехода — явное
 * ожидание реальной навигации (page.waitForURL), и ошибка, если её не
 * произошло; (в) прежде чем открывать меню и качать PDF — проверяем,
 * что дата/время самой верхней строки списка "свежие" (не старше
 * нескольких минут) — если нет, значит новое КП не создалось, и лучше
 * остановиться с понятной ошибкой, чем молча скачать чужое старое КП.
 *
 * ФИКС (25.09.2026, третий раунд): по наблюдению Артёма кнопка
 * "Коммерческое предложение" иногда не реагирует на первый клик сразу
 * после захода на /cart, а после ПЕРЕЗАГРУЗКИ страницы срабатывает
 * нормально. Добавлена одна повторная попытка: если первый клик не
 * привёл к переходу за 15 секунд — перезагружаем страницу, снова
 * закрываем модалки (cookie/"Уведомление", они могут появиться заново
 * после reload) и пробуем клик ещё раз. Падаем с ошибкой, только если
 * не сработало и со второй попытки.
 */

const logger = require("../utils/logger");
const { getPage } = require("../scraper/browser");
const { закройCookieModalЕслиЕсть } = require("./cookieModal");
const { закройУведомлениеЕслиЕсть } = require("./notificationModal");
const path = require("path");
const fs = require("fs");

const delay = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

const CART_URL = "https://ktzholding.com/cart";
const KP_LIST_URL = "https://ktzholding.com/history-orders/commerce-offer";

// С каким максимальным "возрастом" верхней строки списка мы ещё
// доверяем, что это и есть только что созданное нами КП. С запасом на
// рендер/сеть, но не резиновым — если новое КП не появилось за это
// время, что-то реально не так (клик не сработал, сайт завис и т.п.).
// ВАЖНО: сравнение идёт с системным временем процесса — предполагается,
// что бот работает в том же часовом поясе, что и отображаемые на
// сайте даты (Москва), как и весь остальной код проекта.
const МАКС_ВОЗРАСТ_СВЕЖЕЙ_СТРОКИ_МС = 5 * 60 * 1000;

// Сколько раз пробуем клик по "Коммерческое предложение" (1 обычный +
// 1 после перезагрузки страницы), прежде чем сдаться.
const МАКС_ПОПЫТОК_КЛИКА_КП = 2;
const ТАЙМАУТ_ОЖИДАНИЯ_ПЕРЕХОДА_МС = 15000;

/**
 * Оформляет Коммерческое предложение по текущему содержимому корзины
 * КТЗ и скачивает PDF. Предполагается, что корзина уже набита через
 * cart-ktz.js.
 * @returns {Promise<string>} путь к скачанному PDF
 */
async function placeOrderKTZ() {
  const page = await getPage();

  logger.info("КТЗ: переходим в корзину");
  await page.goto(CART_URL);
  await page.waitForLoadState("domcontentloaded");
  await delay(1500);

  await закройCookieModalЕслиЕсть(page);
  await закройУведомлениеЕслиЕсть(page);

  // ============================================================
  // 1-2. КЛИК "КОММЕРЧЕСКОЕ ПРЕДЛОЖЕНИЕ" + ОЖИДАНИЕ ПЕРЕХОДА,
  //      С ОДНОЙ ПОВТОРНОЙ ПОПЫТКОЙ ЧЕРЕЗ ПЕРЕЗАГРУЗКУ СТРАНИЦЫ
  // ============================================================

  await перейдиНаСписокКППоКлику(page);

  await закройУведомлениеЕслиЕсть(page);

  // ============================================================
  // 3. ЖДЁМ ТАБЛИЦУ И ПРОВЕРЯЕМ, ЧТО ВЕРХНЯЯ СТРОКА — СВЕЖАЯ
  // ============================================================

  await page.waitForSelector('button[aria-label="more"]', { timeout: 10000 });
  await проверьЧтоВерхняяСтрокаСвежая(page);

  // ============================================================
  // 4. ОТКРЫВАЕМ МЕНЮ (ТРИ ТОЧКИ) У ПЕРВОЙ (САМОЙ СВЕЖЕЙ) СТРОКИ
  // ============================================================

  const кнопкаМеню = page.locator('button[aria-label="more"]').first();
  await кнопкаМеню.click();
  await delay(500);

  // ============================================================
  // 5. "СКАЧАТЬ КП" — ЭТО ОБЫЧНАЯ ССЫЛКА <a href>, НЕ ДЕЙСТВИЕ.
  //    Прямо забираем её href, переход по клику не нужен.
  // ============================================================

  const pdfUrl = await page.evaluate(() => {
    const ссылки = Array.from(document.querySelectorAll("a"));
    const ссылка = ссылки.find((a) => a.textContent.includes("Скачать КП"));
    return ссылка ? ссылка.href : null;
  });

  if (!pdfUrl) {
    throw new Error('Не нашли ссылку "Скачать КП" после открытия меню строки');
  }

  logger.info("КТЗ: получена ссылка на PDF коммерческого предложения", { pdfUrl });

  return await скачатьPdf(page, pdfUrl);
}

/**
 * Кликает "Коммерческое предложение" и ждёт реальный переход на
 * список КП (page.waitForURL). Если за отведённое время переход не
 * произошёл — по наблюдению Артёма кнопка иногда просто "не заводится"
 * с первого раза сразу после захода в /cart, но после перезагрузки
 * страницы работает нормально. Поэтому один раз перезагружаем страницу
 * (заново закрывая модалки, которые могут появиться после reload) и
 * пробуем ещё раз. Если не сработало и со второй попытки — громко
 * падаем, а не тихо показываем список как есть (см. историю бага со
 * старым КП в шапке файла).
 */
async function перейдиНаСписокКППоКлику(page) {
  for (let попытка = 1; попытка <= МАКС_ПОПЫТОК_КЛИКА_КП; попытка++) {
    const кнопкаКП = page.locator("button").filter({ hasText: "Коммерческое предложение" }).first();
    const кнопкаЕсть = (await кнопкаКП.count()) > 0;

    if (!кнопкаЕсть) {
      throw new Error(
        'Не нашли кнопку "Коммерческое предложение" в корзине КТЗ — возможно, корзина пуста',
      );
    }

    await кнопкаКП.click();

    try {
      await page.waitForURL(/commerce-offer/, { timeout: ТАЙМАУТ_ОЖИДАНИЯ_ПЕРЕХОДА_МС });
      return; // успех — переход произошёл
    } catch (err) {
      const этоПоследняяПопытка = попытка >= МАКС_ПОПЫТОК_КЛИКА_КП;

      if (этоПоследняяПопытка) {
        throw new Error(
          'После клика по "Коммерческое предложение" страница не перешла на список КП ' +
          `даже после перезагрузки (${МАКС_ПОПЫТОК_КЛИКА_КП} попытки, сейчас на: ${page.url()}) — ` +
          "похоже, клик не сработал или сайт завис. Новое КП, скорее всего, НЕ создалось.",
        );
      }

      logger.warn(
        'КТЗ: клик по "Коммерческое предложение" не привёл к переходу — перезагружаю страницу и пробую снова',
        { попытка, текущийUrl: page.url() },
      );

      await page.reload();
      await page.waitForLoadState("domcontentloaded");
      await delay(1500);
      await закройCookieModalЕслиЕсть(page);
      await закройУведомлениеЕслиЕсть(page);
    }
  }
}

/**
 * Проверяет, что дата/время в САМОЙ ВЕРХНЕЙ строке списка КП —
 * "свежие" (создана только что нами, а не это старая запись, которую
 * мы по ошибке приняли за новую). Бросает исключение, если это не так.
 */
async function проверьЧтоВерхняяСтрокаСвежая(page) {
  const датаТекст = await page.evaluate(() => {
    const строка = document.querySelector("table tbody tr");
    if (!строка) return null;
    const совпадение = строка.textContent.match(/(\d{2})\.(\d{2})\.(\d{4})\s+(\d{2}):(\d{2})/);
    return совпадение ? совпадение[0] : null;
  });

  if (!датаТекст) {
    logger.warn("КТЗ: не удалось прочитать дату верхней строки списка КП — пропускаю проверку свежести");
    return;
  }

  const совпадение = датаТекст.match(/(\d{2})\.(\d{2})\.(\d{4})\s+(\d{2}):(\d{2})/);
  const [, day, month, year, hh, mm] = совпадение;
  const датаСтроки = new Date(Number(year), Number(month) - 1, Number(day), Number(hh), Number(mm));
  const возрастМс = Date.now() - датаСтроки.getTime();

  if (возрастМс > МАКС_ВОЗРАСТ_СВЕЖЕЙ_СТРОКИ_МС) {
    throw new Error(
      `Самая свежая запись в списке КП датирована ${датаТекст} — это больше ` +
      `${Math.round(МАКС_ВОЗРАСТ_СВЕЖЕЙ_СТРОКИ_МС / 60000)} минут назад. Похоже, новое КП не создалось ` +
      "(клик по кнопке не сработал), а мы чуть не скачали чужое старое КП. Останавливаюсь.",
    );
  }
}

async function скачатьPdf(page, url) {
  const outputDir = path.join(__dirname, "../../downloads");
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  const filename = `ktz_kp_${Date.now()}.pdf`;
  const filepath = path.join(outputDir, filename);

  const pdfBuffer = await page.evaluate(async (pdfUrl) => {
    const response = await fetch(pdfUrl);
    const buffer = await response.arrayBuffer();
    return Array.from(new Uint8Array(buffer));
  }, url);

  fs.writeFileSync(filepath, Buffer.from(pdfBuffer));

  logger.info("КТЗ: PDF коммерческого предложения скачан", { path: filepath });

  return filepath;
}

module.exports = { placeOrderKTZ, проверьЧтоВерхняяСтрокаСвежая, перейдиНаСписокКППоКлику };