/**
 * baseOptimizer.js
 *
 * ИЗОЛИРОВАННЫЙ модуль — пока НЕ подключён к основному потоку. Цель: для
 * ВСЕЙ заявки целиком (не для одной позиции) подобрать одну или
 * минимальное количество баз/складов, с которых можно собрать все
 * позиции — с приоритетом на "удобные" склады.
 *
 * Правила от менеджера (дословно):
 * 1. Приоритетные базы, по убыванию: Карачарово, Очаково, Балашиха,
 *    Электроугли. Остальные — в меньшей степени.
 * 2. Сначала пытаемся собрать ВСЁ с одной базы — это "оптимальный"
 *    вариант (меньше отгрузок). Если такая база есть, но она НЕ из
 *    приоритетного списка — обязательно спросить менеджера
 *    ("Все твои позиции есть в Лобне, выставлять?").
 * 3. Если отказ (или ни одна база не покрывает всё) — переходим к
 *    минимальному набору баз, отдавая предпочтение приоритетным
 *    ("Тогда будет Карачарово и Очаково. Ок?").
 *
 * Вход: found — массив { position, variants }, где variants — уже
 * отфильтрованные кандидаты по этой позиции (как формирует scraper/index.js
 * в фазе 1 processOrder, ДО текущего selectBestVariant).
 * Выход: рекомендация с объяснением + вопрос для менеджера, если нужно
 * подтверждение.
 *
 * Чистая функция, браузер не трогает — тестируется на реальных JSON
 * из логов.
 */

const ПРИОРИТЕТ_БАЗ = ['Карачарово', 'Очаково', 'Балашиха', 'Электроугли']

// Разбирает строку СМЦ вида "Москва\nКарачарово, Очаково, Электроугли"
// или просто "Карачарово" в список отдельных названий баз. "Москва" и
// подобные региональные ярлыки (не являются складом сами по себе) —
// отбрасываем, если после них есть конкретные названия баз.
function разберБазы(смц) {
  if (!смц) return []

  const строки = String(смц).split('\n').map(s => s.trim()).filter(Boolean)
  // Если первая строка похожа на регион ("Москва" и т.п.) и есть ещё
  // строки — берём остальные. Если строка одна — она и есть база(ы).
  const источник = строки.length > 1 ? строки.slice(1) : строки

  return источник
    .flatMap(s => s.split(','))
    .map(s => s.trim())
    .filter(Boolean)
}

// Для позиции — множество всех баз, где ЕСТЬ хотя бы один подходящий
// вариант (по всем отфильтрованным кандидатам сразу)
function базыПозиции(variants) {
  const базы = new Set()
  for (const v of variants) {
    for (const б of разберБазы(v.смц)) базы.add(б)
  }
  return базы
}

// Индекс приоритета базы (меньше = приоритетнее). Не из списка — большое число.
function приоритетБазы(база) {
  const idx = ПРИОРИТЕТ_БАЗ.indexOf(база)
  return idx === -1 ? 999 : idx
}

// Среди вариантов позиции находит самый дешёвый, который покрывает
// конкретную базу (нужно, чтобы понять, по какой цене реально брать
// позицию, если решили собирать именно с этой базы)
function вариантДляБазы(variants, база) {
  const подходящие = variants.filter(v => разберБазы(v.смц).includes(база))
  if (подходящие.length === 0) return null
  return подходящие.reduce((min, v) => v.цена_от_1т < min.цена_от_1т ? v : min)
}

/**
 * Главная функция — подбирает базу/базы для всей заявки.
 *
 * @param {Array<{position: object, variants: object[]}>} found
 * @param {Set<string>|string[]} [exclude] - базы, которые нужно исключить
 *        из рассмотрения (например, менеджер уже отказался от них)
 * @returns {object} рекомендация
 */
function подбериБазу(found, exclude = []) {
  const исключённые = new Set(exclude)

  if (found.length === 0) {
    return { тип: 'нет_позиций', сообщение: 'Нет ни одной найденной позиции для подбора базы.' }
  }

  const базыПоПозициям = found.map(f => {
    const набор = базыПозиции(f.variants)
    исключённые.forEach(б => набор.delete(б))
    return набор
  })

  // Все базы, которые встречаются хоть где-то — кандидаты на "единую базу"
  const всеБазы = new Set()
  базыПоПозициям.forEach(set => set.forEach(б => всеБазы.add(б)))

  // Базы, которые покрывают АБСОЛЮТНО ВСЕ позиции (пересечение множеств)
  const единыеБазы = [...всеБазы].filter(база =>
    базыПоПозициям.every(набор => набор.has(база))
  )

  if (единыеБазы.length > 0) {
    // Есть хотя бы одна база, откуда можно собрать всё. Предпочитаем
    // приоритетную, если она в их числе.
    единыеБазы.sort((a, b) => приоритетБазы(a) - приоритетБазы(b))
    const выбраннаяБаза = единыеБазы[0]
    const этоПриоритетная = ПРИОРИТЕТ_БАЗ.includes(выбраннаяБаза)

    const позиции = found.map(f => ({
      название: f.position.название,
      вариант: вариантДляБазы(f.variants, выбраннаяБаза),
    }))

    return {
      тип: 'одна_база',
      база: выбраннаяБаза,
      этоПриоритетная,
      требуетПодтверждения: !этоПриоритетная,
      позиции,
      вопросДляМенеджера: этоПриоритетная
        ? null
        : `Все позиции есть на базе "${выбраннаяБаза}", выставлять?`,
      объяснение: этоПриоритетная
        ? `Все позиции собираются с одной приоритетной базы "${выбраннаяБаза}" — лучший вариант, отдельного подтверждения не требует.`
        : `Все позиции можно собрать с одной базы "${выбраннаяБаза}", но она не из приоритетного списка — нужно подтверждение менеджера.`,
    }
  }

  // Единой базы нет — ищем минимальный набор баз (жадный set cover),
  // при равном покрытии предпочитаем более приоритетную базу
  const непокрытые = new Set(found.map((_, i) => i))
  const выбранныеБазы = []

  while (непокрытые.size > 0) {
    let лучшаяБаза = null
    let лучшееПокрытие = -1

    for (const база of всеБазы) {
      if (выбранныеБазы.includes(база)) continue

      let покрытие = 0
      for (const i of непокрытые) {
        if (базыПоПозициям[i].has(база)) покрытие++
      }

      if (покрытие === 0) continue

      const лучше =
        покрытие > лучшееПокрытие ||
        (покрытие === лучшееПокрытие && лучшаяБаза !== null &&
          приоритетБазы(база) < приоритетБазы(лучшаяБаза))

      if (лучшаяБаза === null || лучше) {
        лучшаяБаза = база
        лучшееПокрытие = покрытие
      }
    }

    if (лучшаяБаза === null) break // не должно случиться, но не зацикливаемся
    выбранныеБазы.push(лучшаяБаза)
    for (const i of [...непокрытые]) {
      if (базыПоПозициям[i].has(лучшаяБаза)) непокрытые.delete(i)
    }
  }

  const непокрытыеПозиции = [...непокрытые].map(i => found[i].position.название)

  // Для каждой позиции — на какой из выбранных баз она реально едет
  // (первая по приоритету из выбранных, которая её покрывает)
  выбранныеБазы.sort((a, b) => приоритетБазы(a) - приоритетБазы(b))
  const позиции = found.map(f => {
    const база = выбранныеБазы.find(б => базыПозиции(f.variants).has(б))
    return {
      название: f.position.название,
      база: база || null,
      вариант: база ? вариантДляБазы(f.variants, база) : null,
    }
  })

  const всеПриоритетные = выбранныеБазы.every(б => ПРИОРИТЕТ_БАЗ.includes(б))

  return {
    тип: 'несколько_баз',
    базы: выбранныеБазы,
    непокрытыеПозиции,
    позиции,
    требуетПодтверждения: true,
    вопросДляМенеджера: непокрытыеПозиции.length > 0
      ? `Не все позиции удалось собрать даже несколькими базами (${выбранныеБазы.join(', ')}). Без базы: ${непокрытыеПозиции.join(', ')}. Что делать?`
      : `Тогда будет ${выбранныеБазы.join(' и ')}. Ок?`,
    объяснение: всеПриоритетные
      ? `Единой базы нет, но минимальный набор (${выбранныеБазы.join(', ')}) целиком состоит из приоритетных баз.`
      : `Единой базы нет, минимальный набор баз: ${выбранныеБазы.join(', ')} (не все из приоритетного списка).`,
  }
}

module.exports = { подбериБазу, разберБазы, ПРИОРИТЕТ_БАЗ }