/**
 * decisionTable.js
 *
 * ИЗОЛИРОВАННЫЙ модуль — пока НЕ подключён к основному потоку поиска.
 * Цель: строить полностью прозрачную таблицу решения по каждой позиции —
 * какие варианты были доступны, кто прошёл фильтр, кто отклонён и почему,
 * что в итоге выбрано и почему. Это инструмент ДОВЕРИЯ к боту — сначала
 * нужно накопить историю решений и убедиться, что бот выбирает разумно,
 * прежде чем давать ему больше автономии (замены марок, оптимизация по
 * базам и т.п.).
 *
 * Вход: позиция (как её понял парсер) + ВСЕ сырые кандидаты со страницы
 * (до фильтрации — то, что сейчас теряется после filterVariants).
 * Выход: структура с полным разбором + готовый текст для лога/менеджера.
 *
 * Ничего не ищет и не ходит в браузер — чистая функция над готовыми
 * данными. Поэтому тестируется на реальных JSON из логов, без mc.ru.
 */

const fs = require('fs')
const path = require('path')
const { оцениВсеВарианты } = require('./search')

const DECISIONS_DIR = path.join(__dirname, '..', '..', 'logs', 'decisions')

// Достаёт числовое значение длины варианта (для сравнения "чётко заданная
// длина" vs "н/д"/диапазон). Дублирует ту же идею, что уже есть в
// scraper/index.js (имеетОпределённуюДлину) — сознательно НЕ импортирую
// оттуда, чтобы модуль оставался изолированным, как договорились. Когда
// будем подключать decisionTable к основному потоку — это дублирование
// уйдёт первым.
function имеетОпределённуюДлину(v) {
  const длина = String(v.длина || '').trim()
  return /^\d+$/.test(длина)
}

function этоГост(v) {
  return v.название.toLowerCase().includes('гост')
}

/**
 * Выбирает "лучший" вариант среди прошедших фильтр — та же логика
 * приоритетов, что в scraper/index.js: ГОСТ > ТУ, чёткая длина > "н/д",
 * минимальная цена внутри группы. Возвращает выбранный вариант + текстовое
 * объяснение, почему выбран именно он (для прозрачности в таблице).
 */
function выбериЛучшего(прошедшие) {
  if (прошедшие.length === 0) return { вариант: null, объяснение: 'нет ни одного подходящего варианта' }

  const гостВарианты = прошедшие.filter(этоГост)
  let источник = гостВарианты.length > 0 ? гостВарианты : прошедшие
  const шагиОбъяснения = []

  if (гостВарианты.length > 0) {
    шагиОбъяснения.push(`сузили до ГОСТ (${гостВарианты.length} из ${прошедшие.length})`)
  } else {
    шагиОбъяснения.push(`ГОСТ-вариантов нет, берём из всех (${прошедшие.length})`)
  }

  const сОпределённойДлиной = источник.filter(имеетОпределённуюДлину)
  if (сОпределённойДлиной.length > 0 && сОпределённойДлиной.length < источник.length) {
    шагиОбъяснения.push(`сузили до вариантов с чёткой длиной (${сОпределённойДлиной.length} из ${источник.length}, остальные "н/д"/диапазон отброшены как рискованные)`)
    источник = сОпределённойДлиной
  } else if (сОпределённойДлиной.length > 0) {
    источник = сОпределённойДлиной
  }

  const выбранный = источник.reduce((min, v) => v.цена_от_1т < min.цена_от_1т ? v : min)
  шагиОбъяснения.push(`минимальная цена среди оставшихся (${выбранный.цена_от_1т} ₽/т)`)

  return { вариант: выбранный, объяснение: шагиОбъяснения.join(' → ') }
}

/**
 * Строит полную таблицу решения по одной позиции.
 *
 * @param {object} position - позиция как её распарсил parser.js
 * @param {object[]} rawVariants - ВСЕ сырые кандидаты со страницы (до фильтра)
 * @returns {object} структура с разбором + текстовое представление
 */
function построитьТаблицу(position, rawVariants) {
  const оценённые = оцениВсеВарианты(rawVariants, position)
  const прошедшие = оценённые.filter(r => r.прошёл).map(r => r.вариант)
  const отклонённые = оценённые.filter(r => !r.прошёл)

  const { вариант: выбрано, объяснение } = выбериЛучшего(прошедшие)

  // Группируем отклонённых по причине — удобнее читать, когда одинаковых
  // причин много (например 10 нержавеющих вариантов отклонены одной строкой)
  const причиныСводка = {}
  for (const r of отклонённые) {
    причиныСводка[r.причина] = (причиныСводка[r.причина] || 0) + 1
  }

  return {
    позиция: position.название,
    запрошено: {
      марка: position.параметры?.марка || null,
      длина: position.параметры?.длина || null,
      номер: position.параметры?.номер || null,
    },
    всегоКандидатов: rawVariants.length,
    прошлоФильтр: прошедшие.length,
    отклонено: отклонённые.length,
    выбрано,
    объяснениеВыбора: объяснение,
    прошедшие,
    отклонённые: отклонённые.map(r => ({ вариант: r.вариант, причина: r.причина })),
    причиныСводка,
  }
}

/**
 * Строит человекочитаемый текст таблицы — для лога или сообщения менеджеру.
 */
function таблицаТекстом(таблица) {
  const строки = []
  строки.push(`━━━ ${таблица.позиция} ━━━`)
  строки.push(`Запрошено: марка=${таблица.запрошено.марка || '—'}, длина=${таблица.запрошено.длина || '—'}, номер=${таблица.запрошено.номер || '—'}`)
  строки.push(`Кандидатов всего: ${таблица.всегоКандидатов} | прошло фильтр: ${таблица.прошлоФильтр} | отклонено: ${таблица.отклонено}`)
  строки.push('')

  if (таблица.выбрано) {
    строки.push(`✅ ВЫБРАНО: ${таблица.выбрано.название} | марка=${таблица.выбрано.марка || '—'} | длина=${таблица.выбрано.длина || '—'} | ${таблица.выбрано.смц} | ${таблица.выбрано.цена_от_1т} ₽/т`)
    строки.push(`   Почему: ${таблица.объяснениеВыбора}`)
  } else {
    строки.push(`❌ Ничего не выбрано: ${таблица.объяснениеВыбора}`)
  }

  if (таблица.прошедшие.length > 1) {
    строки.push('')
    строки.push(`Остальные прошедшие фильтр (не выбраны, но подходят):`)
    for (const v of таблица.прошедшие) {
      if (v === таблица.выбрано) continue
      строки.push(`   • ${v.название} | ${v.марка || '—'} | ${v.длина || '—'} | ${v.смц} | ${v.цена_от_1т} ₽/т`)
    }
  }

  if (таблица.отклонено > 0) {
    строки.push('')
    строки.push(`Отклонённые (по причинам):`)
    for (const [причина, кол] of Object.entries(таблица.причиныСводка)) {
      строки.push(`   ${кол}× — ${причина}`)
    }
  }

  return строки.join('\n')
}

/**
 * Сохраняет таблицу решения на диск для последующего аудита —
 * data/decisions/{orderId}.json, один файл на заказ, накапливает все
 * позиции этого заказа по мере обработки.
 */
function сохраниТаблицу(orderId, таблица) {
  try {
    if (!fs.existsSync(DECISIONS_DIR)) {
      fs.mkdirSync(DECISIONS_DIR, { recursive: true })
    }

    const filePath = path.join(DECISIONS_DIR, `${orderId}.json`)
    let существующие = []

    if (fs.existsSync(filePath)) {
      try {
        существующие = JSON.parse(fs.readFileSync(filePath, 'utf8'))
      } catch {
        существующие = []
      }
    }

    существующие.push({ время: new Date().toISOString(), ...таблица })
    fs.writeFileSync(filePath, JSON.stringify(существующие, null, 2), 'utf8')
    return filePath
  } catch (err) {
    console.error('Не удалось сохранить таблицу решения:', err.message)
    return null
  }
}

module.exports = { построитьТаблицу, таблицаТекстом, сохраниТаблицу }