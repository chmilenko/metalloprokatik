function форматЦены(цена) {
  const n = Number(цена);
  return Number.isFinite(n) ? n.toLocaleString("ru-RU") : String(цена);
}

/**
 * Один блок текста на позицию: количество, лучшая база (точное совпадение приоритетнее
 * альтернативы), ещё две ближайшие по цене и справочные поставщики, если они дешевле.
 * Возвращает массив сообщений (каждое < 3500 символов).
 */
function собратьСводкуДляМенеджера(индексСводки, итог) {
  let приоритет = [];
  try {
    приоритет = getBasePriority() || [];
  } catch (e) { /* без приоритета — просто самая дешёвая */ }
  const блоки = [];
  индексСводки.forEach((з, k) => {
    const p = з.position || {};
    const колво = p.количество_не_указано
      ? "кол-во не указано"
      : [p.количество, p.единица].filter((x) => x != null && x !== "").join(" ");
    const заголовок = `${k + 1}. ${з.названиеСтроки}${колво ? ` — ${колво}` : ""}`;

    const варианты = [];
    for (const [база, яч] of Object.entries(з.ячейки || {})) {
      const v = яч?.варианты?.[0];
      const цена = Number(v?.цена_от_1т);
      if (!Number.isFinite(цена)) continue;
      варианты.push({ база, цена, альтернатива: яч.тип === "альтернатива" });
    }
    варианты.sort((a, b) => Number(a.альтернатива) - Number(b.альтернатива) || a.цена - b.цена);

    const строки = [заголовок];
    if (варианты.length === 0) {
      const справ = Object.keys(з.справочные || {});
      строки.push(
        справ.length > 0
          ? `   ℹ️ Заказать негде, цена только у: ${справ.join(", ")}`
          : "   ❌ Не найдено",
      );
    } else {
      // Точное совпадение приоритетнее альтернативы; среди точных лидер — самая дешёвая
      // ПРИОРИТЕТНАЯ база (настройка /bases), а если она дороже минимума по всем базам,
      // дешёвую неприоритетную показываем отдельной строкой «💰».
      const точные = варианты.filter((v) => !v.альтернатива);
      const пул = точные.length > 0 ? точные : варианты;
      const знак = точные.length > 0 ? "✅" : "🟧";
      const минВсех = Math.min(...пул.map((v) => v.цена));
      const приор = пул.filter((v) => приоритет.includes(v.база));
      const цЛидера = приор.length > 0 ? Math.min(...приор.map((v) => v.цена)) : минВсех;
      const порядок = (v) => {
        const k = приоритет.indexOf(v.база);
        return k === -1 ? 999 : k;
      };
      const лидеры = пул.filter((v) => v.цена === цЛидера).sort((a, b) => порядок(a) - порядок(b));
      строки.push(`   ${знак} ${лидеры.map((v) => v.база).join(", ")} — ${форматЦены(цЛидера)} ₽`);

      const дешевле = цЛидера > минВсех ? пул.filter((v) => v.цена === минВсех) : [];
      if (дешевле.length > 0) {
        строки.push(
          `   💰 Дешевле на ${форматЦены(цЛидера - минВсех)} ₽: ${дешевле.map((v) => v.база).join(", ")} — ${форматЦены(минВсех)} ₽`,
        );
      }

      // Остальные: базы с одинаковой ценой склеиваем, показываем до двух групп
      const остальные = варианты.filter((v) => !лидеры.includes(v) && !дешевле.includes(v));
      const группы = new Map();
      for (const v of остальные) {
        const ключ = `${v.цена}|${v.альтернатива ? 1 : 0}`;
        if (!группы.has(ключ)) группы.set(ключ, { цена: v.цена, альтернатива: v.альтернатива, базы: [] });
        группы.get(ключ).базы.push(v.база);
      }
      const спискоГрупп = [...группы.values()].sort(
        (a, b) => Number(a.альтернатива) - Number(b.альтернатива) || a.цена - b.цена,
      );
      if (спискоГрупп.length > 0) {
        строки.push(
          "   ещё: " +
            спискоГрупп
              .slice(0, 2)
              .map((г) => `${г.базы.join(", ")} ${форматЦены(г.цена)}${г.альтернатива ? " 🟧" : ""}`)
              .join("; "),
        );
      }
      for (const [база, ин] of Object.entries(з.справочные || {})) {
        if (ин?.точная && Number(ин.цена) < минВсех) {
          строки.push(`   💙 ${база}: ${форматЦены(ин.цена)} ₽ (дешевле, только сравнение)`);
        }
      }
    }
    блоки.push(строки.join("\n"));
  });

  const шапка =
    `📋 Лучшие варианты по заявке (${индексСводки.length} поз.)\n` +
    `✅ точное · 🟧 альтернатива (другая марка/длина/ТУ)` +
    (итог?.нет?.length ? ` · ❌ нет: ${итог.нет.length}` : "");

  const сообщения = [];
  let текущее = шапка;
  for (const б of блоки) {
    if ((текущее + "\n\n" + б).length > 3500) {
      сообщения.push(текущее);
      текущее = б;
    } else {
      текущее += "\n\n" + б;
    }
  }
  сообщения.push(текущее);
  return сообщения;
}

/**
 * Формирует и отправляет Excel-таблицу по всей заявке.
 * Вызывается прямо из обработчика обычного текстового сообщения —
 * без отдельной команды, см. bot/handlers/message.js.
 */
async function экспортироватьЗаявку(ctx, text) {
  try {
    // Один «живой» прогресс-экран вместо десятков сообщений: бот правит его
    // по ходу работы (см. utils/liveMessage.js).
    const замерСтарт = Date.now();
    const live = await создатьЖивоеСообщение(ctx, "🔍 Анализирую заявку...");
    const positions = await parseOrder(text);
    const замерРазбор = Date.now() - замерСтарт;
    const замерПозиций = []; // [{название, ктзЖдалиСек, mcСек}] — для итоговой строки в логе

    if (positions.length === 0) {
      await live.завершить("❌ Не нашёл позиций в заявке.");
      return;
    }

    const отметки = positions.map(() => "▫️"); // ▫️ ждёт · ⏳ ищу · ✅ готово · ❌ нигде нет · ⚠️ ошибка
    let заметка = "";
    const показатьПрогресс = (заголовок) => {
      const строки = positions.map((п, k) => `${отметки[k]} ${String(п.название).slice(0, 60)}`);
      live.обновить(
        `${заголовок}\n\n${строки.join("\n")}` + (заметка ? `\n\n${заметка}` : ""),
      );
    };
    const название_источников = "mc.ru, КТЗ, Дипос, Брок";
    показатьПрогресс(`📋 Нашёл ${positions.length} поз. Ищу: ${название_источников}`);

    const строкиТаблицы = [];
    const позицииДляСводки = []; // {position, прошедшие, оценённые} — для листа "Сводная по базам"

    // КТЗ ищет в ФОНЕ, по одной позиции за раз, пока браузер занят mc.ru (КТЗ браузер не
    // использует — это поиск по каталогу, поэтому они друг другу не мешают). К моменту,
    // когда очередь доходит до позиции, результат КТЗ обычно уже готов.
    const ктзФон = [];
    let ктзЦепочка = Promise.resolve();
    positions.forEach((п, k) => {
      ктзФон[k] = ктзЦепочка = ктзЦепочка.then(() => безопасноНайдиНаКТЗ(п));
    });

    // Справочные источники (КТЗ, Дипос, Брок) собираем ПОСЛЕ того, как mc.ru обработал ВСЕ
    // позиции: КТЗ ищет в фоне параллельно, и ждать его внутри цикла значило бы простаивать
    // браузеру (если КТЗ медленный — до 45 с на первой позиции).
    const собратьСправочные = async (i, position) => {
      const замерКтзСтарт = Date.now();
      const { variants: ктзВариантыПоиска, оценённые: ктзОценённыеПоиска } = await ктзФон[i];
      const ктзЖдали = Date.now() - замерКтзСтарт;
      // Дипос — прайс-лист без корзины, только для сравнения цен. Идёт в
      // сводную той же дорожкой, что и КТЗ (отдельная колонка "Дипос: Москва").
      const дипос = безопасноНайдиВДипосе(position);
      // Брок Инвест — тоже только прайс (склад «Октябрьский»), та же дорожка.
      const брок = безопасноНайдиВБроке(position);
      return {
        ктзПрошедшие: [...ктзВариантыПоиска, ...дипос.variants, ...брок.variants],
        ктзОценённые: [...ктзОценённыеПоиска, ...дипос.оценённые, ...брок.оценённые],
        ктзЖдали,
      };
    };

    // ШАГ 1: mc.ru по всем позициям подряд (браузер не простаивает).
    const результатыMc = [];
    for (let i = 0; i < positions.length; i++) {
      const position = positions[i];
      отметки[i] = "⏳";
      заметка = "";
      показатьПрогресс(`🔍 Ищу ${i + 1}/${positions.length}`);
      const замерMcСтарт = Date.now();

      let найденное = null;
      let ошибкаMc = null;
      try {
        найденное = await findPosition(position, async (msg) => {
          // служебные сообщения поиска показываем строкой под списком, а не отдельными сообщениями
          заметка = String(msg).slice(0, 300);
          показатьПрогресс(`🔍 Ищу ${i + 1}/${positions.length}`);
        });
      } catch (err) {
        logger.error("Ошибка поиска позиции при экспорте", {
          название: position.название,
          error: err.message,
        });
        ошибкаMc = err;
      }
      результатыMc[i] = {
        найденное,
        ошибкаMc,
        замерMcСек: Math.round((Date.now() - замерMcСтарт) / 100) / 10,
      };
      отметки[i] = "☑️"; // mc.ru готов, ждём справочные источники
    }

    // ШАГ 2: сводим mc.ru со справочными источниками, строго в порядке позиций.
    заметка = "Дожидаюсь КТЗ и прайсов…";
    показатьПрогресс("🔍 Собираю результаты");
    for (let i = 0; i < positions.length; i++) {
      const position = positions[i];
      const { найденное, ошибкаMc, замерMcСек } = результатыMc[i];

      if (ошибкаMc) {
        строкиТаблицы.push({
          позиция: position,
          вариант: null,
          статус: "ошибка поиска",
          причина: ошибкаMc.message,
        });
        отметки[i] = "⚠️";
        // КТЗ мог найти что-то, даже если mc.ru упал — не теряем это
        const { ктзПрошедшие, ктзОценённые } = await собратьСправочные(i, position);
        позицииДляСводки.push({
          position,
          прошедшие: ктзПрошедшие,
          оценённые: ктзОценённые,
        });
        continue;
      }

      const { ктзПрошедшие, ктзОценённые, ктзЖдали } = await собратьСправочные(i, position);
      замерПозиций.push({
        название: String(position.название).slice(0, 40),
        ктзЖдалиСек: Math.round(ктзЖдали / 100) / 10,
        mcСек: замерMcСек,
      });
      const result = найденное.result;
      const кандидаты = найденное.rawRows?.length
        ? найденное.rawRows
        : result.variants || [];

      if (кандидаты.length === 0) {
        строкиТаблицы.push({
          позиция: position,
          вариант: null,
          статус: "не найдено",
          причина: "сайт не вернул ни одного результата по этому запросу",
        });
        отметки[i] = ктзПрошедшие.length > 0 ? "✅" : "❌";
        позицииДляСводки.push({
          position,
          прошедшие: ктзПрошедшие,
          оценённые: ктзОценённые,
        });
        continue;
      }

      const оценённые = оцениВсеВарианты(кандидаты, position);
      const прошедшие = оценённые.filter((r) => r.прошёл).map((r) => r.вариант);
      отметки[i] = прошедшие.length > 0 || ктзПрошедшие.length > 0 ? "✅" : "❌";
      const выбранные = выбериЛучшего(прошедшие, position);

      // Сводная получает mc.ru + КТЗ вместе. "Заявка" (детальная,
      // по-кандидатно, ниже по коду) — по-прежнему только mc.ru.
      позицииДляСводки.push({
        position,
        прошедшие: [...прошедшие, ...ктзПрошедшие],
        оценённые: [...оценённые, ...ктзОценённые],
      });

      for (const { вариант, прошёл, причина } of оценённые) {
        строкиТаблицы.push({
          позиция: position,
          вариант,
          статус: прошёл
            ? выбранные.includes(вариант)
              ? "выбран"
              : "подходит"
            : "отклонён",
          причина: причина || "",
        });
      }
    }

    заметка = "";
    показатьПрогресс("📊 Собираю Excel-таблицу…");
    const { filepath, индексСводки, базыСписок } = await построитьXlsx(
      строкиТаблицы,
      позицииДляСводки,
    );

    // В try/catch отдельно от общего — чтобы сбой записи на диск не
    // сожрал уже готовый Excel-файл: он должен уйти пользователю в любом
    // случае, даже если /order потом не сможет найти эту таблицу
    try {
      добавьТаблицу(ctx.from.id, {
        text,
        позицииДляСводки,
        индексСводки,
        базыСписок,
      });
    } catch (err) {
      logger.error(
        "Не удалось сохранить сводную таблицу на диск — /order по этой заявке работать не будет",
        {
          userId: ctx.from.id,
          error: err.message,
        },
      );
    }

    const итог = посчитайИтог(positions, индексСводки);

    // Замер времени: чтобы сравнивать скорость до/после ускорений на одной и той же заявке
    logger.info("Заявка: время обработки", {
      позиций: positions.length,
      всегоСек: Math.round((Date.now() - замерСтарт) / 100) / 10,
      разборLLMСек: Math.round(замерРазбор / 100) / 10,
      суммаMcСек: Math.round(замерПозиций.reduce((а, п) => а + п.mcСек, 0) * 10) / 10,
      суммаОжиданияКТЗСек: Math.round(замерПозиций.reduce((а, п) => а + п.ктзЖдалиСек, 0) * 10) / 10,
      позиции: замерПозиций,
    });

    // Финальный вид прогресс-экрана; сам итог (и уведомление) — новыми сообщениями ниже
    {
      const строки = positions.map((п, k) => `${отметки[k]} ${String(п.название).slice(0, 60)}`);
      await live.завершить(`✅ Поиск завершён (${positions.length} поз.)\n\n${строки.join("\n")}`);
    }

    // Режим вывода: по умолчанию менеджеру приходит компактная сводка «лучший вариант по
    // каждой позиции», а таблица отдаётся по кнопке «📊 Таблица Excel».
    // ПРИСЫЛАТЬ_EXCEL=on в .env — вернуть старое поведение (таблица сразу файлом).
    const excelСразу = String(process.env.ПРИСЫЛАТЬ_EXCEL || "off").toLowerCase() === "on";

    if (excelСразу) {
      await ctx.replyWithDocument(
        {
          source: filepath,
          filename: `заявка_${new Date().toISOString().slice(0, 10)}.xlsx`,
        },
        {
          // Telegram режет подпись к файлу на 1024 символах — поэтому здесь
          // только счётчики, а названия позиций уходят отдельным сообщением ниже
          caption:
            `📊 Таблица по заявке:\n` +
            `• Всего позиций: ${positions.length}\n` +
            `• ✅ Точное совпадение (mc.ru/КТЗ): ${итог.точное.length}\n` +
            `• 🟧 Только альтернатива: ${итог.альтернатива.length}\n` +
            `• ❌ Не найдено: ${итог.нет.length}\n\n` +
            `Лист "Заявка" — разбор по mc.ru (что подошло/отклонено и почему). ` +
            `Лист "Сводная по базам" — цены поставщиков, склады КТЗ с префиксом "КТЗ: ", колонки "Дипос: Москва" и "Брок: Октябрьский" — только для сравнения (заказать там через бота нельзя). ` +
            `🟧 — точного совпадения на базе нет, но есть близкое (другая длина/ТУ/марка).\n\n` +
            `✏️ Оформить: /order и выбор склада кнопками.`,
        },
      );

      fs.unlinkSync(filepath);
    } else {
      сохранитьПоследнююТаблицу(ctx.from.id, filepath);
    }

    // Сводка для менеджера: лучший вариант по каждой позиции
    try {
      const текстыСводки = собратьСводкуДляМенеджера(индексСводки, итог);
      for (let k = 0; k < текстыСводки.length; k++) {
        const последний = k === текстыСводки.length - 1;
        await ctx.reply(
          текстыСводки[k] + (последний ? "\n\n✏️ Оформить: /order" : ""),
          !excelСразу && последний
            ? { reply_markup: { inline_keyboard: [[{ text: "📊 Таблица Excel", callback_data: "t|x" }]] } }
            : undefined,
        );
      }
    } catch (e) {
      logger.warn("Не удалось собрать сводку для менеджера", { error: e.message });
    }

    // Позиции без количества, «только альтернатива», «не найдено» и «только справочные» уже
    // видны в сводке выше — здесь только то, чего в ней нет (состояние прайсов Дипоса и Брока).
    const строкиИтога = [];
    const прайсДипоса = инфоОПрайсеДипоса();
    if (!прайсДипоса.есть) {
      строкиИтога.push("ℹ️ Прайс Дипоса не загружен — колонки «Дипос» в таблице нет. Обновить: /dipos");
    } else {
      const сравнение =
        итог.дипос.сЦеной > 0
          ? `Дипос (только сравнение, прайс от ${прайсДипоса.датаПрайсаТекст}): цена есть у ${итог.дипос.сЦеной} из ${positions.length} позиций, ` +
            `дешевле mc.ru/КТЗ — у ${итог.дипос.дешевле} (голубые ячейки).`
          : `Дипос (прайс от ${прайсДипоса.датаПрайсаТекст}): подходящих позиций не нашлось.`;
      let предупреждение = "";
      if (прайсДипоса.устарел) {
        предупреждение =
          `⚠️ Бот не смог скачать прайс Дипоса уже больше суток (последний раз скачан ${прайсДипоса.скачанТекст || "—"}) — ` +
          `цены Дипоса могут не совпадать с сайтом. Обновить: /dipos`;
      } else if (прайсДипоса.давноНеОбновлялся) {
        предупреждение =
          `ℹ️ Бот проверил сайт Дипоса ${прайсДипоса.скачанТекст}: самый свежий прайс там от ${прайсДипоса.датаПрайсаТекст} ` +
          `(новее Дипос не выложил) — цены могут быть неактуальны.`;
      }
      строкиИтога.push(предупреждение ? `${предупреждение}\n${сравнение}` : сравнение);
    }

    const прайсБрока = инфоОПрайсеБрока();
    if (!прайсБрока.есть) {
      строкиИтога.push("ℹ️ Прайсы Брок Инвеста не загружены — колонки «Брок» в таблице нет. Обновить: /brok");
    } else {
      const сБ = итог.справочные["Брок Инвест"];
      const сравнениеБ =
        сБ.сЦеной > 0
          ? `Брок Инвест, склад Октябрьский (только сравнение, прайс от ${прайсБрока.датаПрайсаТекст}): цена есть у ${сБ.сЦеной} из ${positions.length} позиций, ` +
            `дешевле mc.ru/КТЗ — у ${сБ.дешевле} (голубые ячейки).`
          : `Брок Инвест (прайс от ${прайсБрока.датаПрайсаТекст}): подходящих позиций не нашлось.`;
      let предупреждениеБ = "";
      if (прайсБрока.устарел) {
        предупреждениеБ =
          `⚠️ Бот не смог скачать прайсы Брок Инвеста уже больше суток (последний раз ${прайсБрока.скачанТекст || "—"}) — ` +
          `цены могут не совпадать с сайтом. Обновить: /brok`;
      } else if (прайсБрока.нетКатегорий.length > 0) {
        предупреждениеБ = `ℹ️ Часть категорий Брок Инвеста не загружена (${прайсБрока.нетКатегорий.join(", ")}) — по ним цен нет. Обновить: /brok`;
      } else if (прайсБрока.давноНеОбновлялся) {
        предупреждениеБ =
          `ℹ️ Бот проверил сайт Брок Инвеста ${прайсБрока.скачанТекст}: самый свежий прайс там от ${прайсБрока.датаПрайсаТекст} — цены могут быть неактуальны.`;
      }
      строкиИтога.push(предупреждениеБ ? `${предупреждениеБ}\n${сравнениеБ}` : сравнениеБ);
    }
    if (строкиИтога.length > 0) {
      await ctx.reply(строкиИтога.join("\n\n"));
    }
  } catch (err) {
    logger.error("Ошибка экспорта заявки", {
      error: err.message,
      stack: err.stack,
    });

    const МАКС_ДЛИНА_СООБЩЕНИЯ = 3500;
    let текстОшибки = err.message || "неизвестная ошибка";
    if (текстОшибки.length > МАКС_ДЛИНА_СООБЩЕНИЯ) {
      текстОшибки =
        текстОшибки.slice(0, МАКС_ДЛИНА_СООБЩЕНИЯ) +
        `\n\n… (обрезано, полный текст в логах, длина ${err.message.length} символов)`;
    }

    try {
      await ctx.reply(`❌ Ошибка: ${текстОшибки}`);
    } catch (sendErr) {
      logger.error("Не удалось отправить сообщение об ошибке", {
        error: sendErr.message,
      });
      await ctx
        .reply("❌ Не удалось обработать заявку — подробности в логах.")
        .catch(() => {});
    }
  }
}

async function построитьXlsx(строкиТаблицы, позицииДляСводки) {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = "metalloprokatik bot";
  workbook.created = new Date();

  построитьЛистЗаявка(workbook, строкиТаблицы);
  const { индексСводки, базыСписок } = построитьЛистСводки(
    workbook,
    позицииДляСводки,
  );
  построитьЛистДипос(workbook, позицииДляСводки);
  построитьЛистБрок(workbook, позицииДляСводки);

  const outputDir = path.join(__dirname, "../../downloads");
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  const filepath = path.join(outputDir, `заявка_${Date.now()}.xlsx`);
  await workbook.xlsx.writeFile(filepath);

  return { filepath, индексСводки, базыСписок };
}

