// Сводные таблицы по заявкам — нужны для /order (bot/handlers/order.js)
// и /collect (bot/handlers/collect.js). Раньше жили ТОЛЬКО в памяти
// (Map, одна последняя таблица на пользователя) — переживали рестарт
// бота плохо: если бот перезапускался (краш/деплой/nodemon) между
// присылкой заявки и командой /order, сводная пропадала, и /order падал
// с "Нет сохранённой сводной таблицы", даже если заявка была прислана
// только что.
//
// Теперь — пишем на диск (downloads/order-tables-<userId>.json), храним
// до МАКС_ТАБЛИЦ_НА_ПОЛЬЗОВАТЕЛЯ последних заявок на пользователя, и у
// каждой есть TTL (ORDER_TABLE_TTL_MINUTES в .env, по умолчанию 90 мин) —
// протухшую таблицу нельзя использовать для /order (цены/остатки могли
// измениться), бот явно скажет, что она устарела, а не тихо оформит
// заказ по старым данным.
const ДИРЕКТОРИЯ_ТАБЛИЦ = path.join(__dirname, "../../downloads");
const МАКС_ТАБЛИЦ_НА_ПОЛЬЗОВАТЕЛЯ = 3;
const TTL_МИНУТЫ_СВОДНОЙ =
  parseInt(process.env.ORDER_TABLE_TTL_MINUTES, 10) || 90;

function путьТаблиц(userId) {
  return path.join(ДИРЕКТОРИЯ_ТАБЛИЦ, `order-tables-${userId}.json`);
}

function загрузиТаблицы(userId) {
  const путь = путьТаблиц(userId);
  if (!fs.existsSync(путь)) return [];
  try {
    return JSON.parse(fs.readFileSync(путь, "utf-8"));
  } catch (err) {
    logger.error(
      "Не удалось прочитать сохранённые сводные таблицы — повреждён файл",
      {
        userId,
        error: err.message,
      },
    );
    return [];
  }
}

function сохраниТаблицы(userId, таблицы) {
  if (!fs.existsSync(ДИРЕКТОРИЯ_ТАБЛИЦ))
    fs.mkdirSync(ДИРЕКТОРИЯ_ТАБЛИЦ, { recursive: true });
  const финальныйПуть = путьТаблиц(userId);
  const временныйПуть = `${финальныйПуть}.tmp`;
  // Временный файл + переименование — атомарно на уровне ФС (как в
  // orderCheckpoint.js), чтобы краш посередине записи не оставил битый JSON
  fs.writeFileSync(временныйПуть, JSON.stringify(таблицы, null, 2));
  fs.renameSync(временныйПуть, финальныйПуть);
}

function этоЖивая(таблица) {
  return Date.now() - таблица.время < TTL_МИНУТЫ_СВОДНОЙ * 60 * 1000;
}

// Все ещё живые таблицы пользователя, новые сначала — для /order,
// когда их может быть несколько и нужно дать выбрать
function получиВсеТаблицы(userId) {
  return загрузиТаблицы(userId)
    .filter(этоЖивая)
    .sort((a, b) => b.время - a.время);
}

// Последняя живая — обратная совместимость с /collect и любым другим
// местом, которому нужна ровно одна таблица без выбора
function получиКэшСводки(userId) {
  const живые = получиВсеТаблицы(userId);
  return живые.length > 0 ? живые[0] : null;
}

// Конкретная таблица по id (id = момент её создания) — для /order,
// когда живых таблиц несколько и менеджер уже выбрал нужную
function получиТаблицуПоId(userId, id) {
  return получиВсеТаблицы(userId).find((t) => t.id === id) || null;
}

// Добавляет новую таблицу и вытесняет самые старые сверх лимита —
// вытесняет по КОЛИЧЕСТВУ, даже если ещё не протухли по TTL (иначе
// "до 3" не работало бы, если заявки шлют чаще, чем истекает TTL)
function добавьТаблицу(userId, данные) {
  const таблицы = загрузиТаблицы(userId);
  const новая = { id: Date.now(), время: Date.now(), ...данные };
  таблицы.push(новая);
  const оставшиеся = таблицы
    .sort((a, b) => b.время - a.время)
    .slice(0, МАКС_ТАБЛИЦ_НА_ПОЛЬЗОВАТЕЛЯ);
  сохраниТаблицы(userId, оставшиеся);
  return новая;
}

/**
 * Определяет "выбранный" вариант среди прошедших фильтр — та же логика
 * приоритетов, что в scraper/index.js.selectBestVariant: ГОСТ > чёткая
 * длина > минимальная цена. Только для наглядности в таблице (сам выбор
 * в корзину эта функция не делает).
 */
function этоГост(v) {
  return v.название.toLowerCase().includes("гост");
}

function этоТУ(v) {
  const название = v.название.toLowerCase();
  const марка = (v.марка || "").toLowerCase();
  return /(^|\s)ту(\s|$)/i.test(название) || марка.startsWith("ту");
}

function имеетОпределённуюДлину(v) {
  return /^\d+$/.test(String(v.длина || "").trim());
}

// Лучший вариант ВНУТРИ уже сузенной группы — чёткая длина > мин. цена
function лучшийВГруппе(группа) {
  if (группа.length === 0) return null;
  let источник = группа;
  const сДлиной = источник.filter(имеетОпределённуюДлину);
  if (сДлиной.length > 0) источник = сДлиной;
  return источник.reduce((min, v) => (v.цена_от_1т < min.цена_от_1т ? v : min));
}

// Как лучшийВГруппе, но возвращает ВСЕ различные цены внутри той же
// сузенной группы (та же логика приоритетов: сначала предпочитаем
// чёткую длину, если такие есть), а не только минимальную. Нужно для
// случаев, когда на ОДНОЙ базе у одного и того же товара реально два
// разных предложения по разной цене (например собственная прокатка
// собственная прокатка и продукция стороннего комбината) — менеджер попросил показывать
// оба, а не молча схлопывать в минимальную цену.
function всеЦеныВГруппе(группа) {
  if (группа.length === 0) return [];
  let источник = группа;
  const сДлиной = источник.filter(имеетОпределённуюДлину);
  if (сДлиной.length > 0) источник = сДлиной;

  const поЦене = new Map(); // цена → вариант (первый встреченный с этой ценой)
  for (const v of источник) {
    if (!поЦене.has(v.цена_от_1т)) поЦене.set(v.цена_от_1т, v);
  }

  return [...поЦене.values()].sort((a, b) => a.цена_от_1т - b.цена_от_1т);
}

// "Мягкая" причина отклонения — та, что не меняет сути товара (это
// по-прежнему тот же размер/марка/форма, просто другая длина или ТУ
// вместо ГОСТ), а значит годится как альтернатива для пустой ячейки.
// НЕ считаем мягкими причины вроде "не та марка"/"не та форма"/"размер
// не совпадает" — это уже совсем другой товар, не альтернатива.
// ВАЖНО: у труб/прутков причина называется "длина не совпадает", а у
// листов — ДРУГОЙ строкой, "длина листа не совпадает" (проверяется
// отдельным блоком в search.js, через параметры.длина_листа, а не
// параметры.длина) — оба варианта относим к одной и той же "мягкой"
// категории 'длина', иначе альтернативный раскрой листа никогда не
// подхватывался бы (баг, замеченный Александром).
// Марка круга ("альтернатива из белого списка круга") — третий вид
// мягкой причины: Ст3 по умолчанию, но если её физически нет на базе,
// Ст10/Ст20 подходящая замена (та же логика, что и с длиной/ГОСТ-ТУ).
function мягкаяПричина(причина) {
  if (!причина) return null;
  if (причина.startsWith("длина не совпадает")) return "длина";
  if (причина.startsWith("длина листа не совпадает")) return "длина";
  if (причина === "ТУ-спецификация вместо ГОСТ (риск нулевого остатка)")
    return "ту";
  if (
    причина.startsWith(
      "марка стали отличается — альтернатива из белого списка круга",
    )
  )
    return "марка";
  return null;
}

// Короткая метка для отображения в скобках рядом с ценой альтернативы —
// "ТУ", "12м", "Ст10", или несколько сразу, если кандидат не подошёл
// сразу по нескольким мягким причинам.
function меткаАльтернативы(вариант, причины) {
  const части = [];
  if (причины.has("ту")) части.push("ТУ");
  if (причины.has("марка")) части.push(вариант.марка || "др. марка");
  if (причины.has("длина")) {
    const ммСтрока = String(вариант.длина || "").trim();
    let мм = parseInt(ммСтрока, 10);
    if (Number.isFinite(мм)) {
      части.push(`${Math.round(мм / 1000)}м`);
    } else {
      const перваяСтрока = String(вариант.название || "").split("\n")[0];
      const числа = перваяСтрока.match(/\d+/g);
      const последнее =
        числа && числа.length > 0
          ? parseInt(числа[числа.length - 1], 10)
          : null;
      части.push(Number.isFinite(последнее) ? `${последнее}мм` : "др. раскрой");
    }
  }
  return части.join(", ");
}

function альтернативыДляБазы(оценённые, база, position) {
  if (!оценённые || оценённые.length === 0) return [];

  // Дипос: близкие варианты (другая длина/ТУ/2 сорт/сталь не указана) уже
  // посчитаны в scraper-dipos и несут готовую метку — повторно гонять их
  // через оцениВсеВарианты (логику mc.ru) нельзя, формат названий другой.
  if (этоСправочная(база)) {
    const поЦене = new Map();
    for (const { вариант, прошёл } of оценённые) {
      if (прошёл || !вариант._дипос) continue;
      const запись = поЦене.get(вариант.цена_от_1т) || { вариант, метки: new Set() };
      for (const м of String(вариант._альтМетка || "").split(", ")) if (м) запись.метки.add(м);
      поЦене.set(вариант.цена_от_1т, запись);
    }
    return [...поЦене.values()]
      .map(({ вариант, метки }) => ({
        вариант,
        цена: вариант.цена_от_1т,
        метка: [...метки].join(", "),
        ссылка: null,
      }))
      .sort((a, b) => a.цена - b.цена)
      .slice(0, 3);
  }

  const поЦене = new Map();
  for (const { вариант, прошёл, причина } of оценённые) {
    if (прошёл) continue;
    if (вариант._дипос) continue;
    const мягкая = мягкаяПричина(причина);
    if (!мягкая) continue;
    if (!разберБазы(вариант.смц).includes(база)) continue;

    const причины = new Set();

    const безДлины = {
      ...position,
      параметры: { ...position.параметры, длина: null, длина_листа: null },
    };
    const [резБезДлины] = оцениВсеВарианты([вариант], безДлины);
    if (резБезДлины.прошёл) причины.add("длина");
    else {
      const м = мягкаяПричина(резБезДлины.причина);
      if (м) причины.add(м);
    }

    const безТУ = {
      ...position,
      параметры: {
        ...position.параметры,
        спецификация: {
          ...(position.параметры?.спецификация || {}),
          нужны_оба: true,
        },
      },
    };
    const [резБезТУ] = оцениВсеВарианты([вариант], безТУ);
    if (резБезТУ.прошёл) причины.add("ту");
    else {
      const м = мягкаяПричина(резБезТУ.причина);
      if (м) причины.add(м);
    }

    const безМарки = {
      ...position,
      параметры: { ...position.параметры, марка: null },
    };
    const [резБезМарки] = оцениВсеВарианты([вариант], безМарки);
    if (резБезМарки.прошёл) причины.add("марка");
    else {
      const м = мягкаяПричина(резБезМарки.причина);
      if (м) причины.add(м);
    }

    if (причины.size === 0) причины.add(мягкая);

    const запись = поЦене.get(вариант.цена_от_1т) || {
      вариант,
      причины: new Set(),
    };
    for (const п of причины) запись.причины.add(п);
    поЦене.set(вариант.цена_от_1т, запись);
  }

  return [...поЦене.values()]
    .map(({ вариант, причины }) => ({
      вариант, // ДОБАВЛЕНО — нужно для индексСводки (/order), раньше терялось
      цена: вариант.цена_от_1т,
      метка: меткаАльтернативы(вариант, причины),
      ссылка: вариант.cardUrl || вариант.sourceUrl || null,
    }))
    .sort((a, b) => a.цена - b.цена);
}

function выбериЛучшего(прошедшие, position) {
  if (прошедшие.length === 0) return [];

  const спец = position?.параметры?.спецификация || {};

  if (спец.нужны_оба) {
    const лучшийГост = лучшийВГруппе(прошедшие.filter(этоГост));
    const лучшийТУ = лучшийВГруппе(прошедшие.filter(этоТУ));

    const результат =
      спец.приоритет === "ТУ" ? [лучшийТУ, лучшийГост] : [лучшийГост, лучшийТУ];

    const непустые = результат.filter(Boolean);
    return непустые.length > 0 ? непустые : [лучшийВГруппе(прошедшие)];
  }

  let источник = прошедшие.filter(этоГост);
  if (источник.length === 0) источник = прошедшие;
  return [лучшийВГруппе(источник)];
}

/**
 * Ищет позицию на КТЗ — обёртка вокруг найдиНаКТЗ(), которая никогда
 * не бросает исключение наружу (при ошибке — пустой результат + лог).
 * Вызывается НЕЗАВИСИМО от исхода поиска на mc.ru — чтобы результат с
 * КТЗ появился в сводной таблице, даже если mc.ru на этой позиции упал
 * с ошибкой (сеть/браузер) или вообще ничего не нашёл.
 */
async function безопасноНайдиНаКТЗ(position) {
  try {
    return await найдиНаКТЗ(position);
  } catch (err) {
    logger.warn("Не удалось найти позицию на КТЗ", {
      название: position.название,
      error: err.message,
    });
    return { variants: [], оценённые: [] };
  }
}

