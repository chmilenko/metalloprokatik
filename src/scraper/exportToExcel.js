/**
 * Лист "Сводная по базам" — строки: позиции, столбцы: базы (mc.ru +
 * КТЗ, склады КТЗ с префиксом "КТЗ: "), в ячейках: цена подходящего
 * варианта на этой базе.
 *
 * ВОЗВРАЩАЕТ { индексСводки, базыСписок } — та же самая сетка строк и
 * колонок, что попадает в Excel, но с прямой ссылкой на реальный
 * вариант(ы) в каждой непустой ячейке. Строится ПРЯМО ЗДЕСЬ, в момент
 * построения листа — единственный источник истины для команды /order,
 * чтобы номер строки/буква базы никогда не разъезжались с тем, что
 * менеджер реально видит в файле (см. комментарий у кэшТаблиц выше).
 */
function построитьЛистСводки(workbook, позицииДляСводки) {
  const приоритет = getBasePriority();

  const всеБазы = new Set();
  for (const { прошедшие, оценённые } of позицииДляСводки) {
    for (const v of прошедшие) {
      for (const б of разберБазы(v.смц)) всеБазы.add(б);
    }
    for (const { вариант, прошёл, причина } of оценённые || []) {
      if (прошёл) continue;
      if (!мягкаяПричина(причина) && !вариант._дипос) continue;
      for (const б of разберБазы(вариант.смц)) всеБазы.add(б);
    }
  }

  // Московские базы mc.ru (белый список) + ЛЮБЫЕ базы КТЗ (у них
  // склады по всей стране, не только Москва — фильтровать по региону
  // для КТЗ пока не просили, показываем все).
  const базыСписок = [...всеБазы]
    .filter(
      (б) =>
        ИЗВЕСТНЫЕ_БАЗЫ.includes(б) ||
        б.startsWith(КТЗ_ПРЕФИКС) ||
        этоСправочная(б),
    )
    .sort((a, b) => {
      // Справочные (Дипос, Брок — только сравнение) — всегда последними, после mc.ru и КТЗ
      const справПервый = этоСправочная(a);
      const справВторой = этоСправочная(b);
      if (справПервый !== справВторой) return справПервый ? 1 : -1;
      if (справПервый && справВторой) {
        return СПРАВОЧНЫЕ_ПРЕФИКСЫ.findIndex((п) => a.startsWith(п)) - СПРАВОЧНЫЕ_ПРЕФИКСЫ.findIndex((п) => b.startsWith(п));
      }
      const ктзA = a.startsWith(КТЗ_ПРЕФИКС);
      const ктзB = b.startsWith(КТЗ_ПРЕФИКС);
      // mc.ru-базы всегда идут раньше КТЗ-баз (приоритет — своим складам)
      if (ктзA !== ктзB) return ктзA ? 1 : -1;
      if (ктзA && ктзB) return a.localeCompare(b, "ru"); // КТЗ — просто по алфавиту
      const иА = приоритет.indexOf(a);
      const иБ = приоритет.indexOf(b);
      return (иА === -1 ? 999 : иА) - (иБ === -1 ? 999 : иБ);
    });

  const sheet = workbook.addWorksheet("Сводная по базам", {
    views: [{ state: "frozen", xSplit: 1, ySplit: 1 }],
  });

  const колонки = [
    { header: "Позиция", key: "позиция", width: 28 },
    ...базыСписок.map((база) => ({ header: база, key: база, width: 16 })),
  ];
  sheet.columns = колонки;

  const headerRow = sheet.getRow(1);
  headerRow.font = { name: "Arial", bold: true, color: { argb: "FFFFFFFF" } };
  headerRow.fill = {
    type: "pattern",
    pattern: "solid",
    fgColor: { argb: ЦВЕТ_ЗАГОЛОВОК },
  };
  headerRow.alignment = { vertical: "middle", horizontal: "center" };
  headerRow.height = 22;

  const индексСводки = []; // [{ названиеСтроки, ячейки: { база: {варианты: [...], тип: 'точное'|'альтернатива'} } }]

  function добавьСтроку(
    названиеСтроки,
    кандидаты,
    оценённые = [],
    position = null,
  ) {
    const данныеСтроки = { позиция: названиеСтроки };
    const ценыВСтроке = [];
    const ссылкиВСтроке = {};
    const альтернативныеБазы = new Set();
    let естьЧтоПоказать = false;
    // Дипос — только для сравнения: в ценыВСтроке (зелёная подсветка
    // "лучшая цена для заказа") и в ячейкиИндекса (/order) не попадает
    const справочныеЦены = {}; // база → { цена, точная }

    const ячейкиИндекса = {};

    for (const база of базыСписок) {
      const наЭтойБазе = кандидаты.filter((v) =>
        разберБазы(v.смц).includes(база),
      );
      const варианты = всеЦеныВГруппе(наЭтойБазе);

      if (варианты.length > 0) {
        естьЧтоПоказать = true;
        if (варианты.length === 1) {
          const v = варианты[0];
          // Наценка КТЗ за заказ < 1т (см. ktz/index.js) — уже учтена в
          // цене, но менеджер должен ВИДЕТЬ, что цена с наценкой, а не
          // сверять "на глаз" с сайтом и недоумевать, откуда разница
          данныеСтроки[база] = v._наценкаЗаМалыйЗаказПрименена
            ? `${v.цена_от_1т} (+1000₽/т, заказ <1т)`
            : v.цена_от_1т;
        } else {
          данныеСтроки[база] = `${варианты
            .map((v) =>
              v._наценкаЗаМалыйЗаказПрименена
                ? `${v.цена_от_1т}*`
                : `${v.цена_от_1т}`,
            )
            .join(
              " / ",
            )} (${варианты.length} предложения${варианты.some((v) => v._наценкаЗаМалыйЗаказПрименена) ? ", * = +1000₽/т за заказ <1т" : ""})`;
        }
        if (этоСправочная(база)) {
          справочныеЦены[база] = { цена: варианты[0].цена_от_1т, точная: true };
        } else {
          ценыВСтроке.push({ база, цена: варианты[0].цена_от_1т });
        }
        const сСсылкой = варианты.find((v) => v.cardUrl || v.sourceUrl);
        if (сСсылкой)
          ссылкиВСтроке[база] = сСсылкой.cardUrl || сСсылкой.sourceUrl;

        // Для /order: если предложение одно — однозначно, если больше
        // одного — берём самое дешёвое автоматически (менеджер видит
        // все цены в самой ячейке Excel и может при желании сначала
        // свериться, прежде чем слать команду /order)
        if (!этоСправочная(база)) {
          ячейкиИндекса[база] = { варианты, тип: "точное" };
        }
        continue;
      }

      const альтернативы = альтернативыДляБазы(оценённые, база, position);
      if (альтернативы.length === 0) continue;

      естьЧтоПоказать = true;
      альтернативныеБазы.add(база);
      данныеСтроки[база] = альтернативы
        .map((a) => `${a.цена} (${a.метка})`)
        .join(" / ");
      if (альтернативы[0].ссылка) ссылкиВСтроке[база] = альтернативы[0].ссылка;

      // Для /order — берём самый дешёвый альтернативный вариант
      // (Дипос и Брок в /order не участвуют — у них нет корзины)
      if (этоСправочная(база)) {
        справочныеЦены[база] = { цена: альтернативы[0].цена, точная: false };
      } else {
        ячейкиИндекса[база] = {
          варианты: альтернативы.map((a) => a.вариант),
          тип: "альтернатива",
        };
      }
    }

    const row = sheet.addRow(данныеСтроки);
    row.font = { name: "Arial", size: 10 };
    row.alignment = { vertical: "middle", horizontal: "center" };
    row.getCell(1).alignment = { vertical: "middle", horizontal: "left" };

    базыСписок.forEach((база, idx) => {
      const cell = row.getCell(idx + 2);
      if (typeof данныеСтроки[база] === "number") cell.numFmt = "# ##0";
      if (ссылкиВСтроке[база]) {
        cell.value = {
          text: String(данныеСтроки[база] ?? ""),
          hyperlink: ссылкиВСтроке[база],
        };
        cell.font = {
          name: "Arial",
          size: 10,
          color: { argb: "FF1155CC" },
          underline: true,
        };
      }
      if (альтернативныеБазы.has(база)) {
        cell.fill = {
          type: "pattern",
          pattern: "solid",
          fgColor: { argb: ЦВЕТ_АЛЬТЕРНАТИВА },
        };
      }
    });

    if (ценыВСтроке.length > 0) {
      const минЦена = Math.min(...ценыВСтроке.map((c) => c.цена));
      for (const { база, цена } of ценыВСтроке) {
        if (цена === минЦена) {
          const колонкаIdx = базыСписок.indexOf(база) + 2;
          row.getCell(колонкаIdx).fill = {
            type: "pattern",
            pattern: "solid",
            fgColor: { argb: ЦВЕТ_ВЫБРАН },
          };
        }
      }
    } else if (!естьЧтоПоказать) {
      row.eachCell({ includeEmpty: true }, (cell) => {
        cell.fill = {
          type: "pattern",
          pattern: "solid",
          fgColor: { argb: ЦВЕТ_НЕ_НАЙДЕНО },
        };
      });
    }

    // Голубым — если точная цена справочного поставщика (Дипос, Брок) ниже
    // лучшей цены для заказа (или заказать больше негде). Это подсказка
    // для сравнения, не выбор базы.
    const лучшаяЦенаЗаказ =
      ценыВСтроке.length > 0 ? Math.min(...ценыВСтроке.map((c) => c.цена)) : null;
    for (const [база, { цена, точная }] of Object.entries(справочныеЦены)) {
      if (!точная || !(лучшаяЦенаЗаказ == null || цена < лучшаяЦенаЗаказ)) continue;
      const колонка = базыСписок.indexOf(база) + 2;
      if (колонка >= 2) {
        row.getCell(колонка).fill = {
          type: "pattern",
          pattern: "solid",
          fgColor: { argb: ЦВЕТ_ДИПОС_ДЕШЕВЛЕ },
        };
      }
    }
    const цены_Дипос = Object.entries(справочныеЦены).find(([б]) => б.startsWith(ДИПОС_ПРЕФИКС));

    индексСводки.push({
      названиеСтроки,
      position,
      ячейки: ячейкиИндекса,
      дипосЦена: цены_Дипос ? цены_Дипос[1].цена : null,
      дипосТочная: цены_Дипос ? цены_Дипос[1].точная : false,
      справочные: справочныеЦены,
      лучшаяЦенаЗаказ,
    });
  }

  for (const { position, прошедшие, оценённые } of позицииДляСводки) {
    const спец = position?.параметры?.спецификация || {};

    if (спец.нужны_оба) {
      const гостКандидаты = прошедшие.filter(этоГост);
      const туКандидаты = прошедшие.filter(этоТУ);

      if (гостКандидаты.length > 0) {
        добавьСтроку(
          `${position.название} (ГОСТ)`,
          гостКандидаты,
          оценённые,
          position,
        );
      }
      if (туКандидаты.length > 0) {
        добавьСтроку(
          `${position.название} (ТУ)`,
          туКандидаты,
          оценённые,
          position,
        );
      }
      if (гостКандидаты.length === 0 && туКандидаты.length === 0) {
        добавьСтроку(position.название, прошедшие, оценённые, position);
      }
    } else {
      добавьСтроку(position.название, прошедшие, оценённые, position);
    }
  }

  sheet.autoFilter = {
    from: { row: 1, column: 1 },
    to: { row: 1, column: колонки.length },
  };

  return { индексСводки, базыСписок };
}

/**
 * Лист "Дипос" — подробности по прайсу Дипоса: какие именно строки прайса
 * подошли к каждой позиции (точные и близкие альтернативы с пометкой).
 * Нужен, чтобы цену в сводной можно было проверить глазами. Если по заявке
 * ничего из Дипоса не нашлось — лист не создаётся.
 */
function построитьЛистПоставщика(workbook, позицииДляСводки, { имяЛиста, подходит, получитьИнфо, заголовокСтрокиПрайса }) {
  const строки = [];
  for (const { position, оценённые } of позицииДляСводки) {
    const кандидаты = (оценённые || [])
      .filter((о) => о.вариант && подходит(о.вариант))
      .sort((a, b) => Number(b.прошёл) - Number(a.прошёл) || a.вариант.цена_от_1т - b.вариант.цена_от_1т);
    for (const { вариант, прошёл } of кандидаты) {
      строки.push({ позиция: position.название, прошёл, вариант });
    }
  }
  if (строки.length === 0) return;

  const инфо = получитьИнфо();
  const sheet = workbook.addWorksheet(имяЛиста, {
    views: [{ state: "frozen", ySplit: 1 }],
  });
  sheet.columns = [
    { header: "Позиция (запрошено)", key: "позиция", width: 30 },
    { header: "Статус", key: "статус", width: 14 },
    { header: "Отличие", key: "метка", width: 22 },
    { header: заголовокСтрокиПрайса, key: "название", width: 70 },
    { header: "Длина", key: "длина", width: 12 },
    { header: "Цена ₽/т (с НДС)", key: "цена", width: 16 },
    { header: `Строка в файле (прайс от ${инфо.датаПрайсаТекст || "?"})`, key: "номер", width: 22 },
  ];
  const шапка = sheet.getRow(1);
  шапка.font = { name: "Arial", bold: true, color: { argb: "FFFFFFFF" } };
  шапка.fill = { type: "pattern", pattern: "solid", fgColor: { argb: ЦВЕТ_ЗАГОЛОВОК } };
  шапка.alignment = { vertical: "middle", horizontal: "left", wrapText: true };
  шапка.height = 30;

  let предыдущая = null;
  for (const { позиция, прошёл, вариант } of строки) {
    const row = sheet.addRow({
      позиция,
      статус: прошёл ? "точное" : "альтернатива",
      метка: вариант._альтМетка || "",
      название: вариант.название,
      длина: вариант.длина,
      цена: вариант.цена_от_1т,
      номер: вариант._строкаПрайса,
    });
    row.font = { name: "Arial", size: 10 };
    row.alignment = { vertical: "top", wrapText: true };
    row.getCell("цена").numFmt = "# ##0";
    if (!прошёл) {
      row.eachCell({ includeEmpty: true }, (cell) => {
        cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: ЦВЕТ_АЛЬТЕРНАТИВА } };
      });
    }
    if (позиция !== предыдущая) {
      row.eachCell({ includeEmpty: true }, (cell) => {
        cell.border = { top: { style: "medium", color: { argb: "FF2C3E50" } } };
      });
      row.getCell(1).font = { name: "Arial", size: 10, bold: true };
      предыдущая = позиция;
    }
  }
  sheet.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: 7 } };
}

function построитьЛистДипос(workbook, позицииДляСводки) {
  построитьЛистПоставщика(workbook, позицииДляСводки, {
    имяЛиста: "Дипос",
    подходит: (в) => !!в._дипос && !в._брок,
    получитьИнфо: инфоОПрайсеДипоса,
    заголовокСтрокиПрайса: "Строка прайса Дипоса",
  });
}

function построитьЛистБрок(workbook, позицииДляСводки) {
  построитьЛистПоставщика(workbook, позицииДляСводки, {
    имяЛиста: "Брок",
    подходит: (в) => !!в._брок,
    получитьИнфо: инфоОПрайсеБрока,
    заголовокСтрокиПрайса: "Строка прайса Брок Инвеста (склад Октябрьский)",
  });
}

