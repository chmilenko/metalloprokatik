/**
 * Итог по позициям на основе ТОГО ЖЕ индексСводки, из которого строится
 * лист "Сводная по базам" и работает /order — поэтому подпись к файлу не
 * может разойтись с тем, что менеджер видит в таблице.
 *   точное       — хотя бы на одной базе (mc.ru или КТЗ) есть точное совпадение
 *   альтернатива — точных нет, но есть оранжевые ячейки (другая длина/ТУ/марка)
 *   нет          — в сводной нет ни одной цены
 */
function посчитайИтог(positions, индексСводки) {
  const статусПозиции = new Map();
  for (const { position, ячейки } of индексСводки) {
    const типы = Object.values(ячейки || {}).map((я) => я.тип);
    let статус = "нет";
    if (типы.includes("точное")) статус = "точное";
    else if (типы.includes("альтернатива")) статус = "альтернатива";

    const прежний = статусПозиции.get(position);
    // Позиция может занимать две строки (ГОСТ и ТУ) — берём лучший статус
    const вес = { нет: 0, альтернатива: 1, точное: 2 };
    if (!прежний || вес[статус] > вес[прежний]) статусПозиции.set(position, статус);
  }

  // Позиции, у которых нет ни точного, ни альтернативы на mc.ru/КТЗ, но есть
  // цена у справочного поставщика (Дипос, Брок) — это не "ничего нет",
  // просто заказать там нельзя
  const справочныеПоПозиции = new Map(); // position → Set(названия поставщиков с ценой)
  for (const з of индексСводки) {
    for (const база of Object.keys(з.справочные || {})) {
      const набор = справочныеПоПозиции.get(з.position) || new Set();
      набор.add(названиеПоставщика(база));
      справочныеПоПозиции.set(з.position, набор);
    }
  }

  const итог = { точное: [], альтернатива: [], нет: [], тольковДипосе: [], тольковСправочных: [] };
  for (const position of positions) {
    const статус = статусПозиции.get(position) || "нет";
    итог[статус].push(position.название);
    if (статус === "нет" && справочныеПоПозиции.has(position)) {
      итог.тольковСправочных.push({ название: position.название, поставщики: [...справочныеПоПозиции.get(position)] });
      итог.тольковДипосе.push(position.название);
    }
  }

  // Сравнение цен: у скольких позиций справочный поставщик дешевле лучшей
  // цены mc.ru/КТЗ (только точные цены поставщика)
  итог.справочные = {};
  for (const поставщик of ["Дипос", "Брок Инвест"]) {
    const поПозиции = new Map();
    for (const з of индексСводки) {
      for (const [база, { цена, точная }] of Object.entries(з.справочные || {})) {
        if (названиеПоставщика(база) !== поставщик || !точная) continue;
        const прежняя = поПозиции.get(з.position) || { справ: Infinity, лучшая: null };
        прежняя.справ = Math.min(прежняя.справ, цена);
        if (з.лучшаяЦенаЗаказ != null) {
          прежняя.лучшая = прежняя.лучшая == null ? з.лучшаяЦенаЗаказ : Math.min(прежняя.лучшая, з.лучшаяЦенаЗаказ);
        }
        поПозиции.set(з.position, прежняя);
      }
    }
    итог.справочные[поставщик] = {
      сЦеной: поПозиции.size,
      дешевле: [...поПозиции.values()].filter((v) => v.лучшая != null && v.справ < v.лучшая).length,
    };
  }
  итог.дипос = итог.справочные["Дипос"];
  return итог;
}

/**
 * Формирует и отправляет Excel-таблицу по всей заявке.
 * Вызывается прямо из обработчика обычного текстового сообщения —
 * без отдельной команды, см. bot/handlers/message.js.
 */
async function экспортироватьЗаявку(ctx, text) {
  try {
    // Один «живой» прогресс-экран вместо десятков сообщений: бот правит его
    // по ходу работы (см. utils/liveMessage.js).
    const live = await создатьЖивоеСообщение(ctx, "🔍 Анализирую заявку...");
    const positions = await parseOrder(text);

    if (positions.length === 0) {
      await live.завершить("❌ Не нашёл позиций в заявке.");
      return;
    }

    const отметки = positions.map(() => "▫️"); // ▫️ ждёт · ⏳ ищу · ✅ готово · ❌ нигде нет · ⚠️ ошибка
    let заметка = "";
    const показатьПрогресс = (заголовок) => {
      const строки = positions.map((п, k) => `${отметки[k]} ${String(п.название).slice(0, 60)}`);
      live.обновить(
        `${заголовок}\n\n${строки.join("\n")}` + (заметка ? `\n\n${заметка}` : ""),
      );
    };
    const название_источников = "mc.ru, КТЗ, Дипос, Брок";
    показатьПрогресс(`📋 Нашёл ${positions.length} поз. Ищу: ${название_источников}`);

    const строкиТаблицы = [];
    const позицииДляСводки = []; // {position, прошедшие, оценённые} — для листа "Сводная по базам"

    for (let i = 0; i < positions.length; i++) {
      const position = positions[i];
      отметки[i] = "⏳";
      заметка = "";
      показатьПрогресс(`🔍 Ищу ${i + 1}/${positions.length}`);

      // КТЗ — независимо от исхода mc.ru (см. безопасноНайдиНаКТЗ выше).
      // Результат идёт ТОЛЬКО в сводную таблицу — лист "Заявка" (детальный,
      // по-кандидатно) остаётся только для mc.ru, как и было.
      const { variants: ктзВариантыПоиска, оценённые: ктзОценённыеПоиска } =
        await безопасноНайдиНаКТЗ(position);

      // Дипос — прайс-лист без корзины, только для сравнения цен. Идёт в
      // сводную той же дорожкой, что и КТЗ (отдельная колонка "Дипос: Москва").
      const дипос = безопасноНайдиВДипосе(position);
      // Брок Инвест — тоже только прайс (склад «Октябрьский»), та же дорожка.
      const брок = безопасноНайдиВБроке(position);
      const ктзПрошедшие = [...ктзВариантыПоиска, ...дипос.variants, ...брок.variants];
      const ктзОценённые = [...ктзОценённыеПоиска, ...дипос.оценённые, ...брок.оценённые];

      let найденное;
      try {
        найденное = await findPosition(position, async (msg) => {
          // служебные сообщения поиска показываем строкой под списком, а не отдельными сообщениями
          заметка = String(msg).slice(0, 300);
          показатьПрогресс(`🔍 Ищу ${i + 1}/${positions.length}`);
        });
      } catch (err) {
        logger.error("Ошибка поиска позиции при экспорте", {
          название: position.название,
          error: err.message,
        });
        строкиТаблицы.push({
          позиция: position,
          вариант: null,
          статус: "ошибка поиска",
          причина: err.message,
        });
        отметки[i] = "⚠️";
        // КТЗ мог найти что-то, даже если mc.ru упал — не теряем это
        позицииДляСводки.push({
          position,
          прошедшие: ктзПрошедшие,
          оценённые: ктзОценённые,
        });
        continue;
      }

      const result = найденное.result;
      const кандидаты = найденное.rawRows?.length
        ? найденное.rawRows
        : result.variants || [];

      if (кандидаты.length === 0) {
        строкиТаблицы.push({
          позиция: position,
          вариант: null,
          статус: "не найдено",
          причина: "сайт не вернул ни одного результата по этому запросу",
        });
        отметки[i] = ктзПрошедшие.length > 0 ? "✅" : "❌";
        позицииДляСводки.push({
          position,
          прошедшие: ктзПрошедшие,
          оценённые: ктзОценённые,
        });
        continue;
      }

      const оценённые = оцениВсеВарианты(кандидаты, position);
      const прошедшие = оценённые.filter((r) => r.прошёл).map((r) => r.вариант);
      отметки[i] = прошедшие.length > 0 || ктзПрошедшие.length > 0 ? "✅" : "❌";
      const выбранные = выбериЛучшего(прошедшие, position);

      // Сводная получает mc.ru + КТЗ вместе. "Заявка" (детальная,
      // по-кандидатно, ниже по коду) — по-прежнему только mc.ru.
      позицииДляСводки.push({
        position,
        прошедшие: [...прошедшие, ...ктзПрошедшие],
        оценённые: [...оценённые, ...ктзОценённые],
      });

      for (const { вариант, прошёл, причина } of оценённые) {
        строкиТаблицы.push({
          позиция: position,
          вариант,
          статус: прошёл
            ? выбранные.includes(вариант)
              ? "выбран"
              : "подходит"
            : "отклонён",
          причина: причина || "",
        });
      }
    }

    заметка = "";
    показатьПрогресс("📊 Собираю Excel-таблицу…");
    const { filepath, индексСводки, базыСписок } = await построитьXlsx(
      строкиТаблицы,
      позицииДляСводки,
    );

    // В try/catch отдельно от общего — чтобы сбой записи на диск не
    // сожрал уже готовый Excel-файл: он должен уйти пользователю в любом
    // случае, даже если /order потом не сможет найти эту таблицу
    try {
      добавьТаблицу(ctx.from.id, {
        text,
        позицииДляСводки,
        индексСводки,
        базыСписок,
      });
    } catch (err) {
      logger.error(
        "Не удалось сохранить сводную таблицу на диск — /order по этой заявке работать не будет",
        {
          userId: ctx.from.id,
          error: err.message,
        },
      );
    }

    const итог = посчитайИтог(positions, индексСводки);

    // Финальный вид прогресс-экрана; сам итог (и уведомление) — новыми сообщениями ниже
    {
      const строки = positions.map((п, k) => `${отметки[k]} ${String(п.название).slice(0, 60)}`);
      await live.завершить(`✅ Поиск завершён (${positions.length} поз.)\n\n${строки.join("\n")}`);
    }

    await ctx.replyWithDocument(
      {
        source: filepath,
        filename: `заявка_${new Date().toISOString().slice(0, 10)}.xlsx`,
      },
      {
        // Telegram режет подпись к файлу на 1024 символах — поэтому здесь
        // только счётчики, а названия позиций уходят отдельным сообщением ниже
        caption:
          `📊 Таблица по заявке:\n` +
          `• Всего позиций: ${positions.length}\n` +
          `• ✅ Точное совпадение (mc.ru/КТЗ): ${итог.точное.length}\n` +
          `• 🟧 Только альтернатива: ${итог.альтернатива.length}\n` +
          `• ❌ Не найдено: ${итог.нет.length}\n\n` +
          `Лист "Заявка" — разбор по mc.ru (что подошло/отклонено и почему). ` +
          `Лист "Сводная по базам" — цены поставщиков, склады КТЗ с префиксом "КТЗ: ", колонки "Дипос: Москва" и "Брок: Октябрьский" — только для сравнения (заказать там через бота нельзя). ` +
          `🟧 — точного совпадения на базе нет, но есть близкое (другая длина/ТУ/марка).\n\n` +
          `✏️ Оформить: /order и выбор склада кнопками.`,
      },
    );

    fs.unlinkSync(filepath);

    const строкиИтога = [];
    const безКоличества = positions.filter((п) => п.количество_не_указано);
    if (безКоличества.length > 0) {
      строкиИтога.push(
        `⚠️ Не указано количество (цены показаны, но для заказа его нужно уточнить):\n` +
          безКоличества.map((п) => `• ${п.название}`).join("\n"),
      );
    }
    if (итог.альтернатива.length > 0) {
      строкиИтога.push(
        `🟧 Только альтернатива (точного нет — проверь в таблице, что именно предложено):\n` +
          итог.альтернатива.map((н) => `• ${н}`).join("\n"),
      );
    }
    if (итог.нет.length > 0) {
      строкиИтога.push(
        `❌ Не найдено ни на mc.ru, ни на КТЗ (заказать нельзя):\n` +
          итог.нет.map((н) => `• ${н}`).join("\n"),
      );
    }
    if (итог.тольковСправочных.length > 0) {
      строкиИтога.push(
        `ℹ️ Из «не найдено» есть цена у поставщиков без корзины (заказать через бота нельзя — только для сравнения):\n` +
          итог.тольковСправочных.map((н) => `• ${н.название} — ${н.поставщики.join(", ")}`).join("\n"),
      );
    }
    const прайсДипоса = инфоОПрайсеДипоса();
    if (!прайсДипоса.есть) {
      строкиИтога.push("ℹ️ Прайс Дипоса не загружен — колонки «Дипос» в таблице нет. Обновить: /dipos");
    } else {
      const сравнение =
        итог.дипос.сЦеной > 0
          ? `Дипос (только сравнение, прайс от ${прайсДипоса.датаПрайсаТекст}): цена есть у ${итог.дипос.сЦеной} из ${positions.length} позиций, ` +
            `дешевле mc.ru/КТЗ — у ${итог.дипос.дешевле} (голубые ячейки).`
          : `Дипос (прайс от ${прайсДипоса.датаПрайсаТекст}): подходящих позиций не нашлось.`;
      let предупреждение = "";
      if (прайсДипоса.устарел) {
        предупреждение =
          `⚠️ Бот не смог скачать прайс Дипоса уже больше суток (последний раз скачан ${прайсДипоса.скачанТекст || "—"}) — ` +
          `цены Дипоса могут не совпадать с сайтом. Обновить: /dipos`;
      } else if (прайсДипоса.давноНеОбновлялся) {
        предупреждение =
          `ℹ️ Бот проверил сайт Дипоса ${прайсДипоса.скачанТекст}: самый свежий прайс там от ${прайсДипоса.датаПрайсаТекст} ` +
          `(новее Дипос не выложил) — цены могут быть неактуальны.`;
      }
      строкиИтога.push(предупреждение ? `${предупреждение}\n${сравнение}` : сравнение);
    }

    const прайсБрока = инфоОПрайсеБрока();
    if (!прайсБрока.есть) {
      строкиИтога.push("ℹ️ Прайсы Брок Инвеста не загружены — колонки «Брок» в таблице нет. Обновить: /brok");
    } else {
      const сБ = итог.справочные["Брок Инвест"];
      const сравнениеБ =
        сБ.сЦеной > 0
          ? `Брок Инвест, склад Октябрьский (только сравнение, прайс от ${прайсБрока.датаПрайсаТекст}): цена есть у ${сБ.сЦеной} из ${positions.length} позиций, ` +
            `дешевле mc.ru/КТЗ — у ${сБ.дешевле} (голубые ячейки).`
          : `Брок Инвест (прайс от ${прайсБрока.датаПрайсаТекст}): подходящих позиций не нашлось.`;
      let предупреждениеБ = "";
      if (прайсБрока.устарел) {
        предупреждениеБ =
          `⚠️ Бот не смог скачать прайсы Брок Инвеста уже больше суток (последний раз ${прайсБрока.скачанТекст || "—"}) — ` +
          `цены могут не совпадать с сайтом. Обновить: /brok`;
      } else if (прайсБрока.нетКатегорий.length > 0) {
        предупреждениеБ = `ℹ️ Часть категорий Брок Инвеста не загружена (${прайсБрока.нетКатегорий.join(", ")}) — по ним цен нет. Обновить: /brok`;
      } else if (прайсБрока.давноНеОбновлялся) {
        предупреждениеБ =
          `ℹ️ Бот проверил сайт Брок Инвеста ${прайсБрока.скачанТекст}: самый свежий прайс там от ${прайсБрока.датаПрайсаТекст} — цены могут быть неактуальны.`;
      }
      строкиИтога.push(предупреждениеБ ? `${предупреждениеБ}\n${сравнениеБ}` : сравнениеБ);
    }
    if (строкиИтога.length > 0) {
      await ctx.reply(строкиИтога.join("\n\n"));
    }
  } catch (err) {
    logger.error("Ошибка экспорта заявки", {
      error: err.message,
      stack: err.stack,
    });

    const МАКС_ДЛИНА_СООБЩЕНИЯ = 3500;
    let текстОшибки = err.message || "неизвестная ошибка";
    if (текстОшибки.length > МАКС_ДЛИНА_СООБЩЕНИЯ) {
      текстОшибки =
        текстОшибки.slice(0, МАКС_ДЛИНА_СООБЩЕНИЯ) +
        `\n\n… (обрезано, полный текст в логах, длина ${err.message.length} символов)`;
    }

    try {
      await ctx.reply(`❌ Ошибка: ${текстОшибки}`);
    } catch (sendErr) {
      logger.error("Не удалось отправить сообщение об ошибке", {
        error: sendErr.message,
      });
      await ctx
        .reply("❌ Не удалось обработать заявку — подробности в логах.")
        .catch(() => {});
    }
  }
}

async function построитьXlsx(строкиТаблицы, позицииДляСводки) {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = "metalloprokatik bot";
  workbook.created = new Date();

  построитьЛистЗаявка(workbook, строкиТаблицы);
  const { индексСводки, базыСписок } = построитьЛистСводки(
    workbook,
    позицииДляСводки,
  );
  построитьЛистДипос(workbook, позицииДляСводки);
  построитьЛистБрок(workbook, позицииДляСводки);

  const outputDir = path.join(__dirname, "../../downloads");
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  const filepath = path.join(outputDir, `заявка_${Date.now()}.xlsx`);
  await workbook.xlsx.writeFile(filepath);

  return { filepath, индексСводки, базыСписок };
}

