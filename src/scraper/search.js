// Определяем можно ли искать по URL категории
function getCategoryUrl(position) {
  const название = (position.название || "").toLowerCase();
  const запрос = (position.поисковый_запрос || "").toLowerCase();
  const толщина = position.параметры?.толщина;
  const диаметр = position.параметры?.диаметр;
  const текст = `${запрос} ${название}`;
  // Листы — категория по толщине
  if (толщина) {
    for (const [ключ, urlFn] of Object.entries(CATEGORY_URLS)) {
      // ключ вида 'лист г/к' → извлекаем тип 'г/к' для этоЛистКатегории
      const тип = ключ.replace("лист ", "");
      // Проверяем и "название" (обычно = как менеджер написал в заявке),
      // и "поисковый_запрос" (может быть подменён словарём searchMap.json
      // на другую формулировку — тогда проверка по одному полю не сработала бы)
      const совпадает =
        этоЛистКатегории(название, тип) || этоЛистКатегории(запрос, тип);
      if (совпадает) return urlFn(толщина);
    }
  }

  // Арматура — категория по диаметру + классу профиля. Без распознанного
  // класса (марка не задана или не входит в известные группы) не рискуем
  // угадывать рифлёная/гладкая — уходим в глобальный поиск.
  const этоАрматура =
    название.includes("арматура") || запрос.includes("арматура");
  if (этоАрматура && диаметр) {
    const класс = нормализуйМарку(position.параметры?.марка);
    const urlFn = ARMATURE_CATEGORY_URLS[класс];
    if (urlFn) return urlFn(диаметр);
  }

  // Круг г/к — категория по диаметру. Основной источник — параметр
  // "диаметр" из парсера; если вдруг не заполнен (модель иногда пропускает
  // это поле) — подстраховываемся и достаём число прямо из текста, как
  // для швеллера/квадрата.
  const этоКруг =
    (естьЦелоеСлово(название, "круг") || естьЦелоеСлово(запрос, "круг")) &&
    !этоАрматура; // на всякий случай не путаем с "кругляк" внутри других названий
  if (этоКруг) {
    const диаметрКруга =
      диаметр ||
      extractShapeNumber(
        естьЦелоеСлово(запрос, "круг") ? запрос : название,
        "круг",
      );
    if (диаметрКруга) return КРУГ_CATEGORY_URL(диаметрКруга);
  }

  // ПВЛ (просечно-вытяжной лист) — категория по номеру модели. Номер —
  // структурный параметры.номер (заполняется парсером напрямую), с
  // текстовым фолбэком на случай, если модель его пропустила.
  const этоПВЛ =
    естьЦелоеСлово(название, "пвл") || естьЦелоеСлово(запрос, "пвл") ||
    название.includes("просечно") || запрос.includes("просечно");
  if (этоПВЛ) {
    const номерПВЛ =
      position.параметры?.номер ||
      extractShapeNumber(
        естьЦелоеСлово(запрос, "пвл") ? запрос : название,
        "пвл",
      );
    if (номерПВЛ) return ПВЛ_CATEGORY_URL(номерПВЛ);
  }

  // Круглая труба — распознаём по слову "труб" + наличию параметры.диаметр
  // ИЛИ параметры.ду (профильная труба вместо этого использует
  // параметры.ширина — так их теперь чётко разводит parser.js).
  // Приоритет типа: ВГП > г/д (бесшовная горячедеформ.) > х/д (бесшовная
  // холоднодеформ.) > эл/св круглая — дефолт, если тип явно не указан
  // (см. разбор менеджера от 13.08: "не указано ничего — ищем эл/св").
  const этоТруба = название.includes("труб") || запрос.includes("труб");
  const ду = position.параметры?.ду;

  if (этоТруба && ду) {
    return ТРУБА_ВГП_CATEGORY_URL(ду);
  }

  if (этоТруба && диаметр) {
    const этоГД =
      название.includes("г/д") || запрос.includes("г/д") ||
      название.includes("горячедеформированн") || запрос.includes("горячедеформированн");
    const этоХД =
      название.includes("х/д") || запрос.includes("х/д") ||
      название.includes("холоднодеформированн") || запрос.includes("холоднодеформированн");
    const этоНержавейка =
      название.includes("нержав") || запрос.includes("нержав") ||
      название.includes("aisi") || запрос.includes("aisi");

    if (этоНержавейка) {
      // Круглая нержавеющая — своя развилка: бесшовная (явно указано)
      // или AISI электросварная (дефолт), г/д и х/д сюда не относятся —
      // это деление специфично для обычной (не нержавеющей) стали.
      const этоБесшовная =
        название.includes("бесшовн") || запрос.includes("бесшовн");
      return этоБесшовная
        ? ТРУБА_НЕРЖ_БЕСШОВНАЯ_CATEGORY_URL(диаметр)
        : ТРУБА_НЕРЖ_КРУГ_CATEGORY_URL(диаметр);
    }

    if (этоГД) return ТРУБА_ГД_CATEGORY_URL(диаметр);
    if (этоХД) return ТРУБА_ХД_CATEGORY_URL(диаметр);

    // Ни г/д, ни х/д явно не указано — дефолт: электросварная круглая.
    return ТРУБА_ЭЛСВ_КРУГ_CATEGORY_URL(диаметр);
  }

  // Труба профильная (квадратная/прямоугольная) — узнаём по тому, что
  // заполнена ширина, а не диаметр/ду (это и есть признак трёхчисленного
  // формата "ширина×высота×стенка" vs двухчислового круглого). Квадратная
  // vs прямоугольная — по тому, заполнено ли параметры.длина_листа
  // (вторая, отличающаяся сторона прямоугольной трубы).
  if (этоТруба && position.параметры?.ширина != null) {
    const сторонаА = position.параметры.ширина;
    const этоПрямоугольная =
      position.параметры?.длина_листа != null &&
      position.параметры.длина_листа !== сторонаА;
    const этоНержавейкаПрофиль =
      название.includes("нержав") || запрос.includes("нержав") ||
      название.includes("aisi") || запрос.includes("aisi");

    if (этоНержавейкаПрофиль) {
      return этоПрямоугольная
        ? ТРУБА_НЕРЖ_ПРЯМОУГОЛЬНАЯ_CATEGORY_URL(сторонаА)
        : ТРУБА_НЕРЖ_КВАДРАТНАЯ_CATEGORY_URL(сторонаА);
    }

    if (этоПрямоугольная) {
      return ТРУБА_ЭЛСВ_ПРЯМОУГОЛЬНАЯ_CATEGORY_URL(сторонаА);
    }
    return ТРУБА_ЭЛСВ_КВАДРАТНАЯ_CATEGORY_URL(сторонаА);
  }

  // Балка (двутавр) — категория по номеру профиля + классу стали.
  // Если марка не указана явно — по умолчанию считаем обычную сталь
  // (Ст3/С255/С245), если только в тексте нет явного намёка на
  // низколегированную (09Г2С/С345/С355/"низколегир").
  const формаБалкиЗапроса = определиФормуБалки(запрос);
  const формаБалкиНазвания = определиФормуБалки(название);
  if (формаБалкиЗапроса || формаБалкиНазвания) {
    // Приоритет: структурный параметры.номер (не зависит от текста вообще,
    // заполняется парсером напрямую) → название → запрос. Текстовые поля
    // могут быть искажены словарём searchMap.json ОБА СРАЗУ (например
    // "Балка низколегированная Б2" вместо "Балка 18 Б2" — теряется номер
    // и в названии, и в запросе), поэтому структурный параметр надёжнее.
    let номерБалки = position.параметры?.номер || null;

    if (!номерБалки) {
      const источникБалки = формаБалкиНазвания ? название : запрос;
      const ключевоеСлово = естьЦелоеСлово(источникБалки, "балка")
        ? "балка"
        : "двутавр";
      номерБалки = extractShapeNumber(источникБалки, ключевоеСлово);
    }

    if (номерБалки) {
      let классБалки = нормализуйМарку(position.параметры?.марка);
      if (классБалки !== "3" && классБалки !== "nl3") {
        // Марка не указана или не распознана — определяем по ключевым
        // словам в тексте, по умолчанию считаем обычную сталь
        const весьТекст = `${запрос} ${название}`;
        классБалки = /низколегир|09г2с|с ?345|с ?355/i.test(весьТекст)
          ? "nl3"
          : "3";
      }

      const urlFn = BALKA_CATEGORY_URLS[классБалки];
      if (urlFn) return urlFn(номерБалки);
    }
  }

  // Швеллер гнутый — проверяем ДО общего цикла ниже, иначе слово
  // "швеллер" там перехватится первым и уведёт в категорию горячекатаного
  const этоШвеллерГнутый =
    (естьЦелоеСлово(название, "швеллер") || естьЦелоеСлово(запрос, "швеллер")) &&
    (название.includes("гнут") || запрос.includes("гнут"));
  if (этоШвеллерГнутый) {
    const размерГнутого =
      position.параметры?.номер ||
      extractShapeNumber(
        естьЦелоеСлово(запрос, "швеллер") ? запрос : название,
        "швеллер",
      );
    if (размерГнутого) return ШВЕЛЛЕР_ГНУТЫЙ_CATEGORY_URL(размерГнутого);
  }

  // Швеллер низколегированный — отдельная "чистая" категория, по
  // аналогии с уголком равнополочным низколегированным. Проверяем ДО
  // общего цикла по той же причине, что и гнутый выше.
  const этоШвеллерНизколег =
    (естьЦелоеСлово(название, "швеллер") || естьЦелоеСлово(запрос, "швеллер")) &&
    (название.includes("низколегир") || запрос.includes("низколегир"));
  if (этоШвеллерНизколег) {
    const номерШвеллера =
      position.параметры?.номер ||
      extractShapeNumber(
        естьЦелоеСлово(запрос, "швеллер") ? запрос : название,
        "швеллер",
      );
    if (номерШвеллера) return ШВЕЛЛЕР_НИЗКОЛЕГИР_CATEGORY_URL(номерШвеллера);
  }

  // Катанка — по диаметру.
  const этоКатанка =
    естьЦелоеСлово(название, "катанка") || естьЦелоеСлово(запрос, "катанка");
  if (этоКатанка) {
    const диаметрКатанки =
      position.параметры?.диаметр ||
      extractShapeNumber(
        естьЦелоеСлово(запрос, "катанка") ? запрос : название,
        "катанка",
      );
    if (диаметрКатанки) return КАТАНКА_CATEGORY_URL(диаметрКатанки);
  }

  // Уголок — четыре подкатегории. Проверяем ДО общего цикла ниже по тем
  // же причинам, что и гнутый швеллер выше.
  const этоУголок =
    естьЦелоеСлово(название, "уголок") || естьЦелоеСлово(запрос, "уголок");
  if (этоУголок) {
    const текстУголка = `${запрос} ${название}`;
    const сторонаУголка =
      position.параметры?.номер ||
      extractShapeNumber(
        естьЦелоеСлово(запрос, "уголок") ? запрос : название,
        "уголок",
      );

    if (сторонаУголка) {
      const этоНержавеющий =
        текстУголка.includes("нержав") || текстУголка.includes("aisi");
      const этоНизколег = текстУголка.includes("низколегир");
      // Неравнополочный — узнаём по тому, что заполнена ширина (меньшая
      // полка) — она заполняется ТОЛЬКО когда в заявке три числа, а не два.
      const этоНеравнополочный = position.параметры?.ширина != null;

      if (этоНержавеющий) {
        return УГОЛОК_НЕРЖАВЕЮЩИЙ_CATEGORY_URL(сторонаУголка);
      }
      if (этоНеравнополочный) {
        return УГОЛОК_НЕРАВНОПОЛОЧНЫЙ_CATEGORY_URL(сторонаУголка);
      }
      if (этоНизколег) {
        return УГОЛОК_РАВНОПОЛОЧНЫЙ_НИЗКОЛЕГИР_CATEGORY_URL(сторонаУголка);
      }
      return УГОЛОК_РАВНОПОЛОЧНЫЙ_CATEGORY_URL(сторонаУголка);
    }
  }

  // Сортовой прокат — категория по номеру профиля. Приоритет: структурный
  // параметры.номер (не зависит от текста) → название (человекочитаемое,
  // не подменяется словарём searchMap.json) → поисковый_запрос как
  // последний запасной вариант. Раньше запрос был приоритетнее названия —
  // если словарь подменял запрос на устаревшую формулировку (как было с
  // ПВЛ: "ПВЛ 406..." → словарная "...ПВЛ-410" с другим номером), номер
  // профиля извлекался из НЕПРАВИЛЬНОГО числа. Та же защита, что уже была
  // у балки — теперь применяется ко всем формам сразу.
  for (const [ключ, urlFn] of Object.entries(SHAPE_CATEGORY_URLS)) {
    const источник = естьЦелоеСлово(название, ключ)
      ? название
      : естьЦелоеСлово(запрос, ключ)
        ? запрос
        : null;
    if (!источник) continue;

    // Для полосы используем ширину, для остальных - номер
    let параметр;
    if (ключ === 'полоса') {
      параметр = position.параметры?.ширина || extractShapeNumber(источник, ключ);
    } else {
      параметр = position.параметры?.номер || extractShapeNumber(источник, ключ);
    }

    if (параметр) return urlFn(параметр);
  }
  return null;
}

async function searchPosition(query, position = {}) {
  const page = await getPage();

  // Проверяем можно ли искать по URL категории
  const categoryUrl = getCategoryUrl(position);

  if (categoryUrl) {
    logger.info("Ищем по URL категории", { url: categoryUrl });
    const categoryResult = await searchByUrl(categoryUrl, position, page);

    if (categoryResult.found) {
      return categoryResult;
    }

    // Fallback: по URL категории ничего не нашли (например, толщины
    // нет в этой категории, страница пустая и т.п.) — пробуем глобальный поиск
    logger.warn("По URL категории не найдено — пробуем глобальный поиск", {
      query,
      url: categoryUrl,
    });
    const globalResult = await searchByGlobal(query, position, page);

    // ВАЖНО: если глобальный поиск ТОЖЕ не нашёл (или нашёл меньше) —
    // не теряем rawRows от категории. Категория обычно даёт куда более
    // богатые и релевантные сырые данные (все товары этого размера на
    // одной странице), чем текстовый поиск с конкретной, возможно неверной,
    // формулировкой — это нужно вызывающему коду (findPosition), чтобы
    // корректно определить, есть ли смысл продолжать перебор (см.
    // доступныеСтенкиПриТомЖеРазмере в scraper/index.js).
    if (!globalResult.found) {
      const объединённыеRawRows = [
        ...(categoryResult.rawRows || []),
        ...(globalResult.rawRows || []),
      ];
      return { ...globalResult, rawRows: объединённыеRawRows };
    }

    return globalResult;
  }

  // Иначе — глобальный поиск
  logger.info("Ищем позицию", { query });
  return await searchByGlobal(query, position, page);
}

// Скрапит строки текущей открытой страницы таблицы результатов
async function scrapeTableRows(page) {
  return await page.evaluate(() => {
    function parsePrice(text) {
      if (!text) return null;
      const match = text.match(/[\d\s]+/);
      if (!match) return null;
      return parseInt(match[0].replace(/\s/g, ""), 10);
    }

    const table = document.querySelector("table");
    if (!table) return [];

    const rows = Array.from(table.querySelectorAll("tbody tr"));

    // По умолчанию цена "за 1т" — колонка с индексом 8 (проверено на
    // десятках категорий весь этот месяц, там пороги "от 1 до 5т"/"от 5
    // до 10т"). НО у нержавеющих труб раскладка другая, и их целых ТРИ
    // разных варианта:
    //   - у круглой нержавеющей ЭСВ малого диаметра есть колонка "руб/шт"
    //     — тогда "Цена за 1 т" оказывается на индексе 6
    //   - у квадратной/прямоугольной нержавеющей ЭСВ колонки "руб/шт" НЕТ
    //     вообще, но и стандартных весовых порогов тоже нет (только
    //     "Цена за 1 т" + "Цена, руб от Xм до Yм") — тогда индекс 5
    //   - у бесшовной нержавеющей "цены за 1 т" НЕТ ВООБЩЕ никакой —
    //     только "руб/м" (за погонный метр) и весовой диапазон
    //     "от 0,1 до 1т" — используем этот диапазон как ближайший
    //     разумный аналог цены за тонну, индекс 6 (тот же, что и у
    //     круглой — совпадение по номеру, но по другой причине)
    // ВАЖНО: заголовки этих колонок живут НЕ в самой таблице (не в
    // <thead>), а в отдельном блоке фильтров <ul class="catalogItemsFilters">
    // над таблицей — поэтому ищем признаки по всей странице, а не внутри table.
    let индексЦеныЗаТонну = 8;
    // ВАЖНО: ищем признаки СТРОГО внутри блока заголовков-фильтров
    // (.catalogItemsFilters — подтверждено по реальному HTML), а НЕ по
    // всей странице (document.body.innerText). Раньше поиск по всей
    // странице иногда ловил не относящийся к таблице текст (например
    // дисклеймеры/подписи в других местах страницы) и ложно определял
    // нестандартную раскладку там, где её на самом деле нет — из-за
    // этого цены у обычных категорий (швеллер, полоса, уголок
    // нержавеющий) резко и неверно занижались.
    const блокЗаголовков = document.querySelector(".catalogItemsFilters");
    const текстСтраницы = блокЗаголовков
      ? блокЗаголовков.innerText || ""
      : "";
    const естьКолонкаШт = /руб\s*\/\s*шт/i.test(текстСтраницы);
    const естьЗа1Т = /за\s*1\s*т/i.test(текстСтраницы);
    const естьСтандартныеПороги = /от\s*1\s*до\s*5\s*т/i.test(текстСтраницы);
    const естьРубЗаМетр = /руб\s*\/\s*м(?![а-яё])/i.test(текстСтраницы);

    if (естьКолонкаШт) {
      индексЦеныЗаТонну = 6;
    } else if (естьЗа1Т && !естьСтандартныеПороги) {
      индексЦеныЗаТонну = 5;
    } else if (естьРубЗаМетр && !естьЗа1Т) {
      индексЦеныЗаТонну = 6;
    }
    const этоНестандартнаяРаскладка =
      естьКолонкаШт ||
      (естьЗа1Т && !естьСтандартныеПороги) ||
      (естьРубЗаМетр && !естьЗа1Т);

    return rows
      .map((row) => {
        const cells = row.querySelectorAll("td");
        // Цена "за кг" вместо "за т" — встречается у алюминия и, возможно,
        // у другой мелкой номенклатуры. Сканируем всю строку целиком (а не
        // конкретную ячейку), т.к. точная позиция этой подписи в разметке
        // не гарантирована. Если это "за кг" — цена_от_1т на самом деле
        // цена за килограмм и НЕЛЬЗЯ напрямую сравнивать с ценами за тонну.
        const заКг = /за\s*кг|руб\s*\/\s*кг|\/\s*кг\b/i.test(
          row.innerText || "",
        );

        // Цена "за м" (за погонный метр) вместо "за т" — встречается у
        // нержавеющих профильных труб. ВАЖНО: это проверяется НА КАЖДОЙ
        // СТРОКЕ отдельно (не по раскладке всей страницы), потому что на
        // странице глобального поиска вперемешку могут быть строки с
        // РАЗНЫМИ единицами измерения цены (например бесшовная нержавейка
        // "за т" рядом с профильной нержавейкой "за м") — единый индекс
        // колонки для всей страницы тут не спасает, а построчная проверка
        // (как и заКг выше) отсекает верно вне зависимости от раскладки.
        const заМетр = /за\s*м(?![а-яё])|руб\s*\/\s*м(?![а-яё])/i.test(
          row.innerText || "",
        );

        return {
          название: cells[0]?.innerText?.trim(),
          размер: cells[1]?.innerText?.trim(),
          марка: cells[2]?.innerText?.trim(),
          длина: cells[3]?.innerText?.trim(),
          смц: cells[4]?.innerText?.trim(),
          остаток: этоНестандартнаяРаскладка ? null : cells[5]?.innerText?.trim(),
          цена_от_1т: parsePrice(cells[индексЦеныЗаТонну]?.innerText),
          цена_от_5т: parsePrice(cells[9]?.innerText),
          цена_от_10т: parsePrice(cells[10]?.innerText),
          заКг,
          заМетр,
        };
      })
      .filter((row) => row.название && row.цена_от_1т);
  });
}

// Читает ссылки пагинации из блока .catalogPaginator (структура подтверждена
// на реальной странице mc.ru: <li><a href="/.../PageN/2">2</a></li> и т.п.,
// текущая страница — <a class="selected"> без href).
// Возвращает абсолютные URL.
async function getPaginationLinks(page) {
  const hrefs = await page.evaluate(() => {
    const links = Array.from(
      document.querySelectorAll(".catalogPaginator ul li a[href]"),
    );
    return links.map((a) => a.getAttribute("href")).filter(Boolean);
  });

  return Array.from(
    new Set(hrefs.map((href) => new URL(href, "https://mc.ru").toString())),
  );
}

async function searchByUrl(url, position, page) {
  const MAX_PAGES = 10;
  let allRows = [];
  const visited = new Set([url]);
  const queue = [url];
  let i = 0;

  while (i < queue.length && i < MAX_PAGES) {
    const currentUrl = queue[i];

    await page.goto(currentUrl);
    await page.waitForLoadState("domcontentloaded");
    await delay(1500);

    const tableExists = await page.$("table tbody tr").catch(() => null);

    if (!tableExists) {
      if (i === 0) {
        logger.warn("Таблица не найдена по URL", { url });
        return { found: false, query: url };
      }
      i++;
      continue;
    }

    const rowsRaw = await scrapeTableRows(page);
    // Прикрепляем sourceUrl КО ВСЕМ сырым строкам сразу, а не только к
    // прошедшим фильтр — нужно для экспорта в Excel, где показываем
    // ссылку на карточку/страницу для любого кандидата, включая отклонённых.
    const rows = rowsRaw.map((r) => ({ ...r, sourceUrl: currentUrl }));
    allRows.push(...rows);

    const filtered = filterVariants(rows, position);

    // Обогащаем базами из карточек — ТОЛЬКО прошедших фильтр кандидатов,
    // а не все сырые строки со страницы. Раньше цикл шёл по rows (все
    // строки без разбора, включая нержавейку/ТУ/чужую марку — 20-50+ на
    // странице), каждая итерация открывает новую вкладку и ждёт загрузку
    // карточки — это было основной причиной медленной работы. После
    // фильтра обычно остаётся 1-5 кандидатов, значит и вкладок открывается
    // в разы меньше.
    for (const variant of filtered) {
      // Запоминаем СМЦ ДО обогащения — этим же циклом оно будет
      // перезаписано ниже, а нам нужно исходное значение со страницы
      // категории для точного поиска нужной строки среди дублей.
      const исходныйСмц = variant.смц

      try {
        const rowsWithVariant = await page.$$('tr');
        let targetRow = null;
        for (const row of rowsWithVariant) {
          const nameCell = await row.$('td.TovName');
          if (!nameCell) continue;

          const text = await nameCell.textContent();
          if (!text || text.trim() !== variant.название) continue;

          // ВАЖНО: несколько строк на странице категории могут делить
          // ОДИНАКОВОЕ название (разные комбинации баз/партий одного и
          // того же товара — например Лист х/к 1.2мм с разной ценой на
          // разных СМЦ). Без сверки по СМЦ цикл каждый раз находил бы
          // ПЕРВУЮ строку с таким названием — и все варианты получали
          // бы одинаковый (неверный) результат обогащения.
          const смцCell = (await row.$('td._fact')) || (await row.$('td:nth-child(5)'));
          const смцТекст = смцCell ? (await смцCell.innerText()).trim() : '';
          if (исходныйСмц && смцТекст && смцТекст !== исходныйСмц) continue;

          targetRow = row;
          break;
        }

        if (!targetRow) continue;

        const titleLink = await targetRow.$('td.TovName a');
        if (!titleLink) continue;

        const [newPage] = await Promise.all([
          page.context().waitForEvent('page'),
          titleLink.click({ button: 'middle' })
        ]);

        await newPage.waitForLoadState('domcontentloaded');
        await delay(1500);

        // Раз уж мы всё равно открываем карточку товара для сбора баз —
        // заодно запоминаем её реальный URL. Раньше в variant.sourceUrl
        // оставалась только ссылка на страницу КАТЕГОРИИ с фильтром (там
        // может быть несколько строк), а не на конкретный товар.
        variant.cardUrl = newPage.url();

        let allBases = [];

        const baseRows = await newPage.$$('table#tab_main1 tbody tr');
        if (baseRows.length > 0) {
          for (const row of baseRows) {
            const baseName = await row.getAttribute('data-base');
            if (baseName) {
              allBases.push(baseName);
            }
          }
        }

        if (allBases.length === 0) {
          const baseItems = await newPage.$$('ul.packs li.ipacks');
          for (const item of baseItems) {
            const text = await item.textContent();
            if (text) allBases.push(text.trim());
          }
        }

        if (allBases.length === 0) {
          const baseElements = await newPage.$$('.base-item, .warehouse-item, .stock-item');
          for (const el of baseElements) {
            const text = await el.textContent();
            if (text) {
              const cleanBase = text.trim();
              if (cleanBase && !allBases.includes(cleanBase)) {
                allBases.push(cleanBase);
              }
            }
          }
        }

        if (allBases.length > 0) {
          allBases = [...new Set(allBases)]; // убираем дубли — карточка товара
          // иногда даёт по несколько строк на одну базу (разные ценовые пороги)
          variant.смц = allBases.join(', ');
          variant._allBases = allBases;
          logger.info("Обогащён базами из карточки", {
            название: variant.название,
            базы: allBases
          });
        }

        await newPage.close();
      } catch (e) {
        logger.warn("Не удалось обогатить базами", {
          название: variant.название,
          error: e.message
        });
      }
    }


    logger.info("Страница обработана", {
      url: currentUrl,
      page: i + 1,
      count: rows.length,
      filtered: filtered.length,
      варианты: filtered.map(краткоДляЛога),
      ...(filtered.length === 0 && rows.length > 0
        ? { сэмплДоФильтрации: rows.slice(0, 5).map(краткоДляЛога) }
        : {}),
    });

    if (filtered.length > 0) {
      const withSourceUrl = filtered.map((v) => ({
        ...v,
        sourceUrl: currentUrl,
      }));
      return {
        found: true,
        query: url,
        variants: withSourceUrl,
        rawRows: rows,
      };
    }

    const paginationLinks = await getPaginationLinks(page);
    for (const link of paginationLinks) {
      if (!visited.has(link)) {
        visited.add(link);
        queue.push(link);
      }
    }

    i++;
  }

  const filteredAll = filterVariants(allRows, position);
  // sourceUrl уже проставлен на каждой строке (конкретная страница
  // пагинации, где она была найдена) — здесь его больше не перезаписываем
  const filteredAllWithSourceUrl = filteredAll;

  logger.info("После перебора всех страниц", {
    url,
    totalPages: queue.length,
    totalRows: allRows.length,
    filtered: filteredAll.length,
  });

  return {
    found: filteredAllWithSourceUrl.length > 0,
    query: url,
    variants: filteredAllWithSourceUrl,
    rawRows: allRows,
  };
}


