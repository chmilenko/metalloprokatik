/**
 * metalcalc-integration.js
 *
 * Переходник между позицией заявки (как её отдаёт agent/parser.js) и
 * MetalCalc (utils/metalcalc.js). Определяет тип проката и собирает
 * строку размера, которую понимает calc(), затем считает вес по
 * заданному количеству (т/м/шт).
 *
 * ВАЖНО про уверенность в разных категориях — не все размечены
 * одинаково надёжно:
 *   - Труба (все три вида), арматура, круг, полоса, уголок, швеллер,
 *     балка/двутавр — размер строится из полей, которые парсер честно
 *     заполняет под эти конкретные формы (диаметр/ду/стенка/ширина/
 *     номер), уверенность высокая.
 *   - Квадрат/шестигранник — парсер, насколько я вижу, не заводит под
 *     них отдельных полей (нет одиночных заявок на эти формы в тех
 *     логах, что мы разбирали) — беру ширину как запасной вариант,
 *     но это ПРЕДПОЛОЖЕНИЕ, не проверено на реальных данных. Если
 *     реальная заявка на квадрат/шестигранник даст неверный размер —
 *     сюда и смотреть в первую очередь.
 *   - ВГП — беру параметры.ду как первое число размера (у КТЗ и в
 *     базе калькулятора совпадает одна и та же конвенция — видели на
 *     реальных данных, что оба источника используют "15" одинаково
 *     для ДУ15, а не настоящий наружный диаметр), но отдельно это
 *     не сверял через независимый источник — стоит перепроверить на
 *     реальной заявке, если результат покажется подозрительным.
 */

const path = require("path");
const { MetalCalc } = require("./metalcalc");

let mc = null;
function получиКалькулятор() {
  if (!mc) mc = new MetalCalc();
  return mc;
}

// Проверка вхождения слова целиком — \b не работает с кириллицей в JS
// regex (уже дважды наступали на эти грабли в этом проекте, держим
// проверенное решение под рукой)
function естьЦелоеСлово(текст, слово) {
  const idx = текст.indexOf(слово);
  if (idx === -1) return false;
  const before = текст[idx - 1];
  const after = текст[idx + слово.length];
  const этоБуква = (ch) => !!ch && /[a-zа-яё]/i.test(ch);
  return !этоБуква(before) && !этоБуква(after);
}

// Три числа через х/x/* («50х40х3», «1250х2500х0,8»). Запятая — десятичная.
function триЧислаИзТекста(текст) {
  const m = String(текст).match(
    /(\d+(?:[.,]\d+)?)\s*[xх*×]\s*(\d+(?:[.,]\d+)?)\s*[xх*×]\s*(\d+(?:[.,]\d+)?)/i
  );
  if (!m) return null;
  return [m[1], m[2], m[3]].map((x) => parseFloat(x.replace(",", ".")));
}

/**
 * Определяет тип для MetalCalc и строит строку size по параметрам
 * позиции. Возвращает { type, size } или null, если не смогли
 * уверенно определить (лучше промолчать, чем посчитать неверно).
 */
function определиТипИРазмер(position) {
  const текст = `${position.поисковый_запрос || ""} ${position.название || ""}`.toLowerCase();
  const п = position.параметры || {};

  // ВГП — проверяем раньше обычной трубы, иначе "труба вгп" попадёт
  // в ветку pipe_es по слову "труба"
  if (естьЦелоеСлово(текст, "вгп")) {
    if (п.ду != null && п.стенка != null) {
      return { type: "pipe_vgp", size: `${п.ду}x${п.стенка}`, _ду: Number(п.ду), _стенка: Number(п.стенка) };
    }
    return null;
  }

  // Профильная/квадратная/прямоугольная труба — раньше обычной трубы
  // (там тоже есть слово "труба")
  if (
    (естьЦелоеСлово(текст, "труба") || естьЦелоеСлово(текст, "трубы")) &&
    п.ширина != null &&
    п.стенка != null
  ) {
    const втораяСторона = п.длина_листа ?? п.ширина; // квадратная — вторая сторона не задана явно, значит равна первой
    return { type: "pipe_prof", size: `${п.ширина}x${втораяСторона}x${п.стенка}` };
  }

  // Обычная круглая труба (электросварная)
  if (
    (естьЦелоеСлово(текст, "труба") || естьЦелоеСлово(текст, "трубы")) &&
    п.диаметр != null &&
    п.стенка != null
  ) {
    return { type: "pipe_es", size: `${п.диаметр}x${п.стенка}` };
  }

  // Арматура — раньше круга, оба используют диаметр
  if (естьЦелоеСлово(текст, "арматура") && п.диаметр != null) {
    return { type: "armature", size: String(п.диаметр) };
  }

  // Круг (в т.ч. калиброванный — вес от марки/калибровки не зависит,
  // это тот же диаметр)
  if (естьЦелоеСлово(текст, "круг") && п.диаметр != null) {
    return { type: "round", size: String(п.диаметр) };
  }

  // Квадрат — НЕ ПРОВЕРЕНО на реальных данных, см. предупреждение в шапке файла
  if (естьЦелоеСлово(текст, "квадрат") && (п.диаметр != null || п.ширина != null || п.номер != null)) {
    return { type: "square", size: String(п.диаметр ?? п.ширина ?? п.номер) };
  }

  // Шестигранник — НЕ ПРОВЕРЕНО на реальных данных, см. предупреждение в шапке файла
  if (естьЦелоеСлово(текст, "шестигранник") && (п.диаметр != null || п.ширина != null || п.номер != null)) {
    return { type: "hexagon", size: String(п.диаметр ?? п.ширина ?? п.номер) };
  }

  // Уголок — номер это первая (равная у равнополочного) сторона,
  // ширина (если задана явно) — вторая сторона у неравнополочного
  if (естьЦелоеСлово(текст, "уголок") && п.номер != null && п.стенка != null) {
    const втораяСторона = п.ширина ?? п.номер;
    return { type: "angle", size: `${п.номер}x${втораяСторона}x${п.стенка}` };
  }

  // Швеллер — просто номер (не гнутый — у гнутого своя логика размера,
  // швеллер гнутый в базе калькулятора отдельно не представлен)
  if (естьЦелоеСлово(текст, "швеллер") && !естьЦелоеСлово(текст, "гнутый") && п.номер != null) {
    return { type: "channel", size: String(п.номер) };
  }
  // Швеллер гнутый по размерам «высота×полка×стенка» (50х40х3) — номера
  // нет, в базе по ГОСТ его нет. Берём три числа из названия; вес считает
  // весМетраГеометрией (приблизительно, без радиусов — см. там).
  if (естьЦелоеСлово(текст, "швеллер") && п.номер == null) {
    const числа = триЧислаИзТекста(текст);
    if (числа) return { type: "channel", size: числа.join("x") };
  }

  // Балка / двутавр
  if (
    (естьЦелоеСлово(текст, "балка") || естьЦелоеСлово(текст, "двутавр")) &&
    п.номер != null
  ) {
    return { type: "beam", size: String(п.номер) };
  }

  // Полоса
  if (естьЦелоеСлово(текст, "полоса") && п.ширина != null && п.толщина != null) {
    return { type: "strip", size: `${п.ширина}x${п.толщина}` };
  }

  // Лист — калькулятор для листа считает вес ЦЕЛОГО листа заданного
  // размера (толщина×ширина×длина), а не вес метра — другая природа
  // расчёта, чем у остальных форм. Даём только если знаем все три
  // размера, иначе бессмысленно (просто толщины недостаточно для
  // расчёта веса листа целиком в этой базе).
  if (естьЦелоеСлово(текст, "лист") && п.толщина != null && п.ширина != null && п.длина_листа != null) {
    return { type: "sheet", size: `${п.толщина}x${п.ширина}x${п.длина_листа}` };
  }
  // Парсер не заполнил поля листа — берём три числа из названия
  // («1250х2500х0,8»): толщина — наименьшее, длина — наибольшее.
  if (естьЦелоеСлово(текст, "лист")) {
    const числа = триЧислаИзТекста(текст);
    if (числа) {
      const [т, ш, д] = [...числа].sort((a, b) => a - b);
      return { type: "sheet", size: `${т}x${ш}x${д}` };
    }
  }

  return null; // не смогли уверенно определить — лучше промолчать
}

// Длина хлыста по умолчанию, когда в заявке явно не указана (мм) —
// самая частая длина, что мы видели во ВСЕХ реальных данных (и mc.ru,
// и КТЗ). Используется ТОЛЬКО как запасной вариант — если в заявке
// длина указана явно (параметры.длина), всегда берём её, а не это.
const ДЛИНА_ХЛЫСТА_ПО_УМОЛЧАНИЮ_ММ = 6000;

// Наружные диаметры труб ВГП по условному проходу (ГОСТ 3262), мм
const НАРУЖНЫЙ_ДИАМЕТР_ВГП = {
  6: 10.2, 8: 13.5, 10: 17.0, 15: 21.3, 20: 26.8, 25: 33.5, 32: 42.3,
  40: 48.0, 50: 60.0, 65: 75.5, 80: 88.5, 90: 101.3, 100: 114.0, 125: 140.0, 150: 165.0,
};

/** Результат в формате calc() по известному весу метра (кг/м) и единице заявки. */
function посчитайПоВесуМетра(position, кгМ) {
  const кол = Number(position.количество);
  let длинаМ, штуки = null, длинаШтуки = null;
  if (position.единица === "м") длинаМ = кол;
  else if (position.единица === "шт") {
    штуки = кол;
    длинаШтуки = (position.параметры?.длина != null ? position.параметры.длина : ДЛИНА_ХЛЫСТА_ПО_УМОЛЧАНИЮ_ММ) / 1000;
    длинаМ = штуки * длинаШтуки;
  } else if (position.единица === "т") длинаМ = (кол * 1000) / кгМ;
  else if (position.единица === "кг") длинаМ = кол / кгМ;
  else return null;
  const кг = длинаМ * кгМ;
  return {
    total_length: Math.round(длинаМ * 100) / 100,
    total_weight: Math.round(кг * 100) / 100,
    total_weight_tons: Math.round(кг) / 1000,
    weight_per_meter: кгМ,
    pieces: штуки,
    piece_length: длинаШтуки,
  };
}

/**
 * Лист: вес одного листа (кг) из базы/формулы, дальше — по единице заявки.
 * Возвращает объект в формате calc() плюс поле _лист для красивого вывода.
 */
function посчитайЛист(position, размер) {
  // Считаем геометрией, а не по базе калькулятора: записи листов в базе
  // непоследовательны (для одних размеров вес листа, для других — кг/м).
  const [т, ш, д] = размер.split("x").map(Number);
  if (!(т > 0 && ш > 0 && д > 0)) return null;
  const кгОдного = Math.round(((т * ш * д * 7.85) / 1e6) * 100) / 100;
  if (!(кгОдного > 0)) return null;
  const кол = Number(position.количество);
  if (!(кол > 0)) return null;

  let штуки;
  if (position.единица === "шт") штуки = кол;
  else if (position.единица === "т") штуки = Math.round((кол * 1000) / кгОдного);
  else if (position.единица === "кг") штуки = Math.round(кол / кгОдного);
  else return null; // «метры» для листа не имеют смысла

  // для т/кг оставляем заявленный вес, для шт — штуки × вес листа
  const всегоКг = position.единица === "шт" ? штуки * кгОдного
    : position.единица === "т" ? кол * 1000 : кол;
  return {
    total_weight: Math.round(всегоКг * 100) / 100,
    total_weight_tons: Math.round(всегоКг) / 1000,
    weight_per_meter: кгОдного,
    pieces: штуки,
    piece_length: д / 1000,
    total_length: null,
    _лист: { кгОдного, штуки, толщина: т, ширина: ш, длина: д },
  };
}

/**
 * Считает вес/длину/штуки по позиции заявки. Возвращает результат
 * calc() из MetalCalc (плюс поле _предположениеПоДлине, если длину
 * хлыста пришлось брать по умолчанию, а не из заявки), либо null,
 * если не смогли определить тип/размер.
 */
function посчитайПоЗаявке(position) {
  const типИРазмер = определиТипИРазмер(position);
  if (!типИРазмер) return null;

  // Лист: «вес на метр» в базе — это вес ЦЕЛОГО листа, а не кг/м. Поэтому
  // считаем отдельно: штуки × вес листа; хлыст 6 м к листу не применяется.
  if (типИРазмер.type === "sheet") return посчитайЛист(position, типИРазмер.size);

  // ВГП: вес метра считаем по наружному диаметру из ГОСТ 3262 (ДУ20×2,8 → 1,66 кг/м);
  // в базе калькулятора для ВГП были заниженные значения.
  if (типИРазмер.type === "pipe_vgp" && НАРУЖНЫЙ_ДИАМЕТР_ВГП[типИРазмер._ду] && типИРазмер._стенка > 0) {
    const D = НАРУЖНЫЙ_ДИАМЕТР_ВГП[типИРазмер._ду];
    const кгМ = Math.round((D - типИРазмер._стенка) * типИРазмер._стенка * 0.02466 * 1000) / 1000;
    if (кгМ > 0) return посчитайПоВесуМетра(position, кгМ);
  }

  const calc = получиКалькулятор();
  const params = { type: типИРазмер.type, size: типИРазмер.size };
  let предположениеПоДлине = false;

  let тоннКГ = null; // т/кг считаем сами: calc() гадает «<100 — тонны, иначе кг», и 150 т становились 150 кг
  if (position.единица === "т" || position.единица === "кг") {
    тоннКГ = position.единица === "т" ? position.количество * 1000 : position.количество; // в кг
    params.length = 1; // нужен только вес метра
  } else if (position.единица === "м") {
    params.length = position.количество;
  } else if (position.единица === "шт") {
    // Штуки → метры → тонны. Нужна длина ОДНОЙ штуки (хлыста) — берём
    // из заявки, если указана явно (параметры.длина, в мм), иначе —
    // стандартные 6м по умолчанию (см. константу выше), с явной пометкой.
    params.pieces = position.количество;
    if (position.параметры?.длина != null) {
      params.pieceLength = position.параметры.длина / 1000; // мм → м
    } else {
      params.pieceLength = ДЛИНА_ХЛЫСТА_ПО_УМОЛЧАНИЮ_ММ / 1000;
      предположениеПоДлине = true;
    }
  } else {
    return null;
  }

  let результат = calc.calc(params);
  if (тоннКГ != null && !результат.error) {
    const сКГ = посчитайПоВесуМетра({ ...position, единица: "кг", количество: тоннКГ }, результат.weight_per_meter);
    if (!сКГ) return null;
    результат = { ...результат, ...сКГ };
    delete результат.remaining_length;
  } else if (результат.error) {
    // Калькулятор не нашёл размер (например, гнутый швеллер 50х40х3) — пробуем
    // вес метра по формуле/геометрии (весМетраКг) и считаем сами.
    const кгМ = весМетраКг(типИРазмер.type, типИРазмер.size);
    if (!(кгМ > 0)) return null;
    результат = посчитайПоВесуМетра(position, кгМ);
    if (!результат) return null;
  }
  // calc() округляет тонны до 2 знаков — для малых партий это грубо; берём из кг, 3 знака
  if (результат.total_weight != null) результат.total_weight_tons = Math.round(результат.total_weight) / 1000;
  if (предположениеПоДлине) {
    результат._предположениеПоДлине = `${ДЛИНА_ХЛЫСТА_ПО_УМОЛЧАНИЮ_ММ / 1000}м (в заявке длина хлыста не указана — взято по умолчанию, не факт из заявки)`;
  }
  return результат;
}

/**
 * Вес 1 погонного метра (кг) по типу/размеру: база → формула калькулятора →
 * геометрия гнутого швеллера. null — если нигде не нашли.
 * Для листа это вес метра полосы шириной «ширина» (см. _calcFormulaWeight).
 */
function весМетраКг(тип, размер) {
  const calc = получиКалькулятор();
  const профиль = calc._findProfile(тип, размер);
  if (профиль) return профиль.weight_per_meter;
  const поФормуле = calc._calcFormulaWeight(тип, размер, 7.85);
  if (поФормуле != null) return поФормуле;
  if (тип === "channel") {
    // Гнутый швеллер h×b×t: сечение ≈ t·(h + 2·(b − t)), без радиусов
    // скругления (занижение порядка 1–3%).
    const ч = calc._normalizeSize(размер).split("x").map(Number);
    if (ч.length === 3 && ч.every((x) => x > 0)) {
      const [h, b, t] = ч;
      const площадь = t * (h + 2 * (b - t));
      return Math.round(((площадь * 7.85) / 1000) * 1000) / 1000;
    }
  }
  return null;
}

/**
 * Готовит количество для передачи в addToCart/addToCartKTZ, когда
 * позиция в заявке указана ШТУКАМИ. В отличие от посчитайПоЗаявке()
 * выше (которая для штук без явной длины берёт 6м "по умолчанию") —
 * здесь длина берётся из УЖЕ НАЙДЕННОГО на сайте товара (точная, не
 * предположение). Вызывать ПОСЛЕ поиска, но ДО добавления в корзину.
 *
 * @param {object} position - позиция заявки (как от parseOrder)
 * @param {object} найденное - для КТЗ: вариант из ktz/index.js
 *        (несёт _ктзТовар с весТонн/length_numeric); для mc.ru:
 *        вариант из search.js (несёт длина — строка в мм, например "6000")
 * @param {"mc.ru"|"ktz"} источник
 * @returns {{quantity: number, unit: string, _источникДлины: string}|null}
 *          null — если не смогли посчитать (тип/размер не определён,
 *          длина неизвестна даже у найденного товара — например "н/д"
 *          у mc.ru), тогда вызывающий код должен решить сам, что делать
 *          (спросить у менеджера, отказаться и т.п.) — не подставляем
 *          предположение молча, раз выбрали "надёжный" вариант.
 */
function подготовьКоличествоДляКорзины(position, найденное, источник) {
  // Килограммы: сайты принимают тонны (поле «Тонны»), а «150 кг» уходило туда как 150 (т!).
  if (position.единица === "кг") {
    const т = Math.max(0.001, Math.round(Number(position.количество)) / 1000);
    return { quantity: т, unit: "т", _источникДлины: `${position.количество} кг → ${т} т` };
  }
  if (position.единица !== "шт") {
    // Уже в т/м — конвертация не нужна, отдаём как есть
    return { quantity: position.количество, unit: position.единица, _источникДлины: null };
  }

  const штуки = position.количество;

  // Длина штуки по данным найденного товара (мм) — для КТЗ и mc.ru разный источник
  let длинаМм = null;
  let весТоннНаМетр = null; // только КТЗ: готовое значение с сайта
  let метка = "";
  if (источник === "ktz") {
    const товар = найденное._ктзТовар || найденное;
    if (товар.length_numeric != null) длинаМм = Number(товар.length_numeric);
    if (товар.весТонн != null) весТоннНаМетр = Number(товар.весТонн);
    метка = "найденный товар на КТЗ";
  } else if (источник === "mc.ru") {
    длинаМм = parseInt(найденное.длина, 10);
    метка = "найденный товар на mc.ru";
  } else {
    return null;
  }
  if (!Number.isFinite(длинаМм)) длинаМм = null;

  const типИРазмер = определиТипИРазмер(position);

  // Лист: у листа «длина» — это длина листа из размера заявки, если на
  // сайте длина не указана или не число (н/д)
  if (длинаМм == null && типИРазмер && типИРазмер.type === "sheet") {
    const длинаЛиста = parseFloat(типИРазмер.size.split("x")[2]);
    if (Number.isFinite(длинаЛиста) && длинаЛиста > 0) {
      длинаМм = длинаЛиста;
      метка = "длина листа из заявки";
    }
  }
  if (длинаМм == null) return null; // длина неизвестна — не считаем вслепую

  // 0) Лист КТЗ: весТонн — вес ОДНОГО ЛИСТА (т), а не тонн на метр (см. normalize.js).
  //    Раньше здесь для листов применялась формула «на метр» — получались заниженные в
  //    разы тонны (ПВЛ 6 шт → 0,002 т). Дополнительно проверяем вес на правдоподобность:
  //    не больше сплошной стальной плиты и не меньше 5% от неё — иначе данные КТЗ
  //    сомнительные, и бот не гадает, а просит указать тонны.
  if (источник === "ktz") {
    const товар = найденное._ктзТовар || найденное;
    if (товар.category_type === "Лист" && товар.весТонн != null) {
      const вес1 = Number(товар.весТонн);
      const т = Number(товар.thickness_numeric);
      const a = Number(товар.side_a_numeric);
      const b = Number(товар.side_b_numeric);
      if (т > 0 && a > 0 && b > 0) {
        const сплошной = (т * a * b * 7.85) / 1e9; // мм³ × 7.85 г/см³ → т
        if (!(вес1 >= сплошной * 0.05 && вес1 <= сплошной * 1.08)) return null;
      }
      const тонны = штуки * вес1;
      if (!(тонны > 0)) return null;
      return {
        quantity: Math.round(тонны * 1000) / 1000,
        unit: "т",
        _источникДлины: `лист КТЗ, вес листа ${вес1} т × ${штуки} шт`,
      };
    }
  }

  // 1) КТЗ отдал вес метра — самый точный источник
  if (источник === "ktz" && весТоннНаМетр != null) {
    const тонны = штуки * (длинаМм / 1000) * весТоннНаМетр;
    return {
      quantity: Math.round(тонны * 1000) / 1000,
      unit: "т",
      _источникДлины: `${метка}, ${длинаМм}мм (точно)`,
    };
  }

  // 2) Иначе — вес метра из базы/формулы калькулятора по заявке
  if (!типИРазмер) return null;
  // Лист: вес листа — геометрией (толщина × ширина × длина листа), не через «вес метра»
  if (типИРазмер.type === "sheet") {
    const [т, ш] = типИРазмер.size.split("x").map(Number);
    const тонны = (штуки * т * ш * длинаМм * 7.85) / 1e9;
    if (!(тонны > 0)) return null;
    return {
      quantity: Math.round(тонны * 1000) / 1000,
      unit: "т",
      _источникДлины: `${метка}, лист ${т}×${ш}×${длинаМм} мм × ${штуки} шт`,
    };
  }
  const кгНаМетр = весМетраКг(типИРазмер.type, типИРазмер.size);
  if (кгНаМетр == null) return null;
  const тонны = (штуки * (длинаМм / 1000) * кгНаМетр) / 1000;
  if (!(тонны > 0)) return null;
  return {
    quantity: Math.round(тонны * 1000) / 1000,
    unit: "т",
    _источникДлины: `${метка}, ${длинаМм}мм; вес метра ${кгНаМетр} кг (${типИРазмер.type} ${типИРазмер.size})`,
  };
}

