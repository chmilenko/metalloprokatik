/**
 * utils/orderFilter.js
 *
 * Быстрая проверка «похоже ли сообщение на заявку на металлопрокат» — ДО вызова
 * LLM. Приветствия, вопросы вроде «когда будет готово?» и прочий разговорный текст
 * иначе уходили в разбор заявки и тратили деньги, а менеджер получал странный ответ.
 *
 * Фильтр намеренно мягкий: пропускает всё, где есть хоть одна цифра И название
 * проката, размер («89х3.5») или количество с единицей («2 т», «300 м»). Отсекает
 * только то, где нет цифр или нет ни одного признака. Лучше пропустить лишнее, чем потерять настоящую заявку.
 *
 * Отключить целиком: ФИЛЬТР_ЗАЯВОК=off в .env.
 */

// Корни слов проката (поиск по вхождению в нижнем регистре)
const КОРНИ_ПРОКАТА = [
  'лист', 'труб', 'круг', 'арматур', 'швеллер', 'балк', 'двутавр', 'уголок', 'углов',
  'полос', 'квадрат', 'шестигранник', 'катанк', 'пвл', 'вгп', 'профнастил', 'проволок',
  'сетк', 'лента', 'ленты', 'рифл', 'оцинк', 'нержав', 'тавр', 'прокат', 'заготовк',
  'пруток', 'прутк', 'штрипс', 'рельс', 'шпунт', 'анкер', 'метиз', 'болт', 'гайк',
  'профиль', 'профил', 'отвод', 'переход', 'фланец', 'заглушк', 'тройник',
  'г/к', 'х/к', 'гк ', 'хк ', 'горячекат', 'холоднокат', 'ст3', 'ст20', 'ст45', '09г2с',
];

// Размер вида 89х3.5, 60*60*3, 1250 х 2500 (рус. «х», лат. x, звёздочка, ×)
const РАЗМЕР = /\d\s*[xх*×]\s*\d/i;
// Количество с единицей: «2 т», «300м», «10 шт», «1,5 тонны», «500 кг»
const КОЛИЧЕСТВО = /\d\s*(?:т|тн|тонн\p{L}*|кг|м|метр\p{L}*|шт|штук\p{L}*)(?![\p{L}])/iu;

function похожеНаЗаявку(текст) {
  if (process.env.ФИЛЬТР_ЗАЯВОК === 'off') return true;
  const т = String(текст || '').toLowerCase().trim();
  if (!т) return false;
  // Любая реальная позиция содержит число (размер, марку, количество). «труба нах» или
  // «нужен лист» без цифр искать бессмысленно — это не заявка.
  if (!/\d/.test(т)) return false;
  if (КОРНИ_ПРОКАТА.some((к) => т.includes(к))) return true;
  if (РАЗМЕР.test(т)) return true;
  // Одно количество без названия («1т», «100 м, 12 шт») — искать нечего: нужен хотя бы
  // один посторонний «словесный» кусок
  if (КОЛИЧЕСТВО.test(т)) {
    const остаток = т.replace(new RegExp(КОЛИЧЕСТВО.source, 'giu'), ' ');
    return /\p{L}{3,}/u.test(остаток);
  }
  return false;
}

const ПОДСКАЗКА =
  '🤔 Не вижу в сообщении позиций с размером или количеством.\n\n' +
  'Напишите заявку списком, например:\n' +
  'Труба 89х3.5 - 2т\n' +
  'Лист г/к 4х1500х3000 - 10 шт\n\n' +
  'Список команд — /help';

module.exports = { похожеНаЗаявку, ПОДСКАЗКА };