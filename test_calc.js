let ошибок = 0, всего = 0;
const итог = (ок, текст) => { всего++; if (!ок) ошибок++; console.log(`${ок ? 'OK  ' : 'FAIL'} ${текст}`); };
const безопасно = (f) => { try { return f(); } catch (e) { console.log('   исключение:', e.message); return undefined; } };

console.log('=== Расчёт веса ===');
for (const [имя, поз, ожид, допуск] of расчёт) {
  const р = безопасно(() => посчитайПоЗаявке(поз));
  const т = р && р.total_weight != null ? р.total_weight / 1000 : null;
  const откл = т != null ? Math.abs(т - ожид) / ожид * 100 : null;
  итог(откл != null && откл <= допуск,
    `${имя}: ожидаем ${ожид.toFixed(3)} т, получили ${т == null ? 'null' : т.toFixed(3)} т` + (откл != null ? ` (откл. ${откл.toFixed(2)}%, допуск ${допуск}%)` : ''));
}

console.log('\n=== Должны вернуть null ===');
for (const [имя, поз] of неСчитается) {
  const р = безопасно(() => посчитайПоЗаявке(поз));
  итог(р === null, `${имя}: ${р === null ? 'null' : 'посчитал ' + JSON.stringify(р).slice(0, 80)}`);
}

console.log('\n=== Количество для корзины (шт/кг → т) ===');
for (const [имя, поз, найд, ист, ожид, допуск] of корзина) {
  const р = безопасно(() => подготовьКоличествоДляКорзины(поз, найд, ист));
  if (ожид === null) { итог(р == null, `${имя}: ${р == null ? 'null' : JSON.stringify(р)}`); continue; }
  const q = р ? р.quantity : null;
  const откл = q != null ? Math.abs(q - ожид) / ожид * 100 : null;
  итог(откл != null && откл <= (допуск ?? 1), `${имя}: ожидаем ${ожид.toFixed(3)}, получили ${q == null ? 'null' : q} ${р ? р.unit : ''}`);
}

